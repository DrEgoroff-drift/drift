/* лодка на месте cv/em: br — дыхание лампы (как CHEB_LAMP*br у выпечки) */
function bodyCheburek(x,y,a,s,wx,wy,br){
  if(!bodyGpu())return false;
  const m=bodyChebMesh(),sc=s*(18/(m.R||18));
  if((m.len||36)*sc<BODY.LOD){bodyDot(x,y,[74,58,46],wx,wy,1);return true;}
  if(!bodyRun(m,x,y,a,sc,wx,wy,.3))return false;
  bodyLights(m,x,y,a,sc,br==null?1:br);return true;
}
