/* ══════════════ возможность ══════════════

   Позвоночник главного квеста (`docs/DESIGN-quest.md`, орган A; книга —
   `docs/saga/КНИГА.md` §5).

   Мир этой игры **не выдаёт кредиты. Он выдаёт доступ**: место в рейсе, имя,
   которое можно назвать, маршрут, который никто не работает, бокс в чужом
   гараже. Всегда с лицом. Всегда с окном, которое закроется молча.

   ── Почему это вообще построено так, а не квестами ──

   Дуга книги поворачивает ровно одну ценность: **назван или не назван** — то
   есть скажет ли кто-нибудь твой позывной вслух. В книге читатель это видит,
   потому что проза показывает. В игре журнала заданий нет, маркеров нет,
   полосы репутации нет и не будет — и поэтому ценность рискует быть невидимой
   вообще ничем (`docs/saga/СУД.md`, проход I).

   Отсюда единственное правило, ради которого весь модуль:

       ИМЕННОЕ ПРЕДЛОЖЕНИЕ ЗАМЕТНО ВЫГОДНЕЕ ХОЛОДНОГО.

   Не на проценты — в разы. Тогда закрытая дверь чувствуется кошельком и
   списком возможностей, без единой строки интерфейса. Игрок никогда не
   прочтёт слов «репутация» и «мораль». Он заметит, что раньше ему предлагали
   хорошее, а теперь предлагают обычное.

   ── Чего здесь нет и не будет ──

   Ни журнала заданий, ни маркера на карте, ни счётчика до срока, ни
   напоминаний. Возможность приходит так же, как в этой игре приходит всё
   остальное — строкой в эфире, очередью у стойки, письмом на столе, — и,
   если её не взять, истекает молча. В книге списки экспедиции закрываются в
   пятницу, и никто герою об этом не говорит. */

/* Виды. `ru` — то, что игрок прочтёт; `note` — вторая строка; `k` — во сколько
   раз именное выгоднее холодного в своей валюте (деньги, время, доступ). */
/* Суммы держатся ниже полного трюма нарочно (`docs/DESIGN-economy.md`): полный
   трюм на сорок единиц даёт под восемьсот, и возможность не должна его
   заменять. Именное плечо — это «полтрюма за услугу», холодное — карманные.
   Первый заход с шестьюстами в кармане не должен превращаться в тысячу. */
const OFFER_KIND={
  run:   {ru:"место в рейсе",        note:"второй пилот сошёл",          pay:[45,120]},
  route: {ru:"плечо, которое никто не работает", note:"покажут, если довезёшь", pay:[0,0]},
  bay:   {ru:"бокс в чужом гараже",  note:"обслуживание своими руками",  pay:[0,0]},
  topic: {ru:"тема института",       note:"нужен человек, который не спутает ленту", pay:[80,200]},
  word:  {ru:"имя, которое можно назвать", note:"скажете, что от меня",  pay:[0,0]},
  haul:  {ru:"груз с узла",          note:"постоянный, если не подведёте", pay:[60,150]}
};
/* Во сколько раз именное щедрее холодного. Три — это «в разы», а не «на
   проценты»: разницу обязано быть видно с первого взгляда на две строки
   рядом. */
const OFFER_NAMED_K=3;
/* Сколько живёт окно, в игровых минутах. Короткое нарочно: цена промаха — не
   штраф, а просто закрывшаяся дверь. */
const OFFER_TTL=[40,180];

function offersAll(){
  if(!Array.isArray(G.offers))G.offers=[];
  return G.offers;
}
/* Память людей. У каждого лица два состояния и ничего больше: помнит хорошо
   (`good`) и назвал ли когда-нибудь (`named`). Цифр нет — цифра превратилась
   бы в полосу репутации, а её мы не заводим. */
function folkAll(){
  if(!G.folk||typeof G.folk!=="object")G.folk={};
  return G.folk;
}
function folkOf(id){
  const F=folkAll();
  if(!F[id])F[id]={good:1,named:0,shut:0};
  return F[id];
}
/* ── дверь закрывается тихо и навсегда ──
   Ни сообщения, ни записи в журнал, ни звука. Человек продолжает здороваться
   так же тепло; именных предложений от него больше не будет никогда. Это
   единственное необратимое в игре, и необратимость — единственное, что даёт
   происходящему вес (`СУД`, проход XVIII). */
function folkShut(id){
  const f=folkOf(id);
  f.good=0;f.shut=1;
}
function offerPay(o){
  const K=OFFER_KIND[o.kind];if(!K)return 0;
  const lo=K.pay[0],hi=K.pay[1];
  if(hi<=0)return 0;
  const base=lo+Math.floor(rng(o.seed||1)()*(hi-lo));
  return o.named?Math.round(base*OFFER_NAMED_K):base;
}
/* Заведение возможности. `who` — идентификатор лица; `named` ставится только
   тогда, когда этот человек помнит игрока хорошо. */
function offerAdd(kind,who,named){
  if(!OFFER_KIND[kind])return null;
  const f=folkOf(who);
  const nm=!!named&&!!f.good;
  const seed=hashi(Math.floor(G.t*7),offersAll().length,0x0FFE)>>>0;
  const ttl=OFFER_TTL[0]+Math.floor(rng(seed)()*(OFFER_TTL[1]-OFFER_TTL[0]));
  const o={id:seed,kind,who,named:nm?1:0,sx:G.sx,sy:G.sy,
           t0:G.t,ttl,seed,taken:0};
  offersAll().push(o);
  if(nm)f.named=1;
  return o;
}
/* ── что предлагают на этой станции сегодня ──
   Заводится при стыковке и живёт своё окно. Лицо здесь одно на место — тот,
   кто стоит за стойкой; когда появятся четверо друзей (`docs/saga/ЖИВЫЕ.md`),
   у них будут свои лица и свои предложения.
   Заново при каждой стыковке не сыплем: если тут уже что-то висит, значит,
   висит. */
function offerVisit(){
  if(!G.sys||!G.sys.station)return;
  if(offerHere().length)return;
  const who="st:"+G.sys.key;
  const f=folkOf(who);
  /* ── один набор на место за смену ──
     Без этого станции превращаются в кран: улетел, вернулся — новые
     предложения, и так пока не надоест. Смена держится своим часом, и пока
     она не сменилась, здесь предлагают ровно то, что уже предложили, — даже
     если игрок это упустил. Упустил — значит упустил. */
  const shift=Math.floor(G.t/240);
  if(f.shift===shift)return;
  f.shift=shift;
  const r=rng(hashi(G.sx,G.sy,shift)>>>0);
  const kinds=["run","haul","topic","route","bay","word"];
  const n=1+Math.floor(r()*2);
  for(let i=0;i<n;i++){
    const kind=kinds[Math.floor(r()*kinds.length)];
    /* Именное приходит только от того, кто помнит хорошо, и не каждый раз:
       иначе «вам» перестанет что-нибудь значить. */
    offerAdd(kind,who,f.good&&r()<.45);
  }
}
function offerLive(){
  const t=G.t;
  return offersAll().filter(o=>!o.taken&&t-o.t0<o.ttl);
}
function offerHere(){
  return offerLive().filter(o=>o.sx===G.sx&&o.sy===G.sy);
}
/* ── истечение: молча ──
   Просроченная возможность просто исчезает. Если она была ИМЕННОЙ — человек,
   назвавший твой позывной, закрывает дверь. Он не обижается вслух и не
   перестаёт здороваться; он перестаёт называть.
   Холодную упустить ничего не стоит: её никто за тебя не просил. */
function offerTick(){
  const L=offersAll();
  if(!L.length)return;
  const t=G.t;
  for(let i=L.length-1;i>=0;i--){
    const o=L[i];
    if(o.taken){L.splice(i,1);continue;}
    if(t-o.t0<o.ttl)continue;
    if(o.named)folkShut(o.who);
    L.splice(i,1);
  }
  while(L.length>24)L.shift();
}
/* Взятие. Плата — доступом или деньгами, смотря по виду; именное платит втрое.
   Взятая именная возможность подтверждает память человека, а не улучшает её:
   цифр нет, улучшать нечего. */
function offerTake(o){
  if(!o||o.taken)return 0;
  o.taken=1;
  const pay=offerPay(o);
  /* деньги идут одной воронкой: `earn` (12j) считает оборот дома, и мимо неё
     доход в этой игре не заводится — за этим следит отдельный сторож */
  if(pay>0&&typeof earn==="function")earn(pay,"возможность");
  return pay;
}
/* Строка для доски и для эфира. Разница между именным и холодным должна быть
   слышна словами, а не только цифрой: холодное объявляют всем, именное
   называет тебя. */
function offerLine(o){
  const K=OFFER_KIND[o.kind];
  const pay=offerPay(o);
  return (o.named?"вам":"кто рядом")+" · "+K.ru+(pay>0?" · "+pay+" кр":"");
}
