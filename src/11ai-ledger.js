/* ══════════════ тетрадь, которой никто не ведёт ══════════════

   Всё, что игрок сделал даром и без свидетелей. Её НЕ ВИДНО НИГДЕ: ни вкладки,
   ни строки, ни подтверждения, ни звука. Игрок не должен узнать, что она есть,
   иначе она мгновенно превращается в подсчёт очков и перестаёт работать
   (`docs/saga/КНИГА.md` §5, `docs/DESIGN-quest.md` орган C).

   Она нужна ради финала: подарок в конце приходит не за заслуги, а за то, чего
   никто не считал, — и, если тетрадь завести поздно, платить будет нечем.
   Поэтому она пишется с самого начала игры, задолго до того, как появится
   первая сцена, которая её прочтёт.

   Три сторожа, без которых замысел разваливается:

   1. **Не показывать.** Ни здесь, ни где-либо ещё. `91zzzf-ledger` следит.
   2. **Поступок обязан стоить в момент совершения.** Даровое добро — не добро,
      а кнопка. Поэтому `deedAdd` принимает ЦЕНУ и без неё ничего не пишет.
   3. **Расчётливая доброта весит меньше.** Помог, когда самому нечем, — это
      одно; помог с полным трюмом и полным кошельком — другое. Вес считается по
      тому, чего у игрока было в ту минуту, а не по размеру поступка. */

/* Виды поступков. Плоская таблица, как все таблицы проекта. `ru` тут не для
   показа — тетрадь не показывают, — а чтобы правка через полгода понимала, о
   чём строка. */
const DEEDS={
  mark:   {ru:"оставил груз у знака чужому"},
  rescue: {ru:"снял людей с гибнущего борта"},
  feed:   {ru:"довёз посёлку сверх того, что окупается"},
  paid:   {ru:"заплатил вернувшемуся пустым"},
  pupil:  {ru:"взял стажёра"},
  letter: {ru:"довёз чужое письмо"},
  winter: {ru:"остался на зимовку"},
  spare:  {ru:"отдал место тому, кому нужнее"},
  mercy:  {ru:"не добил"}
};
function ledgerAll(){
  if(!G.ledger||typeof G.ledger!=="object")G.ledger={n:0,w:0};
  return G.ledger;
}
/* ── вес по бедности ──
   Ноль кредитов и пустой трюм — вес полный. Богатому тот же поступок пишется
   вчетверо мельче. Порог намеренно низкий: «богат» в этой игре начинается
   гораздо раньше, чем игроку кажется. */
function ledgerNeed(){
  const st=(typeof stat==="function")?stat():null;
  const cr=clamp((G.credits|0)/4000,0,1);
  const hold=(st&&st.cargoMax)?clamp(held()/st.cargoMax,0,1):0;
  return clamp(1-(cr*.7+hold*.3),.25,1);
}
/* Запись. `cost` — во что поступок обошёлся В МОМЕНТ СОВЕРШЕНИЯ, в условных
   единицах: кредиты, топливо, часы, закрытое окно. Без цены запись не идёт —
   это и есть второй сторож, вшитый в подпись функции. */
function deedAdd(kind,cost){
  if(!DEEDS[kind])return 0;
  cost=+cost||0;
  if(cost<=0)return 0;
  const L=ledgerAll();
  const w=cost*ledgerNeed();
  L.n=(L.n|0)+1;
  L.w=+((L.w||0)+w).toFixed(3);
  /* Ни `say`, ни `logAdd`, ни звука. Здесь ничего не происходит для игрока, и
     это единственное место в игре, где молчание — не оформление, а механика. */
  return w;
}
