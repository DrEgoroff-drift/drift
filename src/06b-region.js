/* ══════════════ область: несколько систем на одну тему ══════════════
   Единица тринадцатого прохода — не планета и не система, а ОБЛАСТЬ: квадрат
   сектора со своим ядром где-то внутри. У области ровно один прибор, который в
   ней врёт (M122), и невязка, растущая к ядру плавно, через несколько систем.

   ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Не детектор и не квестовый маркер: область ничего не
   объявляет, нигде не подписана и не даёт наград. Она читается только по
   приборам — и только тем, кто на них смотрит.

   ПРАВИЛА ФАЙЛА:
   1. Всё считается от координат, ничего не хранится. Область — функция от
      сектора, как и система (правило «не персистить эфемерное»).
   2. Невязка монотонна: чем ближе к ядру, тем больше, без исключений. Она
      функция ОДНОГО расстояния — иначе по ней нельзя идти.
   3. Скачков не бывает. Между соседними секторами невязка меняется на малую
      величину: игрок должен чувствовать склон, а не порог.
   4. Прибор у области один. Два прибора — это уже не тема, а шум. */

const REGION_SPAN=4;               // сторона области в секторах
const REGION_R=3;                  // радиус склона: меньше области, чтобы у границы он сошёл
const REGION_SALT=0x2E610;
const REGION_A=["Тихий","Долгий","Слепой","Стеклянный","Медленный","Пустой",
  "Рыжий","Ветхий","Немой","Двойной"];
const REGION_B=["предел","косяк","затон","перекат","околоток","рукав","мыс",
  "порог","залив","край"];

function regionKey(sx,sy){
  return Math.floor(sx/REGION_SPAN)+","+Math.floor(sy/REGION_SPAN);
}
/* ── ядро ──
   Точка внутри области, к которой всё сходится. Она обязана быть живой:
   ядро в пустоте — это склон, ведущий в никуда. */
function regionCore(rx,ry,r){
  const bx=rx*REGION_SPAN,by=ry*REGION_SPAN;
  /* ядро сидит во ВНУТРЕННИХ клетках области, а не у самого её края. Иначе
     склон обрывается ровно на границе, и правило 3 нарушается там, где его
     легче всего не заметить: первый заход так и делал. */
  const wx=bx+1+Math.floor(r()*(REGION_SPAN-2)),wy=by+1+Math.floor(r()*(REGION_SPAN-2));
  if(starAt(wx,wy))return {sx:wx,sy:wy};
  /* ближайшая звезда области целиком: во внутренних клетках её может не быть
     вовсе, а ядро в пустоте — это склон, ведущий в никуда. Если ядро село у
     края, склон под него сузится сам — ширина считается в `regionAt` */
  let best=null,bd=1e9;
  for(let x=bx;x<bx+REGION_SPAN;x++)for(let y=by;y<by+REGION_SPAN;y++){
    if(!starAt(x,y))continue;
    const d=(x-wx)*(x-wx)+(y-wy)*(y-wy);
    if(d<bd){bd=d;best={sx:x,sy:y};}
  }
  return best||{sx:wx,sy:wy};
}
function regionAt(sx,sy){
  const rx=Math.floor(sx/REGION_SPAN),ry=Math.floor(sy/REGION_SPAN);
  const seed=hashi(rx,ry,REGION_SALT),r=rng(seed);
  const core=regionCore(rx,ry,r);
  /* имя есть, но нигде не показывается: оно для журнала и для того, чтобы
     область была вещью, а не индексом */
  const name=pick(REGION_A,r)+" "+pick(REGION_B,r);
  /* правило 4: прибор ровно один, и он от seed области */
  const needle=INSTR_KEYS[Math.floor(r()*INSTR_KEYS.length)];
  /* ── ширина склона ──
     Склон обязан сойти на нет ВНУТРИ области: иначе на границе, где начинается
     чужой склон с чужой крутизной, получается порог. Ширину задаёт само ядро —
     сколько ему осталось до края области, — а крутизна ей пропорциональна:
     узкий склон не может быть и крутым, иначе шаг между секторами станет
     обрывом. Первый заход этого не считал и давал скачок в полневязки. */
  const bx=rx*REGION_SPAN,by=ry*REGION_SPAN;
  const R0=Math.min(core.sx-bx,bx+REGION_SPAN-1-core.sx,
                    core.sy-by,by+REGION_SPAN-1-core.sy)+1;
  const slope=clamp(R0,1,REGION_R);
  const amp=(.45+r()*.45)*(slope/REGION_R);
  return {key:rx+","+ry,rx,ry,seed,name,core,needle,amp,slope,span:REGION_SPAN};
}
/* ── невязка ──
   Одно маленькое число: насколько расходятся пять способов узнать, где и когда
   вы находитесь. Правило 2 — функция расстояния до ядра, и только его. */
function misclose(sx,sy){
  /* склон линейный, и это не упрощение: степень больше единицы делает последний
     сектор перед ядром обрывом, а игрок должен идти по склону, а не падать в него */
  return +(regionAt(sx,sy).amp*regionDepth(sx,sy)).toFixed(4);
}
/* насколько глубоко в области вы находитесь: 0 за радиусом склона, 1 в ядре.
   Радиус меньше области, поэтому у границы склон уже почти сошёл на нет и
   переход в соседнюю область не даёт порога (правило 3). */
function regionDepth(sx,sy){
  const R=regionAt(sx,sy);
  const d=Math.hypot(sx-R.core.sx,sy-R.core.sy);
  return clamp(1-d/R.slope,0,1);
}
