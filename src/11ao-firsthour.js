/* ══════════════ первый час: сменщик в эфире ══════════════
   M207. Проход по свежему сохранению (docs/DESIGN-first-hour.md) показал одну
   вещь, которую в игре на сто вех легко не заметить изнутри: у новичка есть
   корабль, шестьсот кредитов, девять кнопок и НИ ОДНОГО СЛОВА о том, что
   скафандр и топливо кончаются. Обе шкалы нарисованы, обе молчат, и первый
   свой труп человек получает без предупреждения — не от трудности игры, а от
   того, что ему не сказали.

   ЭТО НЕ ОБУЧЕНИЕ. Ни стрелок, ни модальных окон, ни «нажмите сюда», ни флажка
   «пройти обучение» — всё это игра не умеет говорить и не должна научиться.
   Говорит то, что и так говорит: эфир. Диспетчер, который в этой игре
   комментирует всё подряд, в первые минуты роняет четыре строки, каждая — про
   одну вещь, которая иначе убьёт или наскучит. Сказал и забыл; повторять не
   будет, потому что живые люди не повторяют.

   ПОЧЕМУ ИМЕННО ЧЕТЫРЕ. Больше — это лекция. Меньше — не покрывает список из
   разбора: воздух, топливо, деньги, работа. Пятой строки («что такое данные»)
   в списке нет намеренно: без данных не умирают и не скучают.

   ПРАВИЛА ФАЙЛА:
   1. Ни одной строки от лица игры. Только от лица человека в эфире.
   2. Каждая строка говорится один раз за сохранение и по ПОВОДУ, а не по
      таймеру: про воздух — когда вышел на грунт, про топливо — когда полетел.
   3. Ничего не хранится, кроме того, что уже сказано. */
const FIRST_LINES=[
  {k:"air",  who:"диспетчер",
   t:"…борт, свежий? Тогда одно: на грунте вы дышите ранцем, и он не бесконечный. Кончится — возвращайтесь к кораблю, там пополните."},
  {k:"fuel", who:"диспетчер",
   t:"…и бак у вас на сто. Это десяток прыжков, не больше. Заправка на любой станции, деньги берут вперёд."},
  {k:"work", who:"стойка",
   t:"…работа всегда на доске, у стойки. Кто ищет — находит, кто не ищет — сидит без денег."},
  {k:"dig",  who:"старик у стойки",
   t:"…а если совсем пусто — копайте. Что под ногами лежит, то на станции и берут. Все с этого начинали."}
];
const FIRST_BY={};FIRST_LINES.forEach(l=>FIRST_BY[l.k]=l);
function firstAll(){if(!Array.isArray(G.first))G.first=[];return G.first;}
function firstSaid(k){return firstAll().indexOf(k)>=0;}
/* сказать один раз. Голос идёт тем же путём, что и всё остальное в эфире */
function firstSay(k){
  const L=FIRST_BY[k];
  if(!L||firstSaid(k))return false;
  firstAll().push(k);
  if(typeof consoleHeard==="function")consoleHeard(L.t,L.who);
  if(typeof logAdd==="function")logAdd("ether",L.who+": "+L.t);
  return true;
}
/* ── поводы ──
   Зовётся из кадра. Дёшево: четыре сравнения, и после того как всё сказано,
   первая же проверка выходит по длине списка. */
function firstTick(){
  if(!G.running)return;
  const F=firstAll();
  if(F.length>=FIRST_LINES.length)return;
  /* про воздух — когда впервые вышел на грунт и отошёл от корабля */
  if(G.mode==="surface"&&G.surf&&!firstSaid("air")){
    const d=Math.abs((G.surf.x||0)-(G.surf.shipX||0));
    if(d>180)firstSay("air");
  }
  /* про топливо — когда впервые потратил заметную его долю */
  if(!firstSaid("fuel")&&G.fuel<86)firstSay("fuel");
  /* про работу — при первой стыковке */
  if(G.mode==="dock"&&!firstSaid("work"))firstSay("work");
  /* про копать — когда впервые встал рядом с залежью и ничего не сделал */
  if(G.mode==="surface"&&G.surf&&!firstSaid("dig")&&G.credits<900){
    const D=G.surf.deposits||[];
    for(const dep of D)
      if(Math.abs(dep.x-(G.surf.x||0))<70){firstSay("dig");break;}
  }
}
