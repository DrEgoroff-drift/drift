/* ══════════════ лессировка: форма в сером, свет одним слоем (P4, M422) ══════════════
   Десятый закон ремесла из `docs/DESIGN-story-craft.md`, последний из десяти.
   До сих пор каждый рисовальщик грунта сам выбирал себе цвет из палитры мира:
   `pal` читали `drawGround`, `drawRocks`, `drawStrata`, материал и штрих. Свет
   и цвет лежали в одном мазке, и отсюда следовали три беды сразу:

     · смена палитры мира означала правку каждого рисовальщика;
     · СВЕТ НА БОЛЬШЕЙ ЧАСТИ КАДРА БЫЛ КОНСТАНТОЙ — `rgba(0,0,0,.35)` под
       валуном, `rgba(255,246,226,.16)` на контакте пластов, — а не светом
       этой звезды под этим небом. По-настоящему освещение считалось только
       для полос склона (`litRGB`), то есть для одной ленты из всего разреза;
     · час суток входил в ключ ломтя, потому что цвет пёкся вместе с формой.

   ГРИЗАЙЛЬ разводит это на два прохода. Форма печётся В СЕРОМ: рисовальщик
   кладёт только СВЕТЛОТУ — массу, рельеф, тень, кромку. Потом на весь ломоть
   разом ложится лессировка: серое v превращается в `тень + v·(свет − тень)`,
   где тень — цвет неба (`ambRGB`×`ambK`), а свет — цвет звезды (`starRGB`).

   ПОЧЕМУ ЭТО ТА ЖЕ ФИЗИКА, ЧТО БЫЛА. `litRGB` считает `base·(k·amb + I·sun)` —
   линейно по I. Значит двухточечная лессировка с `dark = base⊗amb·k` и
   `light = base⊗(amb·k + sun·df)` — это и есть `litRGB`, у которого ламбертов
   множитель взят из серого прохода, а не из наклона профиля. Никакой новой
   модели света: та же, но теперь она достаётся всему разрезу, а не ленте.

   ── ЧТО ЭТО МЕНЯЕТ В КАРТИНЕ, И ПОЧЕМУ РЕШАЛ АВТОР ──
   Грунт перестаёт брать оттенок от палитры мира и берёт его от СВЕТА:
   землеподобная планета уходит из оливковой в терракотовую под холодным
   дождливым небом. Прибор кадра на этом выигрывает — растёт пара тёплого и
   холодного, а это и был давний долг «грунт день: pair короткий, второй тон
   только у диска», — но мир теряет часть собственного лица. Первый заход
   07.09.2026 был построен, измерен и откачен именно потому, что это развилка
   замысла, а не вопрос кода; автор её снял: заливаем.

   Пробовали и третий проход, который должен был сохранить оба, — альбедо
   возвращалось режимом `color` поверх лессировки. Он восстанавливает палитру
   и УБИВАЕТ пару (10 → 1) на любой доле, то есть отменяет ровно то, ради чего
   закон написан. Не взят; замер лежит в `docs/DESIGN-craft.md` § P4.

   ── СЕРОЕ ЗНАЧИТ «ПОКРАСЬ МЕНЯ», ЦВЕТ ЗНАЧИТ «Я СВОЙ» ──
   Опись перед началом (её требовал план) нашла в пекле девять событий, у
   которых цвет НЕ выводится из палитры и не восстанавливается из светлоты:

     минеральные жилы в материале (`MINERAL`, восемь оттенков на мир);
     жилы и вкрапления внутри пласта;   собственный цвет пласта `L.col`;
     лавовый шов;                       ледяной шов;
     потёки окисла на плите;            искра на ребре кристалла и дисперсия;
     лишайник на валуне;                цвет полос склона — он-то и переезжает.

   Жила и кромка грани дают ОДНУ светлоту при разных тонах: свести их в один
   канал можно, разделить обратно нельзя. Поэтому события рисуются ПОСЛЕ
   лессировки, отдельным проходом (`GLAZE_PASS`), и под неё не попадают вовсе.

   ── ПОЧЕМУ КОМПОЗИТОМ, А НЕ ТАБЛИЦЕЙ ──
   План предлагал LUT через `getImageData`/`putImageData` раз на ломоть. Ломоть
   — 512×~1000, то есть полмиллиона точек на чтение и столько же на запись; и
   главное, чтение канвы роняет её в программный растр (правило про `prof()` в
   CLAUDE.md). Двухточечная лессировка выражается двумя заливками без единого
   чтения:

     multiply цветом (light − dark)   →   v·(light − dark)
     lighter  цветом dark             →   v·(light − dark) + dark

   Ровно линейная карта, ноль readback. Трёхточечную (тень → собственный тон →
   свет) она не даёт; собственный тон материала остаётся там, где он и был, —
   в самом тайле, серым, и его светлота и есть средняя точка. */

/* два конца лессировки для данного тела под данным небом.
   base — собственный тон материала из палитры; в гризайли ему соответствует
   белое, то есть полностью освещённая поверхность */
const GLAZE_FLOOR=.28;      /* сколько неба доходит до самого тёмного места */
function glazeStops(base,p,df){
  const sun=(typeof starRGB==="function")?starRGB():[255,244,214];
  const amb=(p&&typeof ambRGB==="function")?ambRGB(p):[70,90,130];
  const k=(p&&typeof ambK==="function")?ambK(p):.3;
  const d=(df===undefined)?(p&&typeof dayKq==="function"?(.40+.58*dayKq(p)):.78):df;
  /* ── пол тени приглушён (замер M422) ──
     `lighter` — это ПОЛ: всё, что в подмалёвке темнее некоторого порога,
     упирается в него и становится одним цветом. Разрез теряет глубину: чёрный
     градиент вниз (drawGround) превращался в ровную полосу цвета неба, и
     прибор кадра говорил «пусто» 45 → 59. Небо и правда светит в тень, но не
     в трещину и не на дно выработки — там оно перекрыто самой породой.
     Множитель ниже и есть эта перекрытость: тень остаётся ХОЛОДНОЙ (тон неба),
     но перестаёт быть СВЕТЛОЙ. */
  /* ── а НОЧЬЮ перекрывать нечем ──
     Пол выше писан против дневного пересвета: в трещину небо не достаёт,
     потому что его перекрывает порода, освещённая звездой. Ночью звезды нет,
     небо — единственный свет, и тот же множитель просто гасит грунт в чёрное:
     первый заход дал ночь, где земля вне фонаря пропадала вовсе (tones 6 → 4,
     а на кадре — чёрная пустота с одним светлым островом у скафандра). §16
     свода, «экспонировать по теням», говорит ровно обратное. Поэтому пол ходит
     вместе с днём: в полдень .28, в полночь 1, и небо доходит до дна. */
  const dq=(p&&typeof dayKq==="function")?clamp(dayKq(p),0,1):1;
  const fl=GLAZE_FLOOR+(1-GLAZE_FLOOR)*(1-dq);
  const dark=[0,1,2].map(i=>clamp(base[i]*(k*amb[i]/255)*fl,0,255));
  const light=[0,1,2].map(i=>clamp(base[i]*(k*amb[i]/255+d*sun[i]/255),0,255));
  return {dark,light};
}
/* серый той же светлоты, что и цвет: рисовальщик, который раньше брал тон из
   палитры, теперь берёт из неё же светлоту — и разница между слоями остаётся
   там, где ей место, в тоне, а не в оттенке */
function lum3(c){return c[0]*.30+c[1]*.59+c[2]*.11;}
function greyOf(c,mul){
  const v=clamp(lum3(c)*(mul===undefined?1:mul),0,255)|0;
  return "rgb("+v+","+v+","+v+")";
}
function greyA(v,a){
  const q=clamp(v,0,255)|0;
  return "rgba("+q+","+q+","+q+","+a+")";
}
/* ── подмалёвок пишут КОНТРАСТНЕЕ готового ──
   Правило старой лессировки, и оно же измеряется прибором: два залива
   сжимают шкалу — тень поднимается на `dark`, свет упирается в `light`.
   Гризайль, написанная «в натуральную светлоту», после лессировки читается
   плоской: первый заход дал «пусто» 41 → 50 при том, что пара выросла 7 → 10.
   Растягиваем вокруг середины ровно настолько, насколько потом сожмёт. */
const GREY_K=1.62;
/* пласты разводятся сильнее общего: у них не осталось оттенка, чтобы
   отличаться, — значит вся разница обязана лечь в тон (18b) */
const STRATA_K=2.2, STRATA_STEP=16;
function greyStretch(v){return clamp(128+(v-128)*GREY_K,0,255);}
/* ── два прохода одного рисовальщика ──
   `form` — серое, ложится под лессировку; `hue` — события со своим оттенком,
   ложатся после неё. Флаг глобальный по той же причине, что и `GROUND_BAKING`:
   рисовальщиков много, и передавать проход через все подписи дороже, чем
   прочесть его в трёх местах. */
let GLAZE_PASS="";
function glazeIsForm(){return GLAZE_PASS!=="hue";}
function glazeIsHue(){return GLAZE_PASS!=="form";}
/* ── лессировка целого ломтя ──
   Композитные операции считаются и там, где холст ПРОЗРАЧЕН: `multiply` по
   пустому месту кладёт сам цвет, `lighter` подсыпает тень в небо. Поэтому
   исходная альфа снимается копией и возвращается в конце `destination-in` —
   два drawImage на ломоть, ни одного чтения пикселей. */
let GLAZE_MASK=null;
function glazeChunk(stops){
  const cn=ctx.canvas;
  if(!cn||!cn.width)return;
  if(!GLAZE_MASK)GLAZE_MASK=document.createElement("canvas");
  if(GLAZE_MASK.width!==cn.width||GLAZE_MASK.height!==cn.height){
    GLAZE_MASK.width=cn.width;GLAZE_MASK.height=cn.height;
  }
  const m=GLAZE_MASK.getContext("2d");
  m.setTransform(1,0,0,1,0,0);
  m.clearRect(0,0,GLAZE_MASK.width,GLAZE_MASK.height);
  m.drawImage(cn,0,0);
  const dr=stops.dark,lt=stops.light;
  const rgb=c=>"rgb("+Math.round(clamp(c[0],0,255))+","+
    Math.round(clamp(c[1],0,255))+","+Math.round(clamp(c[2],0,255))+")";
  ctx.save();
  ctx.setTransform(1,0,0,1,0,0);
  ctx.globalCompositeOperation="multiply";
  ctx.fillStyle=rgb([lt[0]-dr[0],lt[1]-dr[1],lt[2]-dr[2]]);
  ctx.fillRect(0,0,cn.width,cn.height);
  ctx.globalCompositeOperation="lighter";
  ctx.fillStyle=rgb(dr);
  ctx.fillRect(0,0,cn.width,cn.height);
  ctx.globalCompositeOperation="destination-in";
  ctx.drawImage(GLAZE_MASK,0,0);
  ctx.restore();
}
/* лессировка грунта: верх шкалы серого прохода — верхняя ступень палитры,
   именно по ней нормирован материал (18a), и именно она означает
   «полностью освещено» */
function glazeGround(tr,camx,camy,pal){
  if(!pal||!tr||!tr.mat)return;
  glazeChunk(glazeStops(pal[pal.length-1],tr.p));
}
