/* ══════════════ ляпнул лишнего ══════════════

   Третий просёр из `docs/saga/ДУГА.md` §5, и самый интересный из трёх.

   Слухи в этой игре (`11t`) текут в одну сторону: игрок только СЛЫШИТ. Здесь он
   становится источником. Он рассказывает у стойки, где взял хорошее, — и через
   несколько дней туда приходит баржа.

   ── Почему это не наказание ──

   Книга и приговор (`docs/saga/СУД.md`) требуют одного: **игра никогда не
   заставляет его оступиться**. Рассказать — выбор, и выбор в ту минуту хороший:
   человека, который делится, слушают, и слушают охотно. Плата приходит потом и
   всегда по человеческой линии, никогда по мировой.

   Что он получает СРАЗУ и по-настоящему: тот, кто за стойкой, запоминает его
   тёплым, а значит следующее предложение придёт **именное** (11ah), то есть
   втрое дороже. Это не подачка — это ровно та валюта, на которой стоит вся дуга.

   Что он теряет ПОТОМ: залежь на том месте вырабатывают без него. Ни строки
   упрёка, ни разбора: просто в эфире однажды проходит, что там работает баржа,
   и «кто-то навёл». Прилетев, он найдёт бедное место.

   ── Устройство ──

   Залежи не персистятся — они выводятся из сида посадки. Поэтому «выработано»
   живёт разрежённым оверлеем по месту, как велит правило проекта, а не на самой
   залежи, которой к тому времени уже не существует. */

/* Через сколько суток мира туда доходит баржа. Три — чтобы игрок успел улететь
   и забыть, но не успел решить, что связи нет. */
const TOLD_LAG=3;

function toldAll(){return (G.told||(G.told=[]));}
function toldKey(sx,sy,pi){return sx+","+sy+"#"+(pi|0);}
function toldOf(sx,sy,pi){
  const k=toldKey(sx,sy,pi);
  return toldAll().find(t=>t.k===k)||null;
}
/* Место уже выработали? Не в момент рассказа — через несколько дней. */
function toldWorked(sx,sy,pi){
  const t=toldOf(sx,sy,pi);
  if(!t)return false;
  return (typeof celDay==="function"?celDay():0)-t.d>=TOLD_LAG;
}
/* ── что вообще есть рассказать ──
   Только то, что он взял сам и своими руками, и только если взял заметно.
   Пустая болтовня ничего не стоит и ничего не покупает. */
function toldWorth(){
  const L=G.lastDig;
  if(!L||L.n<6)return null;
  if(toldOf(L.sx,L.sy,L.pi))return null;      // про это место уже рассказано
  return L;
}
/* ── рассказал ──
   Никакого подтверждения о будущем. Одна реплика, и человек запомнил его
   тёплым: следующее предложение придёт именным. */
function toldDo(){
  const L=toldWorth();
  if(!L)return false;
  toldAll().push({k:toldKey(L.sx,L.sy,L.pi),sx:L.sx,sy:L.sy,pi:L.pi,
                  res:L.res,d:(typeof celDay==="function"?celDay():0),said:0});
  while(toldAll().length>24)toldAll().shift();
  /* тот, кто за стойкой, слушал и запомнил (11ah) */
  if(G.sys&&typeof folkOf==="function"){
    const f=folkOf("st:"+G.sys.key);
    if(f.good)f.warm=1;
  }
  if(typeof tell==="function")
    tell("","Рассказал, где брали "+RES[L.res].ru.toLowerCase(),
         "— Вот как.\nНу, спасибо.");
  G.lastDig=null;
  return true;
}
/* ── и однажды это возвращается ──
   Одна строка в эфире, чужим голосом, без имени игрока. Больше не повторяется.
   Зовётся редким фоновым тактом, как всё ленивое в этой игре. */
function toldEther(){
  const day=(typeof celDay==="function"?celDay():0);
  for(const t of toldAll()){
    if(t.said||day-t.d<TOLD_LAG)continue;
    t.said=1;
    if(typeof etherLine==="function")
      etherLine("…там, где брали "+RES[t.res].ru.toLowerCase()+
                ", работает баржа. Кто-то навёл.");
    return true;
  }
  return false;
}
