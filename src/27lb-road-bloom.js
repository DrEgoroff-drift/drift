/* ══════════════ дорожный спутник: поле света ══════════════
   Сияние «моей волны» — не композиция мягких пятен, а ПОЛЕ: свет считается на
   каждый пиксель, и оттого он течёт, а не дышит целыми кляксами.

   G12 (25.09): поле переехало на видеокарту. Прежде это был тот же рецепт на
   ImageData — 88 точек по ширине, 26 Гц, растянутые на экран вшестеро, — и
   весь бюджет кадра уходил на цикл по пикселям в JS (замер M168k: 2 мс после
   трёх мер экономии, 17.9 до них). Теперь это gpuField: формула на КАЖДЫЙ
   пиксель экрана и на каждый кадр, три октавы вместо двух, и ничего не
   растягивается. Что стало лучше, кроме цены:
   - жгуты резкие по краю и мягкие внутри — прежде растяжение размывало всё
     одинаково, и свет читался туманом с ступенькой 26 Гц на быстром басе;
   - в самой густой части поле светит выше единицы, и свечение кадра (08b)
     даёт ему настоящий ореол — у сияния появился источник;
   - шум не растягивается вслед за экраном: на альбомном экране жгуты больше
     не лежат плоскими блинами (поправка на пропорции ниже);
   - цвет смешивается по кругу ПОПИКСЕЛЬНО, без таблицы на 64 ступени — полос
     на плавном переходе тона нет.

   Что внутри — по рецепту, слово в слово:
   - ДОМЕН-ВАРП: `fbm` внутри `fbm`. Один шум даёт облака, шум, сдвинувший
     координаты второго, даёт ТЯГУЧЕСТЬ — жгуты, которые сворачиваются и
     перетекают. Без варпа поле выглядит туманом, с варпом — жидкостью.
   - ВРЕМЯ идёт всегда (`RD.flow`), поэтому на паузе и без микрофона свет живёт.
   - ЦВЕТ — замкнутая петля по пяти тонам палитры (`ROAD_BLOOM_H` вокруг тона
     настроения). Петля закрыта нарочно: произвольная дуга по кругу протащила
     бы палитру через зелень, а мы этот урок уже выучили (M168k, `roadMoodHue`).
   - СПЕКТР входит в поле по X: высота света над каждой точкой кромки — своя
     полоса `RD.wave`. Эквалайзер не нарисован полосками, он растворён в свете.
   - ПОЛОСЫ: бас гонит течение (в `RD.flow`) и поднимает поле, верх кладёт
     быструю мелкую рябь, серёдка добавляет плотности.
   - НИТЬ по самой кромке (прежде отдельный градиент в 27l): держит нижний край
     светящимся даже в полной тишине. Теперь она — часть того же поля. */
const ROAD_FLD_TOP=.57;                   /* выше этой доли экрана света нет вовсе */
const ROAD_FLD_WGSL=`
fn rbH(p:vec2f)->f32{var q=fract(vec3f(p.xyx)*.1031);q=q+dot(q,q.yzx+33.33);return fract((q.x+q.y)*q.z);}
fn rbN(p:vec2f)->f32{let i=floor(p);let f=fract(p);let w=f*f*(3.-2.*f);
  return mix(mix(rbH(i),rbH(i+vec2f(1.,0.)),w.x),mix(rbH(i+vec2f(0.,1.)),rbH(i+vec2f(1.,1.)),w.x),w.y);}
/* три октавы, нормированы в 0..1, как fbm2 у 2D: пороги рецепта остались прежними */
fn rbF(p:vec2f,s:f32)->f32{
  var v=0.;var a=.5;var f=1.;var n=0.;
  for(var i=0;i<3;i++){v+=a*rbN(p*f+vec2f(s*17.1+f32(i)*31.7,s*9.3-f32(i)*13.9));n+=a;a*=.5;f*=2.;}
  return v/n;}
fn rbHsl(h0:f32,s:f32,l:f32)->vec3f{
  let h=pmod(h0,360.)/360.;
  let q=select(l+s-l*s,l*(1.+s),l<.5);let p=2.*l-q;
  var o=vec3f(0.);
  for(var k=0;k<3;k++){
    var x=h+(1./3.)-f32(k)/3.;x=x-floor(x);
    var c=p;
    if(x<1./6.){c=p+(q-p)*6.*x;}else if(x<.5){c=q;}else if(x<2./3.){c=p+(q-p)*(2./3.-x)*6.;}
    o[k]=c;}
  return o;}
/* тон — угол: смешивается по короткой дуге (roadHueMix) */
fn rbMix(a:f32,b:f32,k:f32)->f32{let d=pmod(b-a+540.,360.)-180.;return a+d*k;}
fn rbHue(i:i32)->f32{if(i<4){return fu.v[0][i];}return fu.v[1].x;}
fn rbWave(i:i32)->f32{return fu.v[4+i/4][i%4];}
fn field(p:vec2f,uv:vec2f)->vec4f{
  let top=fu.v[2].y;let v=uv.y;
  /* нить по кромке: ровный свет тона настроения в нижних gh экрана */
  let gh=fu.v[2].z;
  var col=vec3f(0.);
  if(v>1.-gh){let k=(v-(1.-gh))/gh;col=rbHsl(fu.v[3].x,.92,.53)*k*fu.v[2].w;}
  if(v<top){return vec4f(col,0.);}
  let u=uv.x;let fl=fu.v[1].y;
  var vt=(v-top)/(1.-top);vt=vt*vt*(3.-2.*vt);vt=vt*(.34+.66*vt);
  /* спектр по ширине: между соседними полосами — плавно */
  let sp0=u*27.;let si=i32(floor(sp0));let sf=sp0-f32(si);
  let sp=mix(rbWave(si),rbWave(min(27,si+1)),sf);
  /* поправка на пропорции: рецепт настраивался на портретном телефоне (≈0.46),
     на широком экране жгуты растягивались вслед за ним */
  let ax=u*sqrt(max(1.,fu.v[3].z/.46));
  let q=rbF(vec2f(ax*1.9,v*1.25-fl),0.);
  let n=rbF(vec2f(ax*2.6+q*1.2,v*.95-fl*1.15+q*1.05),1.);
  let lift=vt*(.42+sp*1.15);
  /* квадрат вместо линейного: яркие жгуты и тёмные промежутки, а не ровный туман */
  let s2=n*n*2.30-.48+fu.v[2].x*.50;
  var a=lift*fu.v[1].z*max(s2,0.);
  /* рябь от верхов — быстрая и мелкая, только по краю света */
  a=a*(1.+fu.v[1].w*sin(u*41.+fl*8.5)*(1.-vt));
  /* густое светит выше единицы: плечо кадра (08b) его сожмёт, свечение даст ореол */
  a=clamp(a,0.,1.)+max(a-.85,0.)*.9;
  /* цвет ведёт сам варп — пятна тона текут вместе со светом; место по ширине
     только подмешивается */
  let ci=fract(q*.85+u*.20+n*.10)*5.;let k=i32(floor(ci));let f=ci-f32(k);
  let h=rbMix(rbHue(k%5),rbHue((k+1)%5),f);
  col=col+rbHsl(h,.96,.54)*a;
  return vec4f(col,0.);}`;
const ROAD_FLD_U=new Float32Array(44);
/* сияние и нить кромки — одним полем, сложением света поверх всего, что уже в кадре */
function roadBloom(pass,W,H,hue,en,bd){
  if(!pass)return;
  const U=ROAD_FLD_U;
  for(let i=0;i<5;i++)U[i]=hue+ROAD_BLOOM_H[i];
  U[5]=RD.flow||0;
  U[6]=.50+en*.72+RD.beat*.18;            /* усиление */
  U[7]=bd.tre*.30;                         /* рябь */
  U[8]=.30+bd.mid*.55;                     /* плотность */
  U[9]=ROAD_FLD_TOP;
  U[10]=.030+en*.030+bd.bass*.025;         /* высота нити кромки, доля экрана */
  U[11]=.07+en*.08+bd.bass*.06+RD.beat*.06;
  U[12]=hue;U[13]=0;U[14]=W/Math.max(1,H);U[15]=0;
  for(let i=0;i<28;i++)U[16+i]=RD.wave[i]||0;
  gpuField(pass,"road.bloom",ROAD_FLD_WGSL,U,null,{blend:"add"});
}
