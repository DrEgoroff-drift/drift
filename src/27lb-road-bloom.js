/* ══════════════ дорожный спутник: поле света ══════════════
   Сияние «моей волны» — не композиция мягких пятен, а ПОЛЕ: свет считается на
   каждый пиксель, и оттого он течёт, а не дышит целыми кляксами.

   Это тот самый фрагментный шейдер из рецепта, только на ImageData. Поле
   считается в маленькой канве (около ста двадцати пикселей по ширине) и
   растягивается на экран билинейно — растяжение и есть размытие, ровно то,
   что от сияния и нужно. Полкадра сверху не считается вовсе: света там нет.

   Что внутри — по рецепту, слово в слово:
   - ДОМЕН-ВАРП: `fbm2` внутри `fbm2`. Один шум даёт облака, шум, сдвинувший
     координаты второго, даёт ТЯГУЧЕСТЬ — жгуты, которые сворачиваются и
     перетекают. Без варпа поле выглядит туманом, с варпом — жидкостью.
   - ВРЕМЯ идёт всегда (`RD.flow`), поэтому на паузе и без микрофона свет живёт.
   - ЦВЕТ берётся из таблицы на 64 ступени, замкнутой петлёй по пяти тонам
     палитры (`ROAD_BLOOM_H` вокруг тона настроения). Петля закрыта нарочно:
     произвольная дуга по кругу протащила бы палитру через зелень, а мы этот
     урок уже выучили (M168k, `roadMoodHue`).
   - СПЕКТР входит в поле по X: высота света над каждой точкой кромки — своя
     полоса `RD.wave`. Эквалайзер не нарисован полосками, он растворён в свете.
   - ПОЛОСЫ: бас гонит течение (в `RD.flow`) и поднимает поле, верх кладёт
     быструю мелкую рябь, серёдка добавляет плотности.

   Автор снял ограничение по батарее для этого режима — «всё равно телефон на
   зарядке», — и весь бюджет ушёл сюда. Сколько именно — ниже, замерено. */
/* ── чего это стоит и почему столько ──
   Первый замер: 17.9 мс на кадр из 16.7 доступных — поле съедало 95% времени и
   не оставляло ничего ни корпусу, ни ленте. «Батарея не важна» не значит
   «кадр не важен»: тридцать герц в держателе видно сразу. Три меры, каждая
   ничего не отнимает у картинки:
   1. ДВЕ ОКТАВЫ вместо трёх. Третья идёт на учетверённой частоте и весит
      седьмую часть — после растяжения поля вшестеро она лежит внутри пикселя.
   2. ПОЛЕ УЖЕ: 88 точек по ширине вместо 124. Растяжение и есть размытие,
      разницы на экране нет, а точек вдвое меньше.
   3. ПОЛЕ ЖИВЁТ НА СВОЕЙ ЧАСТОТЕ, 26 Гц. Течение медленное (флоу за секунду
      проходит десятую шума), поэтому лишние кадры считать нечего: между
      пересчётами кладётся та же картинка. Кадр при этом остаётся 60 Гц —
      двигаются корпус, лента, звёзды и числа.
   Итого около 2 мс. */
const ROAD_FLD_W=88;                      /* целевая ширина поля, пикселей */
const ROAD_FLD_TOP=.57;                   /* выше этой доли экрана света нет вовсе */
const ROAD_FLD_HZ=26;                     /* с какой частотой поле пересчитывается */
const ROAD_FLD_OCT=2;                     /* октав шума: третья после растяжения не видна */
const ROAD_LUT=64;                        /* ступеней в таблице цвета */

/* hsl→rgb: нужен ровно для таблицы, 64 раза в кадр, поэтому короткий */
function roadHsl(h,s,l,out,at){
  h=((h%360)+360)%360/360;
  const q=l<.5?l*(1+s):l+s-l*s,p=2*l-q;
  const f=k=>{
    let x=h+k;if(x<0)x+=1;if(x>1)x-=1;
    return 255*(x<1/6?p+(q-p)*6*x:x<.5?q:x<2/3?p+(q-p)*(2/3-x)*6:p);
  };
  out[at]=f(1/3);out[at+1]=f(0);out[at+2]=f(-1/3);
}
/* таблица кадра: замкнутая петля по пяти тонам палитры вокруг настроения */
function roadBloomLut(lut,hue){
  const n=ROAD_BLOOM_H.length;
  for(let i=0;i<ROAD_LUT;i++){
    const p=i/ROAD_LUT*n, k=Math.floor(p), f=p-k;
    const a=hue+ROAD_BLOOM_H[k%n], b=hue+ROAD_BLOOM_H[(k+1)%n];
    roadHsl(roadHueMix(a,b,f),.96,.54,lut,i*3);
  }
}
function roadBloom(c,W,H,t,dt,hue,en,bd){
  const S=RD.fld||(RD.fld={});
  const div=Math.max(3,Math.round(W/ROAD_FLD_W));
  const fw=Math.max(24,Math.round(W/div)),fh=Math.max(24,Math.round(H/div));
  if(!S.cv||S.cv.width!==fw||S.cv.height!==fh){
    S.cv=document.createElement("canvas");S.cv.width=fw;S.cv.height=fh;
    S.cx=S.cv.getContext("2d");
    S.img=S.cx.createImageData(fw,fh);
    S.lut=new Uint8ClampedArray(ROAD_LUT*3);
    S.t0=-9;
  }
  /* поле пересчитывается на своей частоте; между пересчётами кладётся то же */
  if(t-S.t0<1/ROAD_FLD_HZ){
    c.save();
    c.globalCompositeOperation="lighter";
    c.imageSmoothingEnabled=true;
    if("imageSmoothingQuality" in c)c.imageSmoothingQuality="high";
    c.drawImage(S.cv,0,0,fw,fh,0,0,W,H);
    c.restore();
    return;
  }
  S.t0=t;
  roadBloomLut(S.lut,hue);
  const lut=S.lut,d=S.img.data,fl=RD.flow||0;
  const y0=Math.floor(fh*ROAD_FLD_TOP);
  d.fill(0,0,y0*fw*4);
  const gain=.50+en*.72+RD.beat*.18;
  const rip=bd.tre*.30;
  const dens=.30+bd.mid*.55;
  const W28=RD.wave;
  for(let y=y0;y<fh;y++){
    const v=(y+.5)/fh;
    let vt=(v-ROAD_FLD_TOP)/(1-ROAD_FLD_TOP);
    vt=vt*vt*(3-2*vt);                    /* smoothstep: край поля мягкий */
    vt*=.34+.66*vt;                       /* и подтянут к кромке: вверху только отсвет */
    let o=y*fw*4;
    for(let x=0;x<fw;x++,o+=4){
      const u=(x+.5)/fw;
      /* спектр по ширине: между соседними полосами — плавно */
      const sp0=u*27,si=Math.floor(sp0),sf=sp0-si;
      const sp=W28[si]*(1-sf)+W28[Math.min(27,si+1)]*sf;
      /* домен-варп: первый шум сдвигает координаты второго. Частоты низкие
         нарочно — поле растягивается на экран вшестеро, и мелкий шум на нём
         читается мрамором, а не светом (проход самокритики M168k) */
      const q=fbm2(u*1.9,v*1.25-fl,0x7A10,ROAD_FLD_OCT);
      const n=fbm2(u*2.6+q*1.2,v*.95-fl*1.15+q*1.05,0x7A11,ROAD_FLD_OCT);
      /* высота света над этой точкой кромки — своя полоса спектра */
      const lift=vt*(.42+sp*1.15);
      /* квадрат вместо линейного: у света должны быть яркие жгуты и тёмные
         промежутки, иначе поле выглядит ровным туманом */
      const s2=n*n*2.30-.48+dens*.50;
      let a=lift*gain*(s2>0?s2:0);
      if(a<=.004){d[o]=0;d[o+1]=0;d[o+2]=0;d[o+3]=0;continue;}
      /* рябь от верхов — быстрая и мелкая, только по краю света */
      if(rip>.001)a*=1+rip*Math.sin(u*41+fl*8.5)*(1-vt);
      if(a>1)a=1;
      /* цвет ведёт САМ ВАРП — низкочастотный, поэтому получаются пятна тона,
         которые текут вместе со светом. Место по ширине только подмешивается.
         Ни то ни другое не должно тащить индекс через всю таблицу быстро: от
         этого выходит радужный мрамор, а не свет (обе крайности пройдены) */
      let ci=((q*.85+u*.20+n*.10)%1);
      if(ci<0)ci+=1;
      const li=((ci*ROAD_LUT)|0)*3;
      d[o]=lut[li]*a;d[o+1]=lut[li+1]*a;d[o+2]=lut[li+2]*a;d[o+3]=255;
    }
  }
  S.cx.putImageData(S.img,0,0);
  c.save();
  c.globalCompositeOperation="lighter";
  c.imageSmoothingEnabled=true;
  if("imageSmoothingQuality" in c)c.imageSmoothingQuality="high";
  c.drawImage(S.cv,0,0,fw,fh,0,0,W,H);
  c.restore();
}
