/* Пригасить краску до доли от эталонной по СВЕТЛОТЕ: тон остаётся, светлота
   уходит под потолок. Нужна там, где цвет собран из воздуха, а потолок задаёт
   звезда (§13 «один свет», §16). */
function capLum(c,ref,k){
  const L=v=>.299*v[0]+.587*v[1]+.114*v[2];
  const cl=L(c), lim=L(ref)*k;
  if(cl<=lim||cl<=0)return c;
  return c.map(v=>v*lim/cl);
}
const CLOUD_SPR=6;        // столько силуэтов пекётся на планету
/* Размер спрайта — это ПРЕДЕЛ РЕЗКОСТИ ближнего яруса, а не только память.
   При CSW=224 и масштабе 1.95 крупное облако растягивалось вдвое, и вся
   работа шума по кромке размазывалась: в кадре оно читалось гладким комком,
   тогда как дальние, нарисованные почти пиксель в пиксель, держали клочья.
   Поэтому спрайт крупнее, а ближний ярус мельче — растяжение ушло с 1.95 до
   1.55, детали стало вдвое больше на ту же экранную ширину (M355). */
const CSW=288, CSH=168;   // размер спрайта кучевого

/* ── спрайт кучевого облака ──
   Тело — сумма метаболов, посаженных на одну линию: отсюда плоский низ и
   бугристый верх. Шум не смещает кромку, а съедает её: плотность умножается
   на шумовое поле, и порог режет уже изъеденное — так получаются клочья,
   а не волна. */
function cloudSprite(p,seed,soft){
  const cn=document.createElement("canvas");cn.width=CSW;cn.height=CSH;
  const c=cn.getContext("2d"),img=c.createImageData(CSW,CSH),d=img.data;
  const r=rng(seed>>>0);
  const sun=starRGB(), amb=p.T.sky[1];
  const base=CSH*.80;                       // линия конденсации: низ всех тел
  const blobs=[];
  /* ── тело в два ряда, а не в одну нитку (M355) ──
     Прежняя раскладка сажала тела на одну линию и сужала их к концам
     (`1-|u-.5|*.9`): низ выгибался вверх по краям, и облако читалось
     косточкой или круассаном — как раз то, чего не бывает. У кучевого
     основание ШИРОКОЕ и ровное, оно и есть самая тяжёлая часть, а вертикаль
     стоит башнями НАД серединой основания. Отсюда два ряда: ряд лежит низом
     на линии конденсации во всю ширину, башни растут из середины ряда. */
  const nb=4+Math.floor(r()*3);
  /* ── шаг МЕНЬШЕ радиуса, иначе метаболы читаются бусами ──
     Тела сливаются только пока расстояние между центрами меньше примерно
     полутора радиусов: дальше поле между ними проваливается под порог, и с
     резкой кромкой (выше) каждый шар обводится собственным кружком — облако
     выходит гусеницей из бусин. Поэтому шаг считается ОТ радиусов соседей,
     а не от заданной ширины: сначала размеры, потом расстановка. */
  const rads=[];
  for(let i=0;i<nb;i++){
    const u=(i+.5)/nb;
    rads.push((CSH*.21)*(.66+r()*.60)*(1-Math.abs(u-.5)*.50));
  }
  const xs=[];let ax=0;
  for(let i=0;i<nb;i++){
    if(i)ax+=(rads[i-1]+rads[i])*.5*.86;
    xs.push(ax);
  }
  const x0=CSW*.5-ax*.5+(r()-.5)*CSW*.07;
  for(let i=0;i<nb;i++)
    blobs.push({x:x0+xs[i],y:base-rads[i]*(.74+r()*.30),r:Math.max(10,rads[i])});
  /* башни держатся за своё тело: смещение меньше радиуса основания, свой
     радиус не меньше двух третей — башня прирастает, а не висит рядом */
  const nt=1+Math.floor(r()*3);
  for(let i=0;i<nt;i++){
    const b=blobs[1+Math.floor(r()*Math.max(1,nb-2))];
    blobs.push({x:b.x+(r()-.5)*b.r*.70,y:b.y-b.r*(.52+r()*.42),r:b.r*(.64+r()*.28)});
  }
  const fld=new Float32Array(CSW*CSH);
  for(let y=0;y<CSH;y++)for(let x=0;x<CSW;x++){
    let v=0;
    for(const b of blobs){
      const dx=x-b.x,dy=(y-b.y)*1.12,q=1-(dx*dx+dy*dy)/(b.r*b.r);
      if(q>0)v+=q*q;
    }
    /* ниже линии конденсации облако не растёт — отсюда плоский низ */
    if(y>base)v*=Math.max(0,1-(y-base)/(CSH*.13));
    /* эрозия в два масштаба: крупный рвёт силуэт, мелкий даёт клочья */
    const e=fbm2(x*.018,y*.018,seed+11,4)*.72+fbm2(x*.07,y*.07,seed+29,3)*.28;
    fld[y*CSW+x]=v*(1-soft)+v*e*soft*2.1;
  }
  /* ── освещённая сторона облака темнее светила (M330) ──
     Было `lerp(255,…)`: облако мешалось с чистой белой и на планете с плотной
     атмосферой выходило ЯРЧЕ солнечного диска — измерено 0.85 против 0.79
     (набор «свет: самое яркое место неба»). Глаз читает самое светлое как
     источник, то есть в кадре появлялось второе солнце, а тени при этом
     лежали от первого: §13 «один свет» ломался ровно там, где света больше
     всего. Верхняя точка облака теперь на ступень ниже диска — оно осталось
     белым облаком, но перестало спорить с тем, что его освещает.

     Второй предел — по самой звезде: под тусклым красным светилом белое
     облако было бы ярче своего источника, а освещённое ярче света не бывает
     (§13, §16). Поэтому белая основа не поднимается выше яркости звезды —
     под красной звездой облака тёмно-рыжие, под белой белые. Сторож —
     набор «свет: облако не ярче своей звезды» (91zzzzy-light). */
  const sunL=.299*sun[0]+.587*sun[1]+.114*sun[2];
  const litC=[0,1,2].map(j=>lerp(Math.min(212,sunL),sun[j],.16));
  /* ── и ТЕНЬ не бывает светлее света (продолжение того же закона) ──
     Теневая сторона замешивается из воздуха планеты, а воздух живёт своей
     жизнью: под тусклой серой звездой при ярком небе он оказывался СВЕТЛЕЕ
     освещённой стороны — облако выходило вывернутым наизнанку, тёмным
     сверху и светлым снизу, и в кадре стояло вторым солнцем ярче настоящего.
     Поймано набором «в кадре ничто не спорит со звездой за источник»: пятно
     0.668 при диске 0.454. Гасим по светлоте, а не по каналам, — иначе
     вместе с яркостью уедет и тон. */
  /* ── ТЕЛО не доходит до полного света, до него доходит только КАЁМКА ──
     Предел M330 держит краску: облако не ярче своей звезды. Но кадр судит не
     по краске, а по площади — диск мал, облако велико, и когда всё тело стоит
     вровень со звездой, источником глаз читает облако (набор «в кадре ничто
     не спорит со звездой за источник»: пятно 0.597 против 0.440 у диска).
     Разводим: тело добирает до .80 от полного света, каёмка — до полного.
     Это и правда: поверхность облака рассеивает свет, а не отражает его весь. */
  const bodyC=capLum(litC,litC,.80);
  const shRaw=[0,1,2].map(j=>lerp(lerp(210,amb[j],.72),amb[j],.5)*.86);
  /* Потолок тени — чуть больше половины света: у настоящего кучевого теневая
     сторона примерно вдвое темнее освещённой, и именно этот разрыв даёт объём
     (§12 «сначала светлоты»). Без потолка тень и свет стояли вплотную: облако
     читалось плоским светлым пятном во весь размах — и оно же выигрывало у
     звезды спор за самое светлое место в кадре (0.590 против 0.442 у диска,
     набор «ничто не спорит со звездой»; слой найден пробой по слоям — перья
     и полог кадр не поднимали вовсе, поднимали кучевые). */
  const shC=capLum(shRaw,litC,.45);
  const F=(x,y)=>(x<0||y<0||x>=CSW||y>=CSH)?0:fld[y*CSW+x];
  for(let y=0;y<CSH;y++)for(let x=0;x<CSW;x++){
    const o=(y*CSW+x)*4, v=fld[y*CSW+x];
    /* ── кромка режется, а не размывается ──
       Полоса перехода была шириной .42 по плотности — на спрайте это десятки
       пикселей мягкой размывки, и вся работа шума пропадала внутри неё:
       облако выходило гладким комком ваты. Настоящая кромка кучевого резкая
       (потому оно и читается силуэтом), а мягкое у него — только клочья по
       краю, и они получаются сами, из изъеденной плотности. */
    let a=(v-.57)/.20;
    if(a<=0){d[o+3]=0;continue;}
    a=clamp(a,0,1);a=a*a*(3-2*a);
    /* нормаль по градиенту плотности: этого хватает, чтобы купол выглядел
       объёмным, а нижние клочья тёмными */
    const gx=F(x+3,y)-F(x-3,y), gy=F(x,y+3)-F(x,y-3);
    const gl=Math.hypot(gx,gy)||1;
    let lit=clamp(.5-(gx/gl*SUN_DIR.x+gy/gl*SUN_DIR.y)*.72,0,1);
    /* высота внутри тела: верх светлее низа даже в тени. Без этого облако
       выглядит комком ваты с равномерной подсветкой */
    const h=clamp((base-y)/(CSH*.62),0,1);
    /* ── объём берётся из ТЕЛА, а не с кромки (§13 «тело — обвод — один свет») ──
       Свет по градиенту плотности живёт только у края: в середине облака
       градиента нет вовсе, и вся внутренность выходила ОДНОЙ краской — на
       небе стояло плоское пятно с чуть тёмным низом. Считаем, сколько тела
       лежит между точкой и светилом: за четырьмя ступенями к солнцу — тень,
       у солнечной стороны — свет. Это и есть объём, и стоит он четырёх
       выборок готового поля. */
    let occ=0;
    for(let k=1;k<=4;k++){
      const s=k*CSH*.085;
      if(F(Math.round(x+SUN_DIR.x*s),Math.round(y+SUN_DIR.y*s))>.62)occ+=.25;
    }
    lit=clamp(lit*.34+h*.30+(1-occ)*.46-.10,0,1);
    /* серебряная каёмка: тонкая кромка со стороны светила. Считается по
       альфе, а не по свету, — именно край, а не склон */
    const rim=clamp(1-Math.abs(a-.45)*4.5,0,1)*
      clamp(-(gx/gl*SUN_DIR.x+gy/gl*SUN_DIR.y),0,1);
    /* ── каёмка поднимает до ПОЛНОГО света, а не за него (§13, закон M330) ──
       Прибавка `+rim*70` шла поверх litC, то есть поверх предела «не ярче
       своей звезды»: кромка выходила ярче солнечного диска. Раньше это
       пряталось — каёмка была в один-два пикселя и терялась в средней по
       квадрату, — а с крупным спрайтом стала видна, и набор «в кадре ничто
       не спорит со звездой за источник» поймал её первым же кадром. Каёмка
       по-прежнему читается: тело почти нигде не освещено до конца. */
    const R=[0,1,2].map(j=>clamp(lerp(lerp(shC[j],bodyC[j],lit),litC[j],rim*.85),0,255));
    d[o]=R[0];d[o+1]=R[1];d[o+2]=R[2];
    /* кромка полупрозрачна, ядро плотно: у облака нет резкой границы, но
       есть плотное тело — иначе оно читается вырезанной бумагой */
    d[o+3]=clamp(a*(.62+.38*clamp(v-.6,0,1))*255,0,255);
  }
  c.putImageData(img,0,0);
  return cn;
}
/* ── перистые ──
   Другое явление и рисуется иначе: не тело, а полосы льда, вытянутые ветром.
   Метаболы тут не нужны — нужен растянутый шум с уклоном. */
function cirrusSprite(p,seed){
  const W2=320,H2=64;
  const cn=document.createElement("canvas");cn.width=W2;cn.height=H2;
  const c=cn.getContext("2d"),img=c.createImageData(W2,H2),d=img.data;
  const sun=starRGB();
  /* тот же предел, что у кучевых (M330): перо не бывает ярче своей звезды */
  const sunL=.299*sun[0]+.587*sun[1]+.114*sun[2];
  const col=[0,1,2].map(j=>lerp(Math.min(224,sunL),sun[j],.12));
  for(let y=0;y<H2;y++)for(let x=0;x<W2;x++){
    const o=(y*W2+x)*4;
    /* волокно: шум, растянутый по x, с наклоном — перо, а не полоса */
    const yy=y+x*.06;
    const f=fbm2(x*.006,yy*.075,seed,4);
    const band=Math.pow(Math.sin(Math.PI*clamp(y/H2,0,1)),1.4);
    let a=(f-.52)/.30*band;
    if(a<=0){d[o+3]=0;continue;}
    a=clamp(a,0,1);
    d[o]=col[0];d[o+1]=col[1];d[o+2]=col[2];
    d[o+3]=clamp(a*a*168,0,255);
  }
  c.putImageData(img,0,0);
  return cn;
}
/* ── полог ──
   Третья форма неба, и без неё небо было одноэтажным. На фотографии ясного
   дня (автор, 05.09.2026) видно ровно три яруса разом: перья наверху, тёмный
   ПОЛОГ, занимающий верхнюю треть кадра, и внизу, у горизонта, цепочка мелких
   светлых кучевых. Между ними — синева. У нас были перья и кучевые, а полога
   не было, поэтому небо читалось пустым скатом с наклейками.

   Полог — не облако и рисуется не как тело: над головой он проходит почти
   ребром, силуэта у него нет вовсе, есть НИЖНЯЯ КРОМКА, изъеденная в клочья,
   и масса, уходящая за верх кадра. Отсюда всё устройство спрайта:
   — волокно вытянуто по горизонту (шум сжат по x, растянут по y);
   — порог растёт книзу, поэтому вверху сплошная масса, внизу лохмотья;
   — низ красит не звезда, а воздух: до нижней стороны прямой свет не доходит,
     она тёмная и холодная — это и есть противовес светлым кучевым (§12);
   — тонкое просвечивает: там, где массы мало, полог теплеет к цвету светила,
     и по рваной кромке идёт та же серебряная каёмка, что у кучевого;
   — по краям спрайта альфа сходит на нет, поэтому полотнища кладутся внахлёст
     без шва и сами собой рвутся на куски, как на фотографии.

   Один спрайт на планету, в кадре два-три drawImage. */
const DW=576, DH=208;
function deckSprite(p,seed){
  const cn=document.createElement("canvas");cn.width=DW;cn.height=DH;
  const c=cn.getContext("2d"),img=c.createImageData(DW,DH),d=img.data;
  const sun=starRGB(), amb=p.T.sky[1];
  const sunL=.299*sun[0]+.587*sun[1]+.114*sun[2];
  /* тот же предел, что у кучевых (M330): просвет полога не ярче своей звезды */
  const litC=[0,1,2].map(j=>lerp(Math.min(212,sunL),sun[j],.16));
  /* изнанка: воздух планеты, уведённый вниз по светлоте и в синеву, а не в
     серое — серая изнанка мертва, а холодная читается тенью от массы над ней */
  const und=capLum([0,1,2].map(j=>lerp(amb[j]*.52,[46,52,68][j],.42)),litC,.62);
  const fld=new Float32Array(DW*DH), thk=new Float32Array(DW);
  for(let y=0;y<DH;y++)for(let x=0;x<DW;x++){
    const u=y/DH;
    const f=fbm2(x*.0072,y*.030,seed,4)*.66+fbm2(x*.025,y*.082,seed+7,3)*.34;
    /* ── кромка гуляет по небу (второй проход M355) ──
       С ровным порогом низ полога выходил чередой одинаковых фестонов — так
       рвут бумагу, а не облака. У настоящего яруса кромка ходит крупной
       волной: где-то он свисает почти до середины неба, где-то поднят и
       открывает синеву. Волна медленная, в один шум на всю ширину. */
    const wv=fbm2(x*.0019+3.1,7.7,seed+41,3);
    const hang=.52+wv*1.20;
    let a=(f-(.28+Math.pow(clamp(u/hang,0,2),1.6)*.72))/.15;
    /* по краям полотнище сходит на нет — так куски кладутся внахлёст без шва */
    const ex=clamp(Math.min(x,DW-1-x)/(DW*.16),0,1);
    fld[y*DW+x]=clamp(a,0,1)*(ex*ex*(3-2*ex));
    if(y===0)thk[x]=fbm2(x*.0037,1.3,seed+91,3);
  }
  const F=(x,y)=>(x<0||y<0||x>=DW||y>=DH)?0:fld[y*DW+x];
  for(let y=0;y<DH;y++)for(let x=0;x<DW;x++){
    const o=(y*DW+x)*4, a0=fld[y*DW+x];
    if(a0<=0){d[o+3]=0;continue;}
    const a=a0*a0*(3-2*a0);
    /* просвет: где массы мало, сквозь полог идёт свет */
    const thin=clamp(1-a0*1.25,0,1);
    const gx=F(x+3,y)-F(x-3,y), gy=F(x,y+3)-F(x,y-3);
    const gl=Math.hypot(gx,gy)||1;
    /* каёмка на рваной кромке со стороны светила — тот же приём, что у тела */
    const rim=clamp(1-Math.abs(a0-.42)*4.2,0,1)*
      clamp(-(gx/gl*SUN_DIR.x+gy/gl*SUN_DIR.y),0,1);
    /* толщина: у полога есть ядра и промоины, и ровная плита цвета — это
       крашеный потолок, а не облачность. Плюс книзу, к горизонту, изнанка
       светлеет: туда свет заходит сбоку, из-под яруса */
    const u=y/DH;
    const dens=clamp(thk[x]*1.5-.35,0,1);
    const bot=clamp((u-.35)/.65,0,1);
    /* ── у полога есть ПОТОЛОК просвета ──
       Слагаемые складывались до единицы и выше, то есть промоины и рваная
       кромка выходили в полную силу света — а это изнанка яруса, до неё
       прямой свет не доходит вовсе. Большие куски полога вставали вровень с
       освещённым кучевым, и в кадре самым светлым местом оказывалось не
       светило, а потолок над головой (пойман набором «ничто не спорит со
       звездой»: 0.604 против 0.454 у диска). Потолок в .58 оставляет и
       просвет, и каёмку, но полог остаётся тёмной массой — тем самым
       противовесом, ради которого он и заведён (§12). */
    const g=clamp(thin*.34+rim*.46+bot*.16+(1-dens)*.12,0,.58);
    for(let j=0;j<3;j++)d[o+j]=clamp(lerp(und[j]*(.82+dens*.30),litC[j],g),0,255);
    d[o+3]=clamp(a*236,0,255);
  }
  c.putImageData(img,0,0);
  return cn;
}
function cloudsOf(p){
  if(p.clouds)return p.clouds;
  const K=wtab(p).cloudK||CLOUD_KIND[p.type]||CLOUD_KIND.terran;
  const sprites=[];
  for(let i=0;i<CLOUD_SPR;i++)
    sprites.push(cloudSprite(p,hashi(p.seed,i,0x0C10D),K.soft*(i%2?1:.78)));
  /* грозовой вариант каждого спрайта (M232): в ливень облака НЕ белые.
     Печётся раз — тот же спрайт, притопленный в сизое поверх своей альфы */
  const dark=sprites.map(s=>{
    const cn=document.createElement("canvas");cn.width=s.width;cn.height=s.height;
    const c2=cn.getContext("2d");
    c2.drawImage(s,0,0);
    c2.globalCompositeOperation="source-atop";
    c2.fillStyle="rgba(56,62,74,.66)";
    c2.fillRect(0,0,cn.width,cn.height);
    return cn;
  });
  /* сколько неба закрыто пологом — свойство планеты, а не броска в кадре:
     над одним миром он стоит почти всегда, над другим не собирается никогда,
     и погода только сгущает то, что уже есть */
  const dr=((hashi(p.seed,0,0xDEC01)>>>8)&1023)/1023;
  /* с вычетом: над частью миров полог не собирается вовсе, и это важнее
     разнообразия — небо без него должно оставаться просторным (§3) */
  /* Полог печётся ЛЕНИВО, при первом кадре, где он есть: над третью миров он
     не собирается никогда, и платить за него выпечкой на каждой посадке —
     значит платить ни за что. Спрайт кладётся в `p.clouds.deck` из drawClouds. */
  p.clouds={K,sprites,dark,cirrus:cirrusSprite(p,(p.seed^0xC1EE)>>>0),
            deck:null,deckAmt:clamp((K.cover||0)*(.30+dr*1.45)-.16,0,1)};
  return p.clouds;
}

/* ── расстановка ──
   Три эшелона. Дальний мелкий, тусклый и почти неподвижный, ближний крупный
   и быстрый. Экземпляры детерминированы от хэша: небо у планеты всегда своё
   и не пересобирается между кадрами. */
const CLOUD_TIER=[
  /* Масштаб выбран так, что ближнее облако занимает четверть кадра: мелкие
     разномастные пятна читаются грядой холмов у горизонта, а не небом.
     Штук мало намеренно — небо должно быть просторным.

     Дальний ярус — не россыпь, а ЦЕПЬ (M355). На фотографии у горизонта стоит
     непрерывная гряда мелких кучевых, они перекрывают друг друга и тем самым
     читаются полем, уходящим вдаль; врозь те же пятна читались крошками на
     стекле — ровно это и было видно на снимке захода. Поэтому у дальнего яруса
     штук больше, размер крупнее, а `span` уже: они обязаны наезжать. */
  {sc:.62,y:.78,par:.020,spd:.14,a:.74,n:16},
  {sc:.86,y:.60,par:.055,spd:.40,a:.84,n:5},
  {sc:1.55,y:.38,par:.115,spd:.95,a:.94,n:2}
];
/* доля высоты спрайта, на которой лежит его плоский низ (см. `base` в cloudSprite) */
const CLOUD_BASE=.80;
function drawClouds(p,camx,camy){
  if(p.T.atm==="отсутствует")return;
  const C=cloudsOf(p), K=C.K;
  const wp=weatherPower(p);
  const yH=H*SURF_HOR-camy*.03;            // горизонт облачного слоя
  const SS=sunSpot(p), sunX=SS.x, sunY=SS.y;   /* облака освещаются с той стороны, где звезда (M172) */
  const SR=starRGB(), SSL=.299*SR[0]+.587*SR[1]+.114*SR[2];
  ctx.save();
  /* перистые выше всех и первыми: они фон для кучевых */
  const cir=C.cirrus;
  const nc=Math.round(2*K.cir);
  for(let i=0;i<nc;i++){
    const h=hashi(p.seed,i,0x77E1);
    const sc=1.6+((h>>>3)&7)*.35;
    const span=W*3.4;
    const x=((h&1023)/1023*span-(camx*.018+G.t*.09)%span+span*2)%span-W*.7;
    const y=yH*(.04+((h>>>13)&7)/7*.20)-camy*.02;
    ctx.globalAlpha=(.34+((h>>>17)&7)/7*.22)*(1-wp*.35);
    ctx.drawImage(cir,x,y,cir.width*sc,cir.height*sc*.8);
  }
  /* ── полог: масса, висящая над головой ──
     Идёт после перьев и до кучевых: он ближе перьев (он их закрывает) и не
     спорит с кучевыми — те живут у горизонта, полог у верхней кромки кадра.
     Верх спрайта уходит за кадр: у яруса, который прямо над тобой, верха не
     видно вовсе, видно только изнанку и рваный край. Полотнища кладутся
     внахлёст, каждое со своим сдвигом, — тогда между ними рвётся синева. */
  /* Полог либо ЕСТЬ, либо его нет: полупрозрачная плёнка поперёк неба —
     это грязь на стекле, а не облачность. `dAmt` решает, стоит ли он сегодня
     и как низко висит; плотность у стоящего полога почти полная, иначе он не
     работает противовесом светлым кучевым (§12: сначала светлоты). */
  /* Ливень идёт ИЗ полога, а не из ясного неба: непогода поднимает ярус над
     любым миром, даже над тем, где он не собирается сам. Без этого дождь шёл
     из синевы — на заходе в грозу это было видно первым делом. */
  const dAmt=clamp(Math.max(C.deckAmt,wp*.92)*(.85+wp*.55),0,1);
  if(dAmt>.18){
    const dk=C.deck||(C.deck=deckSprite(p,(p.seed^0xD3C4)>>>0));
    const dsc=Math.max(W/(DW*.78),1.15);
    const dw=DW*dsc, dh=DH*dsc;
    const dspan=dw*.82;                       /* внахлёст: полотнища перекрываются */
    const dy=-dh*(.46-dAmt*.26)-camy*.012;    /* гуще полог — ниже висит кромка */
    for(let i=0;i<3;i++){
      const h=hashi(p.seed,i,0x0DEC);
      const x=((h&511)/511*dspan-(camx*.030+G.t*.16)%dspan+dspan*3)%dspan-dw+(i-1)*dspan;
      if(x>W+20||x+dw<-20)continue;
      ctx.globalAlpha=(.52+dAmt*.48)*(.84+((h>>>11)&7)/7*.16);
      ctx.drawImage(dk,x,dy+((h>>>15)&7)/7*dh*.10,dw,dh);
    }
    ctx.globalAlpha=1;
  }
  /* кучевые: от дальнего эшелона к ближнему */
  for(let t=0;t<CLOUD_TIER.length;t++){
    const T=CLOUD_TIER[t];
    /* сколько их на небе — от типа мира и погоды. Ясный день в пустыне это
       два облака на весь небосвод, и так и должно быть: пустота ценна */
    const n=Math.max(0,Math.round(T.n*K.n*(.55+wp*.85)));
    const span=W*(2.6+t*.9);
    for(let i=0;i<n;i++){
      const h=hashi(p.seed,i*7+t*131,0x51DE);
      const spr=C.sprites[(h>>>2)%CLOUD_SPR];
      /* Разброс размера внутри яруса шире, чем был (.72…1.34): десяток облаков
         одного калибра читается гирляндой, а на небе рядом стоят и клок, и
         гора. Размер — главный признак того, что они на разном удалении. */
      const sc=T.sc*(.46+((h>>>7)&15)/15*1.20);
      const w=spr.width*sc, hgt=spr.height*sc;
      const drift=(camx*T.par+G.t*T.spd)%span;
      /* Место — не равномерный бросок: облака ходят кучами, между кучами
         пусто (§3). Ярус делится на ячейки, а внутри ячейки облако гуляет
         шире неё, поэтому соседи то сбиваются, то расходятся. */
      const xu=(i+((h&255)/255-.5)*1.9)/n;
      const x=((xu*span)%span-drift+span*2)%span-w;
      /* ── у яруса ОДНА линия конденсации (M355) ──
         Плоский низ пекётся в каждый спрайт — и тут же терялся на небе: высота
         разбрасывалась на восьмую часть небосвода, и десять плоских низов на
         десяти разных уровнях читаются десятью наклейками, а не погодой. В
         природе облака одного яруса висят низом на одной высоте — это первое,
         что видно на любой фотографии неба, и самый дешёвый признак того, что
         небо настоящее. Поэтому спрайт сажается низом на линию яруса, а
         дрожание оставлено крохотное — воздух не идеально ровный, но и не
         лестница. Выше или ниже линия у планеты — решает `hi`. */
      const ty=clamp(T.y-(K.hi-.30)*.42,.18,.94);
      const y=yH*ty-camy*T.par*.5-hgt*CLOUD_BASE+((h>>>12)&7)/7*hgt*.05;
      if(x>W+40||x+w<-40)continue;
      ctx.globalAlpha=T.a*(.68+.32*((h>>>20)&7)/7)*(1-wp*.12);
      /* ── скос по ветру (матрица «закон × поверхность», андаменто §2) ──
         Кучевое дрейфует по ветру, но тело стояло прямоугольным — единственная
         вещь неба, не знавшая направления. Лёгкий сдвиг верха по WIND роднит
         облако с травой, пылью и дымом; сдвиг — тем же transform, спрайту
         перепекаться не надо. */
      const sh=WIND*.22;
      ctx.save();
      ctx.transform(1,0,-sh,1,x+sh*(y+hgt),y);
      ctx.drawImage(spr,0,0,w,hgt);
      /* в осадки облако тонет в сизом по силе непогоды — грозовое небо
         тёмное, а не белое (M232) */
      if(wp>.06){
        const ga=ctx.globalAlpha;
        ctx.globalAlpha=ga*Math.min(1,wp*1.15);
        ctx.drawImage(C.dark[(h>>>2)%CLOUD_SPR],0,0,w,hgt);
        ctx.globalAlpha=ga;
      }
      ctx.restore();
      /* у самого светила облако ещё и просвечивает: второй проход на
         сложении. Каёмка уже в спрайте, это общее свечение вокруг */
      const near=1-clamp(Math.hypot(x+w*.5-sunX,y+hgt*.5-sunY)/(W*.5),0,1);
      if(near>.25){
        ctx.save();ctx.globalCompositeOperation="lighter";
        /* Просвет — единственная краска неба, которая ПРИБАВЛЯЕТ, и потому
           единственная, способная перешагнуть «не ярче своей звезды» (§13).
           Прибавка теперь по светилу: под тусклой звездой облако у диска
           почти не светится, под яркой светится как прежде. Сторож —
           набор «в кадре ничто не спорит со звездой за источник». Порог, а не
           доля: под тусклым светилом просвета нет вовсе (прибавлять там уже
           некуда — предел «не ярче звезды» выбран телом облака целиком), под
           ярким он прежней силы. */
        ctx.globalAlpha=(near-.25)*.44*clamp((SSL-150)/70,0,1);
        ctx.transform(1,0,-sh,1,x+sh*(y+hgt),y);
        ctx.drawImage(spr,0,0,w,hgt);
        ctx.restore();
      }
    }
  }
  ctx.globalAlpha=1;
  ctx.restore();
  /* ── дымка у горизонта не должна КОНЧАТЬСЯ ступенькой (M233) ──
     Полоса набирала половинную непрозрачность к `yH` и там обрывалась. На
     поверхности стык прятала земля — она ровно на этой высоте; в полёте на
     посадке земля совсем в другом месте, и поперёк кадра шла ровная светлая
     черта на треть экрана. Дымка теперь гаснет в обе стороны: сгущается к
     горизонту и тает под ним, края нет вовсе. И цвет берётся из СЕГОДНЯШНЕГО
     воздуха (19c), иначе днём это тёмная перемычка поперёк светлого неба. */
  /* Воздух тоже светится не сам по себе: дымка берёт цвет из `ambRGB`, а тот
     живёт от неба и под тусклым светилом оказывается ярче него. Поверх облака
     такая дымка давала пятно ярче солнечного диска — тот же закон «не ярче
     своего света» (§13), только пойманный с третьей стороны. */
  const amb=capLum((typeof ambRGB==="function")?ambRGB(p):p.T.sky[1],[SSL,SSL,SSL],1);
  const hg=ctx.createLinearGradient(0,yH-H*.18,0,yH+H*.12);
  hg.addColorStop(0,"rgba("+amb.join(",")+",0)");
  hg.addColorStop(.60,"rgba("+amb.join(",")+",.34)");
  hg.addColorStop(1,"rgba("+amb.join(",")+",0)");
  ctx.fillStyle=hg;ctx.fillRect(0,yH-H*.18,W,H*.30);
}
