function relayLights(m,x,y,s,R){
  const pass=gpuScene();if(!pass||!m.L||!m.L.length)return;
  const cb=Math.cos(RELAY_TILT),sb=Math.sin(RELAY_TILT),ph=(R.sx|0)*7+(R.sy|0)*13,D=[],A=[];
  for(const q of m.L){
    if(q.k&&Math.sin(G.t*q.k+ph)<=.2)continue;
    const px=x+q.x*s,py=y+(q.y*cb-q.z*sb)*s;
    if(q.r)D.push([1,px,py,Math.max(.7,q.r*s),0,0,0,q.c[0],q.c[1],q.c[2],.9]);
    A.push([1,px,py,Math.max(.7,q.r*s)*.5,0,0,q.g*s,q.c[0],q.c[1],q.c[2],q.a]);
  }
  if(D.length)gpuShapes(pass,D);
  if(A.length)gpuShapes(pass,A,{blend:"add"});
}
