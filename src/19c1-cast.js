/* ══════════════ падающие тени: рельеф затеняет сам себя (P5, M433) ══════════════
   Одиннадцатая строка свода ремесла (`docs/DESIGN-story-craft.md`, P5), первая
   после десяти законов. До сих пор тень в разрезе была двух родов: ламбертова
   — склон, отвёрнутый от солнца, темнее, — и контактная (`groundShadow`),
   эллипс под предметом. Ни та, ни другая не знает, что стоит МЕЖДУ точкой и
   светилом: гребень на закате светился с той же силой, что и его подошва, и
   валун не клал тени ни на что, кроме собственного пятачка. Вечер на такой
   земле не наступал — он только гасил.

   Здесь третий род: от каждой точки профиля луч ведётся к светилу шагами
   самого профиля. Перекрыл его гребень или валун — точка в тени: прямого
   света нет, остаётся небо. Доля тени идёт в те же три места, где разрез
   считает свет, — полосы склона (`litRGB` с погашенным прямым светом), блик
   корки и движки (в тени их нет) и тело валуна, — и в маску под кромкой.

   ── ПОЧЕМУ ЭТО ДЁШЕВО ──
   Тень — функция солнца и рельефа, и ни то, ни другое не меняется от кадра к
   кадру: ломоть земли и так ключуется стороной солнца (`sunAzQ`) и высотой
   дня (`dayKq`, M242). Значит карта тени считается раз на ломоть и читается
   всеми рисовальщиками из памятки на рельефе. Луч ведётся не дальше
   CAST_MAXD: у самого горизонта тень длиннее кадра, и дальше её всё равно не
   видно. Кадр за неё не платит вовсе.

   ── ЖИВОЕ ТОЖЕ В ТЕНИ (M434) ──
   Постройки, растения и трава рисуются в кадре, не в ломте, и первый заход
   оставил их освещёнными внутри тени гребня — куст горел на склоне, который
   сам уже ушёл в вечер. Памятка стала многослотной и ключуется ломтём:
   живой рисовальщик спрашивает `castLive(tr, x)` по мировому x, попадает в
   карту того же ломтя, что испёк грунт, и платит за это одно чтение массива.
   Карта одна на ломоть и на солнце, кто бы её ни спросил первым.

   ── ПОЧЕМУ ЭТО ЛОЖИТСЯ НА ГРИЗАЙЛЬ, А НЕ ПОВЕРХ ──
   Тень кладётся СЕРЫМ в проход формы, а не чёрной заливкой поверх готового:
   лессировка (18a1) сама делает её цветом неба — синей на ледяном мире,
   зелёной на токсичном, чёрной там, где воздуха нет. §16 свода, «экспонировать
   по теням»: в тени видно, потому что небо светит и туда.

   ── ГДЕ ТЕНИ НЕТ ──
   Ночью (светило ниже CAST_MIN_ALT) карта не строится: прямого света нет, и
   «тень» была бы всем кадром. В зените (|SUN_DIR.x| мал) луч уходит вверх и
   ничего не задевает — тени короче шага профиля. Полутень: гребень, едва
   задевший луч, даёт долю, а не ступень (CAST_SOFT), иначе край тени читался
   бы как трещина, и прибор кадра насчитал бы кромки. */
const CAST_MAXD=900;      /* дальше луч не ведём, px по x */
const CAST_SOFT=7;        /* на сколько px заслон должен перекрыть луч ради полной тени */
const CAST_MIN_ALT=.02;   /* ниже — светила нет, тени нет: ночь остаётся ночью */
const CAST_KEEP=8;        /* сколько карт держать на рельефе: экран — два-три ломтя, плюс запас */
const CAST_LIVE=.5;       /* насколько живой предмет темнеет в полной тени: небо ему остаётся */

/* высота заслона в мировой точке x: профиль и валуны, лежащие на нём.
   Валун — полукруг радиуса rad с центром там, где его кладёт drawRocks
   (y − rad·.42). y растёт вниз: меньше — выше */
function castOccH(tr,x,rocks){
  let y=groundAt(tr,x);
  for(let i=0;i<rocks.length;i++){
    const k=rocks[i],dx=x-k.x;
    if(dx<=-k.rad||dx>=k.rad)continue;
    const top=groundAt(tr,k.x)-k.rad*.42-Math.sqrt(k.rad*k.rad-dx*dx);
    if(top<y)y=top;
  }
  return y;
}
/* доля тени в точке профиля i: 0 — на солнце, 1 — в тени */
function castShadeAt(tr,i,sx,sy,rocks){
  const x0=i*tr.step,y0=tr.h[i];
  const dirx=sx>0?1:-1;
  const climb=sy/Math.abs(sx);           /* подъём луча на px хода по x; sy<0 — вверх */
  let rise=0;
  for(let d=tr.step;d<=CAST_MAXD;d+=tr.step){
    const x=x0+d*dirx;
    if(x<0||x>tr.W)break;
    const r=(y0+d*climb)-castOccH(tr,x,rocks);   /* заслон выше луча — положительно */
    if(r>rise){rise=r;if(rise>=CAST_SOFT)return 1;}
  }
  return clamp(rise/CAST_SOFT,0,1);
}
/* карта тени на диапазон точек [i0,i1] при солнце как оно сейчас.
   Памятка на рельефе — несколько карт, ключ: диапазон и квантованное солнце.
   Два рисовальщика одного ломтя, два прохода (форма, оттенок) и живые
   предметы в кадре читают одну карту; старые вытесняются по порядку */
function castMap(tr,p,i0,i1){
  if(!tr||!p||!tr.h||typeof celSun!=="function"||typeof SUN_DIR!=="object")return null;
  if(celSun(p).alt<=CAST_MIN_ALT)return null;
  const sx=SUN_DIR.x,sy=SUN_DIR.y;
  if(!(Math.abs(sx)>=.03)||!(sy<0))return null;
  const key=i0+"|"+i1+"|"+sunAzQ(p)+"|"+dayKq(p)+"|"+(sx>0?1:0);
  let MM=tr._castM;
  if(!MM)MM=tr._castM=new Map();
  const had=MM.get(key);
  if(had)return had;
  const lo=Math.min(i0,i1)*tr.step-CAST_MAXD-40, hi=Math.max(i0,i1)*tr.step+CAST_MAXD+40;
  const rocks=[];
  if(tr.rocks)for(const k of tr.rocks)if(k.x+k.rad>=lo&&k.x-k.rad<=hi)rocks.push(k);
  const a=new Float32Array(Math.max(0,i1-i0+1));
  for(let i=i0;i<=i1;i++)a[i-i0]=castShadeAt(tr,i,sx,sy,rocks);
  const M={key,i0,a};
  MM.set(key,M);
  while(MM.size>CAST_KEEP)MM.delete(MM.keys().next().value);
  return M;
}
/* тот же диапазон, что берёт drawGround: ломоть и два рисовальщика сходятся на
   одной карте, потому что считают i0/i1 одной формулой */
function castMapFor(tr,camx){
  if(!tr||!tr.p)return null;
  const i0=clamp(Math.floor((camx-40)/tr.step),0,tr.N-1);
  const i1=clamp(Math.ceil((camx+W+40)/tr.step),0,tr.N-1);
  return castMap(tr,tr.p,i0,i1);
}
/* карта ломтя k — та же формула, что у пекла (там camx = k·CHUNK_W и W = CHUNK_W),
   поэтому живой запрос попадает в карту, которую грунт уже испёк */
function castChunkMap(tr,k){
  if(!tr||!tr.p)return null;
  const CW=(typeof CHUNK_W==="number")?CHUNK_W:512;
  const i0=clamp(Math.floor((k*CW-40)/tr.step),0,tr.N-1);
  const i1=clamp(Math.ceil(((k+1)*CW+40)/tr.step),0,tr.N-1);
  return castMap(tr,tr.p,i0,i1);
}
function castAt(M,i){
  if(!M)return 0;
  const j=i-M.i0;
  return (j<0||j>=M.a.length)?0:M.a[j];
}
/* доля тени в мировой точке x — для того, что рисуется в кадре, а не в ломте:
   постройки, растения, трава. Одно чтение массива на предмет */
function castLive(tr,x){
  if(!tr||!tr.p||!(tr.step>0))return 0;
  const CW=(typeof CHUNK_W==="number")?CHUNK_W:512;
  return castAt(castChunkMap(tr,Math.floor(x/CW)),Math.round(x/tr.step));
}
