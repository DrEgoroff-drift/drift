function bodyBb(x,y,s,wx,wy){
  if(!bodyGpu())return false;
  const m=bodyBbMesh(),sc=s*(20/(m.R||20));
  if((m.len||50)*sc<BODY.LOD){bodyDot(x,y,[70,78,88],wx,wy,1);return true;}
  return bodyRun(m,x,y,0,sc,wx,wy,0);
}
