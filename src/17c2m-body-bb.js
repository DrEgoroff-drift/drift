/* ══════════════ щит полосы: стойки телом (G15 / M460) ══════════════
   Две ноги и башмаки под панелью 17k; сама панель, неон и бегущая строка —
   по-прежнему выпечка (буквы). Без GPU — только выпечка, как было.
   c72: срезали junk-микроцикл (уши/заклёпки → 0), оставили читаемую ферму. */
function bodyBbMesh(){
  return bodyMesh("bb:c72",2,()=>{
    const {V,C,box,tube}=h3dKit();
    const iron=C([70,78,88]),dk=C([22,26,32]),shoe=C([40,46,54]);
    for(const s of[-1,1]){
      tube([[s*18,22,0],[s*18,-28,0]],.7,iron,3,.5,6);
      box(s*18-3,s*18+3,-30,-24,-2.5,2.5,.25,shoe,3,.45);
      box(s*18-3.5,s*18+3.5,-31,-29.5,-3,3,.15,dk,3,.5);
      box(s*18-2.2,s*18+2.2,-26,-24.5,-2.8,2.8,.12,shoe,3,.45);
      box(s*18-1,s*18+1,-28.5,-27.5,-2.2,2.2,.1,shoe,3,.45);
      for(const u of[-2,0,2])box(s*18+u-.25,s*18+u+.25,-30.2,-29.6,2.4,3.2,.05,iron,3,.65);
      tube([[s*18,-28,0],[s*22,-32,1]],.2,dk,3,.4,4);
      tube([[s*18,-24,0],[s*6,18,0]],.28,dk,3,.4,5);
      tube([[s*18,16,0],[s*10,20,0]],.2,dk,3,.4,4);
      tube([[s*18,10,0],[s*12,18,0]],.15,dk,3,.4,4);
      for(const y of[16,6,-4,-14])box(s*18-.55,s*18+.55,y-.45,y+.45,-1.35,1.35,.08,dk,3,.55);
      box(s*18-1.5,s*18+1.5,14,16,-2,2,.1,iron,3,.5);
      box(s*18-1.2,s*18+1.2,8,12,-1.8,1.8,.1,iron,3,.5);
      box(s*18-.8,s*18+.8,21.5,23.5,-1.6,1.6,.1,iron,3,.5);
      box(s*18-1.5,s*18+1.5,20,24,-1.8,1.8,.08,dk,3,.5);
    }
    /* перекладина и полка под панелью */
    box(-20,20,18,22,-1.2,1.2,.2,iron,3,.5);
    box(-21,21,17.5,18,-1.4,1.4,.08,dk,3,.55);
    box(-18,18,21.5,22.5,-.8,.8,.1,iron,3,.55);
    box(-18,18,22.5,23.2,-.8,.8,.08,dk,3,.5);
    box(-16,16,19.5,20.2,-1.2,1.2,.08,dk,3,.5);
    box(-4,4,19,21,-1.5,1.5,.1,iron,3,.55);
    box(-2,2,17,18.5,-1.5,1.5,.1,iron,3,.55);
    for(const sx of[-18,0,18])box(sx-1.2,sx+1.2,19.5,22.5,-1.5,1.5,.1,dk,3,.5);
    for(const sx of[-12,0,12])box(sx-.8,sx+.8,18.2,19.2,-1.3,1.3,.08,dk,3,.5);
    for(const s of[-1,1]){
      box(s*6-.5,s*6+.5,18.5,21.5,-1.4,1.4,.08,dk,3,.5);
      box(s*14-.5,s*14+.5,20,22,-1.4,1.4,.08,iron,3,.5);
    }
    for(let i=0;i<4;i++)box(-15+i*10,-14.5+i*10,21.8,22.5,-1.0,1.0,.05,dk,3,.5);
    /* диагонали и связи между стойками */
    tube([[-18,10,0],[18,-8,0]],.22,dk,3,.4,5);
    tube([[-18,-8,0],[18,10,0]],.22,dk,3,.4,5);
    tube([[-18,22,0],[18,22,0]],.15,dk,3,.4,5);
    tube([[-18,-20,0],[18,-20,0]],.18,dk,3,.4,5);
    tube([[-18,-10,0],[18,-10,0]],.15,dk,3,.4,5);
    const m=h3dPack(V,36,{st:[[0,22],[0,-28]],ne:2.0,kh:.5,gl:.35});
    m.len=50;return m;
  });
}
function bodyBb(x,y,s,wx,wy){
  if(!bodyGpu())return false;
  const m=bodyBbMesh(),sc=s*(20/(m.R||20));
  if((m.len||50)*sc<BODY.LOD){bodyDot(x,y,[70,78,88],wx,wy,1);return true;}
  return bodyRun(m,x,y,0,sc,wx,wy,0);
}
