/* сборные корпуса разложены по профессиям поимённо: это решение о том, какие
   истории на них доступны, а не следствие их чисел */
const ROLE_BY_HULL={strizh:"survey",igla:"survey",klinok:"post",vyuk:"ore",
                    mamont:"ore",obod:"tug",topor:"guard",skat:"shift"};
/* уникальные и сплавленные корпуса профессии не имеют — её приходится вывести
   из того, что мастер собрал: что у корпуса выражено сильнее, тем он и живёт */
function roleFromStats(S){
  if(!S)return HULL_ROLE.survey;
  if(S.cargo>=170)return HULL_ROLE.ore;
  if(S.thr>=1.35&&S.cargo<=60)return HULL_ROLE.post;
  if(S.hull>=200)return HULL_ROLE.guard;
  if(S.cargo>=90&&S.hull>=140)return HULL_ROLE.tug;
  if(S.cargo>=70)return HULL_ROLE.shift;
  return HULL_ROLE.survey;
}
function roleOf(id){
  const key=ROLE_BY_HULL[id];
  if(key)return HULL_ROLE[key];
  return roleFromStats(typeof shipData==="function"?shipData(id):null);
}
function hullRole(){return roleOf(G.shipId);}
/* ── эфир: сколько галактики слышно ──
   Почтовик помнит вдвое больше слухов, рудовоз — заметно меньше. Это тот же
   список, что читают в кантине (12p-news), только его глубина зависит от того,
   на чём вы прилетели. */
function newsKeepLimit(){
  return Math.round(NEWS_KEEP*hullRole().ether);
}
/* ── пассажиры: единственный корпус, где в полёте говорят ──
   Вахтовка возит людей, и люди не молчат. Реплики берутся от того, куда и с кем
   летим, повторяются редко и никогда не требуют ответа: это не диалог, а голоса
   за спиной. */
const SHIFT_TALK=[
  "— Слышь, а там правда день по сорок часов?",
  "— У меня брат в этом секторе третий год. Не пишет.",
  "— Ты в первый раз летишь? Сразу видно.",
  "— Скажите, а на станции душ есть? Просто спрашиваю.",
  "— Не садись у переборки, там тянет.",
  "— Мы же вернёмся, да? Ну, когда-нибудь.",
  "— Он говорил: две смены и домой. Пятая пошла.",
  "— Тише вы, капитан слушает приборы."
];
function shiftTalkTick(dt){
  const R=hullRole();
  if(!R.pax||!(G.cargo.folk|0))return;
  if(G.mode!=="system"&&G.mode!=="belt")return;
  G.shiftT=(G.shiftT||0)-dt;
  if(G.shiftT>0)return;
  /* пауза длинная и случайная: голос за спиной ценен тем, что редок */
  G.shiftT=1800+Math.random()*2400;
  const r=rng(hashi(G.sx,G.sy,(G.t|0)));
  logAdd("talk",pick(SHIFT_TALK,r));
}
/* ── буксир: чужая беда — его работа ──
   Доля груза в благодарность за спасённую баржу считается с оглядкой на то,
   кто пришёл: буксир умеет взять её на трос, а не просто отогнать пиратов. */
function towShare(base){
  return Math.max(1,Math.round(base*hullRole().tow));
}
