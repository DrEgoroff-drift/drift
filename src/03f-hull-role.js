/* ══════════════ корпус — это профессия, а не ступенька ══════════════
   M126. Раньше корпуса выстраивались в лестницу «дешёвый → дорогой»: следующий
   был просто больше по всем числам, и выбор сводился к «накопил — купил». Роль
   меняет не числа, а ДОСТУПНЫЕ ИСТОРИИ: на почтовике слышно галактику, на
   изыскателе невязка видна раньше всех, на рудовозе не видно почти ничего,
   вахтовка — единственный корпус, где пассажиры разговаривают в полёте, а
   буксир вытаскивает чужую беду и тем живёт.

   ЧЕСТНОСТЬ ПОКАЗАНИЙ. Роль не врёт про мир: невязка (`06b-region`) остаётся
   тем, что она есть, — меняется РАЗРЕШЕНИЕ прибора, то есть насколько рано
   отклонение вообще становится видно на шкале. Плохой прибор не «-5% к
   чему-то», он просто показывает грубее.

   Роль выводится из корпуса и не сохраняется: это свойство железа, а не
   решение игрока (сквозное правило — не персистить выводимое). */

