/* ══════════════ спички: единственный огонь, который можно взять в руку ══════════════
   Вторая валюта, и единственная, которой торгует «Сорока» (docs/DESIGN-wanderer.md §13).

   ПОЧЕМУ ИХ НЕТ. Открытый огонь запрещён везде — на станции, на борту, на базе,
   — и запрет старше «Долгого Хода» (устав, §9). Где нет огня, не нужны спички;
   фабрики стояли на старых мирах, последние партии разошлись поколение назад.
   Спичка — не деньги, а то, чего деньги не сделают. Чиркнутая исчезает; считают
   только целые.

   ОТКУДА ОНИ У ИГРОКА. Обычай механиков старых миров: под кожух хорошей части
   клали одну спичку — «чтоб стояла». Разобрал часть выше добротной — нашёл.
   Дешёвая и новая работа внутри пуста, поэтому правило объясняет себя само, и
   рынок спичек не знает.

   ПРАВИЛА ФАЙЛА:
   1. Кошелёк G.matches — целое ≥ 0, персистится (решение игрока: разобрать).
   2. Сколько внутри — функция ЧАСТИ (её зерна и тира), не бросок при разборе.
   3. Спички не продаются и не покупаются за кредиты нигде. Тратятся только на
      борту «Сороки» (12v-wander, позже). */
const MATCH_BY_TIER=[0,0,0,1,3,5];   /* обычная, добротная — пусто; редкая 1, отменная 3, легендарная 5 */
const MATCH_BOX=8;                    /* легендарная иногда прячет целый коробок */
function matchesRec(){
  if(typeof G.matches!=="number"||!(G.matches>=0)||G.matches!==Math.floor(G.matches))G.matches=Math.max(0,G.matches|0);
  return G.matches;
}
function matchesAdd(n){n|=0;if(n<=0)return 0;matchesRec();G.matches+=n;return n;}
function matchesSpend(n){n|=0;if(n<=0)return true;if(matchesRec()<n)return false;G.matches-=n;return true;}
/* сколько спичек лежит под кожухом этой части: по тиру, а у легендарной — по зерну */
function matchesInPart(p){
  if(!p)return 0;
  const base=MATCH_BY_TIER[p.tier|0]||0;
  if(!base)return 0;
  if((p.tier|0)>=5){const r=rng(((p.seed|0)^0x5A1C)>>>0);if(r()<.2)return MATCH_BOX;}
  return base;
}
function matchesRu(n){
  n|=0;const d=n%10,h=n%100;
  if(d===1&&h!==11)return n+" спичка";
  if(d>=2&&d<=4&&(h<12||h>14))return n+" спички";
  return n+" спичек";
}
/* строка для трюма и стола */
function matchesLine(){return "спичек: "+matchesRec();}
/* что говорит трюм при разборе (§13 — тексты для игры) */
function matchesScrapNote(n){
  n|=0;
  if(!n)return "внутри пусто, новая работа";
  if(n>=MATCH_BOX)return "под кожухом целый коробок — "+matchesRu(n);
  return "под кожухом "+matchesRu(n)+": мастер клал, чтоб стояла";
}
