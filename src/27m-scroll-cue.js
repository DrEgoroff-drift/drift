/* ══════════════ «внизу ещё есть» ══════════════
   M212. Обход второго часа: первая же стыковка новичка открывает ДОСКУ, а на
   ней восемь разделов — очередь у стойки, что предлагают, нужда, наряд, на
   стене, слухи, имя системы и строка про приёмник. Померено в работающей
   игре: 1229 пикселей содержимого в окне высотой 407. Две трети доски лежат
   ниже кромки, и НИЧТО об этом не говорит: ни тени, ни стрелки, ни обрезанной
   строки — последний ряд заканчивается ровно по краю, как будто он последний.

   Это не спор о том, много ли восемь разделов (это решать автору), а
   недостающая примета. Список, который продолжается, обязан выглядеть
   продолжающимся — иначе половина написанного не существует для игрока.

   ПРИМЕТА ТИХАЯ. Правило интерфейса: старшинство от размера и цвета, а не от
   заглавных, и над миром висит только то, что нужно прямо сейчас. Значит ни
   стрелки, ни надписи «ещё ниже», ни полосы прокрутки во всю высоту. Нижние
   строки просто УХОДЯТ В ТУМАН — тем же приёмом, каким в этой игре меряется
   даль. Дошли до конца — туман пропал, и это и есть ответ «всё».

   ПОЧЕМУ МАСКОЙ, А НЕ НАКЛАДКОЙ. Накладка — это ещё один элемент поверх
   содержимого: его надо позиционировать, он ловит нажатия и он не знает про
   скруглённые углы окна. Маска гасит сам список и не существует как вещь.

   РАБОТАЕТ ВЕЗДЕ, где есть `.body`: станция, корабль, стол, дом, кантина.
   Список, который продолжается за кромкой, — беда не одной доски. */
const CUE_PAD=30;                 /* сколько снизу уходит в туман */
const CUE_EPS=4;                  /* у самого конца тумана уже нет */
function scrollCue(el){
  if(!el)return;
  const more=el.scrollHeight-el.clientHeight-el.scrollTop>CUE_EPS;
  el.classList.toggle("more",more);
}
function scrollCueAll(){
  document.querySelectorAll(".scr .body,#tablewin>.body").forEach(scrollCue);
}
/* прокрутка не всплывает, поэтому слушаем на перехвате: один слушатель на всю
   игру вместо одного на каждый список */
document.addEventListener("scroll",(e)=>{
  const t=e.target;
  if(t&&t.classList&&t.classList.contains("body"))scrollCue(t);
},true);
/* содержимое меняется при каждой перерисовке вкладки, и высота вместе с ним.
   Наблюдатель дешевле, чем звать проверку из двух десятков мест: ни один
   рендер не забудет о примете, потому что его об этом никто и не просит */
(function(){
  const opts={childList:true,subtree:true,characterData:true};
  const seen=new WeakSet();
  const hook=()=>{
    document.querySelectorAll(".scr .body,#tablewin>.body").forEach(el=>{
      if(seen.has(el))return;
      seen.add(el);
      new MutationObserver(()=>scrollCue(el)).observe(el,opts);
      scrollCue(el);
    });
  };
  hook();
  /* окна заводятся не все сразу: стол и дом появляются позже. Перевешиваем
     наблюдателей, когда в игре что-то открылось */
  new MutationObserver(hook).observe(document.body,{childList:true,subtree:true});
  window.addEventListener("resize",scrollCueAll);
})();
