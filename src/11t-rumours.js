const RUMOUR_SRC=[{ru:"механик с «Прибоя»"},{ru:"буфетчица",f:1},{ru:"старик у стойки"},
  {ru:"диспетчер на смене"},{ru:"пассажир барж"},{ru:"женщина в платке",f:1}];
function rumourSeedHere(){
  return hashi(G.sys?(G.sys.sx*131+G.sys.sy*7):0,Math.floor(celDay()/3),0x5A5A);
}
function capRu(s){return s?s[0].toLocaleUpperCase("ru")+s.slice(1):s;}
/* адрес слуха. Всегда со словом «сектор»: без него «-9:18» читается временем.
   Разброс — словами и в тех же секторах, в каких набрана вся игра. */
function rumourWhere(q){
  /* и сколько это отсюда (M298): сектор в чужой системе координат ничего не говорил о том, куда лететь */
  const d=Math.max(Math.abs(q.sx-G.sx),Math.abs(q.sy-G.sy));
  const j=Math.max(1,Math.ceil(d/Math.max(.5,(typeof stat==="function")?stat().jump:3)));
  return "искать у сектора "+q.sx+":"+q.sy+", в "+q.rad+" секторах вокруг · отсюда "+d+" "+pl3(d,"сектор","сектора","секторов")+", примерно "+j+" "+pl3(j,"прыжок","прыжка","прыжков");
}
/* на карту: не метка на чуде, а окно карты на названном секторе и круг поиска (M298) */
function rumourToMap(q){
  G.mapSearch={sx:q.sx,sy:q.sy,rad:q.rad};
  if(typeof gotoSector==="function")gotoSector(q.sx,q.sy,"слух · искать в "+q.rad+" "+pl3(q.rad,"секторе","секторах","секторах")+" вокруг");
}
/* слухи этой станции на эти три дня: два, и один из них может врать */
function rumoursHere(){
  const placed=(typeof REGION_TABLE!=="undefined")?REGION_TABLE.filter(T=>regionOfTheme(T.id)):[];
  if(!placed.length)return [];
  const r=rng(rumourSeedHere()),out=[];
  for(let i=0;i<2;i++){
    const T=placed[Math.floor(r()*placed.length)];
    const at=regionOfTheme(T.id),R=regionAt(at.rx*REGION_SPAN,at.ry*REGION_SPAN);
    let cx=R.core.sx+Math.round((r()-.5)*4),cy=R.core.sy+Math.round((r()-.5)*4);
    const wrong=r()<.15;
    if(wrong){cx=Math.round((r()-.5)*60);cy=Math.round((r()-.5)*60);}   /* просто неверен */
    /* штурманский карандаш («Сорока»): разброс на сектор уже, но не меньше двух */
    const rad=Math.max(2,3+Math.floor(r()*3)-((typeof wanderHas==="function"&&wanderHas("pencil"))?1:0));
    const img=RUMOUR_IMG[T.id]||T.ru.toLowerCase();
    const S=pick(RUMOUR_SRC,r);
    const det=pick(RUMOUR_DETAIL.any.concat(S.f?RUMOUR_DETAIL.f:RUMOUR_DETAIL.m),r);
    /* имя игрока (11u): слух подхватывает его, слегка искажённым */
    let nm="";
    if(typeof namesFor==="function"){const n=namesFor(R.core.sx+","+R.core.sy);if(n)nm="; называют «"+namesMangle(n)+"»";}
    const q={id:T.id,sx:cx,sy:cy,rad,wrong,img:img+nm,src:S.ru,det};
    q.where=rumourWhere(q);
    /* порядок, в котором это и рассказывают: КТО — ПРО ЧТО — ГДЕ — ПОЧЕМУ верить.
       Одним куском: в тетради строка идёт сплошняком, переносов там нет */
    q.text=capRu(S.ru)+" рассказывал про место: "+q.img+". "+
           capRu(q.where)+". "+capRu(det)+".";
    /* три строки для экрана: что, где, с чьих слов */
    q.lines=[capRu(q.img),capRu(q.where),"со слов: "+S.ru+" — "+det];
    /* короткая форма для приёмника: место и сторона, без рассказчика */
    q.short=q.img+" — где-то у сектора "+cx+":"+cy;
    out.push(q);
  }
  /* «Сорока» (12v, M342): третий слух, пока борт стоит в шести прыжках — паруса
     трудно перепутать, поэтому разброс уже обычного, но 15 % всё так же врут */
  if(typeof wanderRumour==="function"){const wq=wanderRumour(r);if(wq)out.push(wq);}
  return out;
}
/* приёмник: изредка слух приходит строкой эфира */
function rumourEtherLine(r){
  /* слуховая трубка («Сорока»): приёмник ловит слухи почти вчетверо чаще */
  if(!G.sys||r()>((typeof wanderHas==="function"&&wanderHas("trumpet"))?.45:.12))return null;
  const L=rumoursHere();
  return L.length?"…говорят, есть "+L[Math.floor(r()*L.length)].short:null;
}
/* ── блок на доске ──
   Два слуха, без карты и без маркера: проверять их игрок будет ногами. Но
   помнить их за него должна тетрадь, а не он сам, — иначе адрес приходится
   переписывать на бумажку рядом с монитором. Записываем один раз на станцию и
   трёхсуточный бакет: слух услышан, а не «обновляется». */
function rumourBlock(){
  const L=rumoursHere();
  if(!L.length)return;
  /* заголовок называет, заметка объясняет один раз (M300); блок идёт в полосу ДАЛЕКО */
  if(typeof secHead==="function")secHead("СЛУХИ",{count:L.length,key:"rumours",
    note:"адрес с промахом и человек, которому вы либо верите, либо нет; метки на карте не будет — записано в тетрадь, ЛЮДИ"});
  else $body.appendChild(el("div","sec","СЛУХИ"));
  for(const q of L){
    const r=el("div","row");
    r.appendChild(el("div","nm","<b style='color:#cfe3ea'>"+q.lines[0]+"</b>"+
      "<s style='line-height:1.8'>"+q.lines[1]+"<br>"+q.lines[2]+"</s>"));
    const b=el("button","act sm","НА КАРТУ");
    b.onclick=()=>{rumourToMap(q);};
    r.appendChild(b);$body.appendChild(r);
  }
  const tag=G.sys.key+"#"+rumourSeedHere();
  if(G.rumLogged!==tag){
    G.rumLogged=tag;
    for(const q of L)peopleLine(q.text,"слух на «"+G.st.name+"»");
  }
}
