function gunSeriesOf(seed){return 1954+((seed>>>7)%38);}
function gunFamilyKeyOf(seed){return GUN_FAM_KEYS[(seed>>>13)%GUN_FAM_KEYS.length];}
function gunFactoryOf(seed){return GUN_FACTORY[(seed>>>19)%GUN_FACTORY.length];}
/* имя вида «АП-23 «Оса»» — индекс от seed, чтобы номер не совпадал с серией */
function gunNameOf(seed,fam){
  const F=GUN_FAMILY[fam];
  return F.ab+"-"+(11+((seed>>>3)%89))+" "+GUN_NICK[(seed>>>23)%GUN_NICK.length];
}
/* полная строка для карточки: имя, завод, серия */
function gunTitleOf(p){
  if(!p||!p.fam)return p?p.name:"";
  return p.name+" · завод "+GUN_FACTORY[p.fact].ru+" · серия "+p.ser;
}
