/* До этого свет на грунте был зашит константами: «склон вправо-вверх светлее».
   Он не знал ни цвета звезды, ни цвета неба, поэтому все планеты освещались
   одинаково — а именно освещение, а не форма, отвечает за то, верит ли игрок
   в место.

   Три вещи, которые дают почти весь эффект:
   направленный свет звезды своего цвета;
   цветной подсвет от неба в тенях (главный приём — без него тень мёртвая);
   воздушная перспектива: далёкое уводится к цвету неба, а не просто гасится. */
/* ── солнце светит оттуда, где оно нарисовано (M242) ──
   Здесь годами стояла КОНСТАНТА «справа сверху», и по ней освещались рельеф,
   облака, посёлок, дом и все тени. А диск в небе рисуется по настоящей высоте
   и азимуту (`sunSpot`→`celSun`) и ходит по небу. То есть в игре было два
   солнца: одно видно, другое светит. На закате это видно сразу — светило у
   левой кромки, а склоны и облака подсвечены справа.
   Теперь вектор пересчитывается на кадр из того же `celSun`, что и диск.
   Знак по горизонтали обратный азимуту: `sunSpot` кладёт диск в
   `W*(.5-az*.40)`, значит при az>0 солнце ЛЕВЕЕ центра, и свет идёт слева.
   По вертикали к высоте добавлена четверть: у самого горизонта свет почти
   горизонтальный, но не строго — иначе плоская земля разом гаснет. */
const SUN_DIR={x:.55,y:-.83};
const SUN_DIR_FLAT={x:.55,y:-.83};            /* запасной: режимы без своего неба */
/* сторона солнца, огрублённая до восьми ступеней: этим ключуются ломти
   земли — печь их на каждый градус азимута никто не будет */
function sunAzQ(p){
  if(!p||typeof celSun!=="function")return 0;
  return Math.round(celSun(p).az*4);
}
function sunDirSet(p){
  if(!p||typeof celSun!=="function"){SUN_DIR.x=SUN_DIR_FLAT.x;SUN_DIR.y=SUN_DIR_FLAT.y;return SUN_DIR;}
  const s=celSun(p);
  const vx=-s.az, vy=-(.25+clamp(s.alt,-.2,1)*1.1);
  const L=Math.hypot(vx,vy)||1;
  SUN_DIR.x=vx/L;SUN_DIR.y=vy/L;
  return SUN_DIR;
}
/* ветер живёт в общей переменной: его читают трава в drawGround, пыль и
   растения, и все они должны качаться в одну сторону — рассинхрон читается
   как брак быстрее, чем полное отсутствие движения */
let WIND=0;
function windOf(p){
  const base=(h01((p.seed|0),3,0x117A)-.5)*2;
  const air=p.T.atm==="отсутствует"?.06:(p.T.atm.indexOf("разреженная")>=0?.5:1);
  /* порывами, а не ровным потоком: ровный ветер глаз не замечает вообще */
  const gust=.62+.38*Math.sin(G.t*.0037+p.seed%7)*Math.sin(G.t*.0011+2);
  return base*air*gust;
}
function starRGB(){
  const sc=(G.sys&&G.sys.cls&&G.sys.cls.col)||"#ffe08a";
  const c=hex2rgb(sc);
  /* затмение гасит НАПРАВЛЕННЫЙ свет и только его: заполняющий от неба остаётся,
     поэтому мир не чернеет, а становится плоским и синим — так это и выглядит
     на самом деле (06a-celest) */
  const d=typeof celDark==="function"?celDark():0;
  if(d<=0)return c;
  const k=1-d;
  return [c[0]*k|0,c[1]*k|0,c[2]*k|0];
}
/* ── дневной ключ (M232, этап 5) ──
   Полдень читался пасмурно на всех мирах, и причина была одна: небо и свет
   вообще не знали часа. Зенит всегда красился ночным sky[1], заполняющий свет
   был им же, а прямой свет грунта — константой. Теперь час входит в палитру:
   dayK — сколько дня сейчас (0 ночь/заря, 1 высокий полдень), приглушённый на
   мирах без воздуха (рассеивать нечем — чёрное небо и в полдень);
   dayKq — он же квантованный, для ключей кэшей: ломоть, испечённый под один
   свет, не должен всплывать под другим. */
function dayK(p){
  if(!p)return .5;
  const s=(typeof celSun==="function")?celSun(p):{alt:.7};
  const air=p.T.atm==="отсутствует"?.12:(p.T.atm.indexOf("разреженная")>=0?.6:1);
  return clamp((s.alt+.12)*1.6,0,1)*air;
}
function dayKq(p){return Math.round(dayK(p)*6)/6;}
/* дневное небо из палитры мира: зенит — светлее и насыщеннее ночного, но
   глубже горизонта; горизонт уходит к светлому воздуху. Ни одного чужого
   цвета: всё выведено из sky[0]/sky[1] самого мира. */
function skyDay(p){
  const k=dayKq(p),s0=p.T.sky[0],s1=p.T.sky[1];
  let top=[0,1,2].map(i=>Math.round(lerp(s1[i],Math.min(255,s0[i]*.92+18),k)));
  const bot=[0,1,2].map(i=>Math.round(lerp(s0[i],Math.min(255,s0[i]*1.30+34),k)));
  /* ── зенит ХОЛОДНЕЕ горизонта (M243) ──
     Прибор показал главное: восемь сцен из десяти одноцветны — у пустынной,
     вулканической и токсичной планеты небо и грунт одного семейства, и в
     кадре просто нет второй температуры. Между тем короткие волны рассеивает
     любая атмосфера: даже над марсианской пустыней зенит холоднее горизонта,
     а тени синеют. Двигаем к холоду ЗЕНИТ (и через ambRGB — заполняющий свет),
     оставляя горизонту цвет мира: планета себя не теряет, а пара появляется. */
  const air=p.T.atm==="отсутствует"?0:(p.T.atm.indexOf("разреженная")>=0?.55:1);
  if(air>0){
    const COLD=[86,128,190];
    top=top.map((v,i)=>Math.round(lerp(v,v*.52+COLD[i]*.48,.50*air*k)));   /* .38→.50 (M304): зенит дальше от флоры */
  }
  return {top,bot,k};
}
/* небо как источник заполняющего света: у токсичного мира тени зелёные,
   у ледяного — синие, и это читается сразу. Днём заполняющий — цвет
   СЕГОДНЯШНЕГО неба: тени голубеют и оживают («тени цветнее» из аудита),
   ночью прежний тёмный. */
function ambRGB(p){
  const D=skyDay(p);
  const base=[0,1,2].map(i=>Math.round(lerp(p.T.sky[1][i],D.top[i],.85*D.k)));
  /* ── заполняющий свет ХОЛОДНЕЕ ключевого (M243) ──
     Небо рассеивает короткие волны, поэтому тень на любом мире с воздухом
     синеет — это и есть второй источник, которого игре не хватало. Без него
     палитра планеты растекалась по всему кадру: прибор мерил 95% тепла днём и
     3% ночью, то есть два монохрома вместо картины. Мир без воздуха остаётся
     как был: рассеивать нечем. */
  const air=p.T.atm==="отсутствует"?.06:(p.T.atm.indexOf("разреженная")>=0?.5:1);
  const COLD=[104,146,196];
  return base.map((v,i)=>Math.round(lerp(v,Math.max(v*.86,COLD[i]*.62),.34*air)));
}
/* сколько света вообще: у безвоздушного мира тень почти чёрная (нечему
   рассеивать), у плотной атмосферы — мягкая */
function ambK(p){
  const a=p.T.atm;
  if(a==="отсутствует")return .13;
  if(a.indexOf("разреженная")>=0)return .26;
  return .40;
}
/* освещённость склона: ламберт по нормали профиля плюс заполнение от неба.
   df — сила прямого света (M232): в полдень ~.96, на заре ~.45, без df —
   прежние .78. Прямой растёт с днём быстрее заполняющего, поэтому в полдень
   тени РЕЗЧЕ, а не просто всё светлее. */
function litRGB(base,slope,p,sun,amb,k,df){
  const nl=Math.hypot(slope,1);
  const nx=-slope/nl, ny=-1/nl;
  const d=clamp(nx*SUN_DIR.x+ny*SUN_DIR.y,0,1);
  /* мягкий переход у терминатора: жёсткий ламберт даёт «пластик» */
  const I=Math.pow(d,.72)*(df||.78);
  const r=base[0]*(k*amb[0]/255+I*sun[0]/255);
  const g=base[1]*(k*amb[1]/255+I*sun[1]/255);
  const b=base[2]*(k*amb[2]/255+I*sun[2]/255);
  return [clamp(r,0,255)|0,clamp(g,0,255)|0,clamp(b,0,255)|0];
}
/* ── камера ──
   Камера, жёстко привязанная к персонажу, читается как «экран едет», а не как
   «оператор идёт рядом». Нужны три вещи: инерция, взгляд вперёд по ходу
   движения и дыхание. Плюс тряска от удара — единственное, что даёт миру вес.
   Состояние живёт в S, поэтому переход между режимами его не ломает. */
function camStep(S,dt,walking){
  if(!S.cam)S.cam={x:S.x,y:S.y};
  /* взгляд вперёд: на ходу камера уводится в сторону движения, на месте
     возвращается. Иначе игрок всегда смотрит ровно в центр и не видит, куда идёт. */
  const look=(walking?S.face*54:0);
  S.camLook=lerp(S.camLook||0,look,Math.min(1,.045*dt));
  const tx=S.x+S.camLook;
  /* по вертикали камера мягче: рельеф под ногами дёргается на каждой кочке,
     и жёсткое следование превращает ходьбу в тряску */
  S.cam.x+=(tx-S.cam.x)*Math.min(1,.11*dt);
  S.cam.y+=(S.y-S.cam.y)*Math.min(1,(S.on?.055:.10)*dt);
  S.shake=Math.max(0,(S.shake||0)-.55*dt);
}
/* смещение камеры на кадр: дыхание плюс затухающая тряска */
function camOffset(S){
  const sh=S.shake||0;
  const b=Math.sin(G.t*.0062)*1.7;                        // дыхание оператора
  if(sh<=0)return {x:0,y:b};
  /* тряска не синусоида, а рваная: синус читается как качели */
  return {x:(h01((G.t*3)|0,1,0x5A)-.5)*sh*1.8,
          y:b+(h01((G.t*3)|0,2,0x5A)-.5)*sh*1.8};
}
/* ── воздушная перспектива ──
   далёкий хребет не «полупрозрачный», а выцветший в цвет неба: именно этим
   глаз мерит расстояние. Отдельная функция, потому что дальний слой рисуется
   тем же drawGround, что и близкий. */
function hazeFar(p,k){
  /* воздух — сегодняшний: днём гряды выцветают в дневное небо, а не в ночное */
  const D=skyDay(p);
  const c=[lerp(D.bot[0],D.top[0],.5),lerp(D.bot[1],D.top[1],.5),lerp(D.bot[2],D.top[2],.5)];
  const pal=p.T.pal[1];
  /* в осадки дальнее тонет в пелене СТУПЕНЯМИ (M232): дальний план моет
     сильнее ближнего — две гряды дают две ступени воздуха, а не чёрные
     силуэты. Сила квантована: этот цвет входит в ключ тайлов. */
  const wq=Math.round(((typeof weatherPower==="function")?weatherPower(p):0)*5)/5;
  const wf=wq*(k>.45?.50:.30);
  /* ── дальний план обязан быть виден ──
     Хребет выцветал точно в цвет неба, и на мирах, где грунт и воздух одного
     тона (вулканический, токсичный, джунглевый), он исчезал вовсе: у половины
     планет за спиной была пустая заливка вместо горизонта. Дальнее не только
     бледнеет — оно ещё и ТЕМНЕЕ неба на просвет, потому что смотришь на
     затенённый склон. Небольшой сдвиг в тень и возвращает горизонт всем. */
  const v=[0,1,2].map(i=>{
    const base=lerp(pal[i]*.8,c[i],k)*(1-.13*(1-k));
    return lerp(base,c[i]*.82,wf);           /* пелена: к цвету воздуха, чуть в тень */
  });
  return "rgb("+v.map(Math.round).join(",")+")";
}
/* дымка в низинах и у горизонта: одна полоса градиента, но она делает
   глубину сильнее, чем любой дополнительный слой рельефа */
function hazeBand(p,y0,h){
  const c=ambRGB(p);                          /* дымка — сегодняшним воздухом */
  const g=ctx.createLinearGradient(0,y0-h,0,y0+h*.35);
  g.addColorStop(0,"rgba("+c.join(",")+",0)");
  g.addColorStop(.55,"rgba("+c.join(",")+","+(p.T.atm==="отсутствует"?.10:.34)+")");
  g.addColorStop(1,"rgba("+c.join(",")+",0)");
  ctx.fillStyle=g;ctx.fillRect(0,y0-h,W,h*1.35);
}
/* ── где на небе звезда (M172) ──
   Час суток в игре был давно (celSun, 06a), но светило всё это время стояло
   прибитым в W*.78, H*.16: менялась только заливка темноты поверх кадра.
   Отсюда и брался главный порок экрана «мир пешком» — у света был час, но не
   было НАПРАВЛЕНИЯ: полдень отличался от заката только яркостью, тени никуда
   не ехали, а закат не был закатом, потому что звезда не садилась.
   Одна точка на всех, кто её рисует: зарево, диск, облака, лучи, ободок на
   человеке. Восток слева, запад справа, полдень наверху; `up` — над ли она
   горизонта (ниже него рисуется только зарево). */
/* высота горизонта на экране в долях кадра. Была .58 и жила россыпью
   магических чисел по трём файлам; на экране «мир пешком» это значило, что
   сорок с лишним процентов кадра всегда занимал разрез грунта под ногами —
   самая большая и самая пустая площадь картинки (M172). */
const SURF_HOR=.64;
function sunSpot(p){
  const s=(typeof celSun==="function")?celSun(p):{alt:.7,az:.35};
  /* диск не прижимается к самой кромке кадра: в зените он упирался в верхний
     край и срезался пополам */
  return {x:W*(.5-s.az*.40), y:Math.max(H*.10,H*(.62-s.alt*.56)), alt:s.alt, az:s.az, up:s.alt>-.08};
}
/* ── лучи от звезды ──
   объёмного света в canvas 2D нет, но есть то, ради чего его хотят: несколько
   мягких клиньев от солнца, медленно дышащих. Только там, где есть чему
   светиться — в вакууме лучей не бывает. */
function lightShafts(p){
  if(p.T.atm==="отсутствует")return;
  const S=sunSpot(p);
  if(!S.up)return;                    /* из-под горизонта клинья не идут */
  /* осадки глушат снопы (M232): ливень и прямые клинья света вместе — брак
     погоды. До половины силы клинья тают, дальше их нет вовсе. */
  const wp=(typeof weatherPower==="function")?weatherPower(p):0;
  if(wp>.5)return;
  const wk=1-wp*2;
  const sx=S.x,sy=S.y;
  const sun=starRGB();
  /* один и тот же веер из пяти лучей под одним углом стоял на каждом мире
     штампом (G1): число, раскрытие и наклон — от планеты */
  const hs=hashi(p.seed,0x5AF7,1), nS=2+(hs&3), a0=.92+((hs>>>4)&15)/15*.4, spr=.12+((hs>>>8)&7)/7*.14;
  ctx.save();
  ctx.globalCompositeOperation="lighter";
  for(let i=0;i<nS;i++){
    const a=a0+i*spr+Math.sin(G.t*.0016+i)*.035;
    const wdt=.030+((i*7)%3)*.012;
    const len=H*1.25;
    const al=(.020+((i*5)%3)*.010)*(1+Math.sin(G.t*.0021+i*2)*.35)*wk;
    const g=ctx.createLinearGradient(sx,sy,sx+Math.cos(a)*len,sy+Math.sin(a)*len);
    g.addColorStop(0,"rgba("+sun.join(",")+","+al.toFixed(3)+")");
    g.addColorStop(1,"rgba("+sun.join(",")+",0)");
    ctx.fillStyle=g;
    ctx.beginPath();ctx.moveTo(sx,sy);
    ctx.lineTo(sx+Math.cos(a-wdt)*len,sy+Math.sin(a-wdt)*len);
    ctx.lineTo(sx+Math.cos(a+wdt)*len,sy+Math.sin(a+wdt)*len);
    ctx.closePath();ctx.fill();
  }
  ctx.restore();
}
/* ── финальная свёртка кадра ──
   виньетка и лёгкий цветовой сдвиг: две заливки, которые сводят разнородные
   слои в одну картинку. Всё, что тут делается, стоит два fillRect. */
function gradePass(p){
  /* ── затмение сводится здесь, а не в небе ──
     Первый проход гасил только небо: сверху темнело, а грунт, флора и
     скафандр оставались дневными, и кадр разваливался на две картинки.
     Затмение — это свет, а свет в кадре сводится последней свёрткой: одна
     холодная заливка на всё сразу, и мир садится целиком (06a-celest). */
  const DK=typeof celDark==="function"?celDark():0;
  if(DK>.02){
    ctx.fillStyle="rgba(10,16,34,"+(.52*DK).toFixed(3)+")";
    ctx.fillRect(0,0,W,H);
    /* и цвет уходит: в сумерках глаз теряет насыщенность раньше яркости */
    ctx.save();ctx.globalCompositeOperation="saturation";
    ctx.fillStyle="rgba(128,128,128,"+(.5*DK).toFixed(3)+")";
    ctx.fillRect(0,0,W,H);ctx.restore();
  }
  /* ── виньетка и тон — один слой ──
     Два полноэкранных градиента на кадр стоили ~25 мс на ×2 (G0, 0.94):
     в canvas 2D единица цены — полноэкранный проход, а градиент дороже
     заливки в пять раз. Картинка при этом не меняется от кадра к кадру —
     печётся один раз на планету и размер и кладётся одним drawImage (18c). */
  const sun=starRGB(),amb=ambRGB(p),dk2=dayKq(p);
  ctx.drawImage(screenLayer("grade|"+sun.join(",")+"|"+amb.join(",")+"|d"+dk2,()=>{
    const g=ctx.createRadialGradient(W*.5,H*.46,Math.min(W,H)*.30,W*.5,H*.46,Math.max(W,H)*.78);
    g.addColorStop(0,"rgba(0,0,0,0)");
    /* виньетка днём легче: полуденный кадр не должен сидеть в сумеречной раме */
    g.addColorStop(1,"rgba(0,0,0,"+lerp(.34,.22,dk2).toFixed(3)+")");
    ctx.fillStyle=g;ctx.fillRect(0,0,W,H);
    /* холодная тень внизу, тёплый свет сверху — сдвиг маленький, но именно он
       не даёт кадру рассыпаться на «фон + фигуры». Раньше шёл в lighter;
       при альфе .06 обычное наложение неотличимо, а в слое оно честнее. */
    const t=ctx.createLinearGradient(0,0,0,H);
    t.addColorStop(0,"rgba("+sun.join(",")+",.07)");
    t.addColorStop(.5,"rgba(0,0,0,0)");
    t.addColorStop(1,"rgba("+amb.join(",")+",.09)");
    ctx.fillStyle=t;ctx.fillRect(0,0,W,H);
  }),0,0,W,H);
}
/* небо-подложка: вертикальный градиент на весь экран, один раз на планету */
function drawSkyBase(p){
  const s=p.T.sky, sc=(G.sys&&G.sys.cls&&G.sys.cls.col)||"#ffe08a", hasAir=p.T.atm!=="отсутствует";
  /* час суток (06a): слой печётся на 48 делений дня — небо темнеет к ночи, а
     зарево гнётся за звездой: сидит на горизонте с её стороны и тем ярче,
     чем она ниже (хвост G7). Ночью зарева нет — нечему рассеиваться */
  const sun=celSun(p), hb=Math.round(sun.ph*48)%48, nite=surfNight(p);
  ctx.drawImage(screenLayer("skybg|"+s[0].join(",")+"|"+s[1].join(",")+"|"+sc+"|"+hasAir+"|"+hb,()=>{
    ctx.fillStyle=skyGrad(p);ctx.fillRect(0,0,W,H);
    if(hasAir){
      const c=hex2rgb(sc), day=clamp(1+sun.alt*2.2,0,1);
      /* полоса зарева — кисть у горизонта, не треть листа (M304, §13):
         была H*.42→.78, стала H*.54→.74 */
      const g=ctx.createLinearGradient(0,H*.54,0,H*.74);
      g.addColorStop(0,"rgba("+c.join(",")+",0)");
      g.addColorStop(.7,"rgba("+c.join(",")+","+(.10*day).toFixed(3)+")");
      g.addColorStop(1,"rgba("+c.join(",")+","+(.16*day).toFixed(3)+")");
      ctx.fillStyle=g;ctx.fillRect(0,H*.54,W,H*.20);
      /* наклонное зарево: пятно у горизонта там, где звезда, сильнее всего
         на восходе и закате — это и есть «гнётся по высоте» */
      const low=clamp(1-Math.abs(sun.alt)*1.4,0,1)*day;
      if(low>.02){
        /* знак тот же, что у sunSpot: зарево обязано быть с той стороны, где
           звезда. Раньше знаки расходились, и на закате небо горело на востоке */
        const gx=W*(.5-sun.az*.42), gy=H*.74;
        const rg=ctx.createRadialGradient(gx,gy,8,gx,gy,W*.55);
        rg.addColorStop(0,"rgba("+c.join(",")+","+(.30*low).toFixed(3)+")");
        rg.addColorStop(.5,"rgba("+c.join(",")+","+(.10*low).toFixed(3)+")");
        rg.addColorStop(1,"rgba("+c.join(",")+",0)");
        ctx.fillStyle=rg;ctx.fillRect(0,0,W,H);
      }
    }
    if(nite>0){ctx.fillStyle="rgba(4,6,14,"+(nite*.9).toFixed(3)+")";ctx.fillRect(0,0,W,H);}
  }),0,0,W,H);
}

/* ══════════════ свечение (bloom) — M243 ══════════════
   «Свет не светит» — общая претензия ко всем сценам: лампа рисовалась пятном,
   но вокруг неё ничего не происходило. Настоящий ореол вокруг ярких мест —
   самый дешёвый способ сделать источник источником: кадр уменьшается вчетверо,
   из него выбивается тёмное (умножение на себя — это квадрат яркости, серое
   гаснет, яркое остаётся), размывается и кладётся обратно сложением.
   Три drawImage на кадр, без единого чтения пикселей. */
let BLOOM_CV=null;
const BLOOM_K={wanderer:.18,system:.34,map:0,landing:.16,surface:.16,dig:.20,cave:.24,
               belt:.24,scoop:.20,base:.18,raid:.18,homein:.22,winter:.20,spa:.18};
function bloomPass(k){
  if(!(k>0)||W<8||H<8)return;
  if(G.opts&&G.opts.gfx&&G.opts.gfx.draw===0)return;
  const w=Math.max(2,Math.round(W/4)),h=Math.max(2,Math.round(H/4));
  if(!BLOOM_CV||BLOOM_CV.width!==w||BLOOM_CV.height!==h){
    BLOOM_CV=document.createElement("canvas");BLOOM_CV.width=w;BLOOM_CV.height=h;
  }
  const g=BLOOM_CV.getContext("2d");
  g.globalCompositeOperation="source-over";
  g.clearRect(0,0,w,h);
  g.drawImage(cvs,0,0,w,h);
  /* порог без чтения пикселей: кадр, умноженный сам на себя */
  g.globalCompositeOperation="multiply";
  g.drawImage(BLOOM_CV,0,0);
  g.globalCompositeOperation="source-over";
  ctx.save();
  ctx.globalCompositeOperation="lighter";
  ctx.globalAlpha=k;
  const hasF=("filter" in ctx);
  if(hasF)ctx.filter="blur(7px)";
  ctx.drawImage(BLOOM_CV,0,0,w,h,0,0,W,H);
  if(hasF)ctx.filter="none";
  ctx.restore();
}

/* ══════════════ зерно и виньетка — один слой на все сцены (M244) ══════════════
   Две вещи, которые связывают девять разных сцен в одну игру и стоят почти
   ничего. Зерно: запечённый тайл шума 64×64, положенный плиткой в режиме
   `overlay`. Это ещё и дизеринг — прибор ловил кольца на короне звезды, и это
   классический бэндинг восьмибитного градиента; шум разбивает ступени.
   Виньетка: только там, где нет своей (на грунте её кладёт gradePass).
   С M251 плитка — СИНИЙ шум (blueNoise, 01-core; разбор DESIGN-craft §7).
   У белого есть низкие частоты — комки: соседние точки сбивались в пятнышки,
   и на ровной заливке зерно читалось грязью, а не фактурой. Ранги синего
   распределены равномерно по построению — это заодно и лучшая матрица против
   бэндинга: у белого пороги толпились, и ступень рвалась неровно. Доказано
   на открытке (M250), стоимость та же — плитка печётся один раз. */
let GRAIN_PAT=null;
function grainPass(vig){
  if(G.opts&&G.opts.gfx&&G.opts.gfx.draw===0)return;
  if(W<8||H<8)return;
  if(!GRAIN_PAT){
    const cv=document.createElement("canvas");cv.width=cv.height=64;
    const g=cv.getContext("2d"),im=g.createImageData(64,64),bt=blueNoise();
    for(let i=0;i<64*64;i++){
      const v=110+Math.round(bt[i]*36);
      im.data[i*4]=im.data[i*4+1]=im.data[i*4+2]=v;im.data[i*4+3]=255;
    }
    g.putImageData(im,0,0);
    GRAIN_PAT=ctx.createPattern(cv,"repeat");
  }
  ctx.save();
  ctx.globalCompositeOperation="overlay";
  ctx.globalAlpha=.075;
  ctx.fillStyle=GRAIN_PAT;
  ctx.fillRect(0,0,W,H);
  ctx.restore();
  if(vig){
    ctx.drawImage(screenLayer("vigg|"+W+"|"+H,()=>{
      const g=ctx.createRadialGradient(W*.5,H*.48,Math.min(W,H)*.34,W*.5,H*.48,Math.max(W,H)*.76);
      g.addColorStop(0,"rgba(0,0,0,0)");
      g.addColorStop(1,"rgba(0,0,0,.40)");
      ctx.fillStyle=g;ctx.fillRect(0,0,W,H);
    }),0,0,W,H);
  }
}
