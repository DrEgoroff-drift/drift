/* ══════════════ пост у входа телом (G15 / M452) ══════════════
   Ферма и доска — сетка h3dKit; текст доски — domLabel (как подписи мира).
   Лампа остаётся фигурой в drawGestPost. Печёный спрайт — запасной без GPU.
   c106: срезали junk-микроцикл (уши/трубочки → 0), оставили читаемую ферму. */
function bodyGestPostMesh(by){
  return bodyMesh("gp:"+by+":c106",6,()=>{
    const {V,C,box,tube}=h3dKit();
    const gnd=(typeof makerGround==="function")?makerGround(by):[120,120,120];
    const iron=C(mixc(gnd,[28,30,34],.55)),board=C(mixc(gnd,[20,24,30],.72)),rim=C(mixc(gnd,[255,255,255],.2)),soot=C([22,26,32]);
    /* ферма: две стойки и кресты (как gestPostSprite) */
    tube([[-4,28,0],[-4,-8,0]],.55,iron,3,.5,6);
    tube([[4,28,0],[4,-8,0]],.55,iron,3,.5,6);
    for(let y=24;y>-4;y-=8){
      tube([[-4,y,0],[4,y-8,0]],.28,soot,3,.4,5);
      tube([[4,y,0],[-4,y-8,0]],.28,soot,3,.4,5);
    }
    /* хомуты стоек */
    for(const s of[-1,1])for(const y of[24,16,8,0,-6])
      box(s*4-.55,s*4+.55,y-.35,y+.35,-.7,.7,.08,rim,3,.55);
    /* перемычки фермы */
    tube([[-4,26,0],[4,26,0]],.22,iron,3,.45,5);
    tube([[-4,10,0],[4,10,0]],.2,iron,3,.45,5);
    tube([[-4,-6,0],[4,-6,0]],.22,iron,3,.45,5);
    box(-6,6,26,28,-1,1,.12,iron,3,.5);
    /* пятки и оттяжки стоек */
    for(const s of[-1,1]){
      box(s*3.5-.5,s*3.5+.5,26,28.5,-.7,.7,.1,rim,3,.55);
      box(s*4.1,s*4.9,24,28,-.45,.45,.08,rim,3,.55);
      tube([[s*4,28,0],[s*4,32,0],[s*6,34,1]],.2,iron,3,.4,4);
      tube([[s*4,-8,0],[s*8,-12,1]],.18,iron,3,.4,4);
      box(s*4-.55,s*4+.55,-8,-6,-.85,.85,.1,iron,3,.5);
    }
    /* доска и обрамление */
    box(-52,52,-32,-8,-2.2,2.2,.35,board,3,-.3);
    box(-52.5,52.5,-32.5,-7.5,-2.5,-2.2,.08,rim,3,.6);
    box(-52.5,52.5,-32.5,-7.5,2.2,2.5,.08,rim,3,.6);
    box(-48,48,-31.5,-30.5,-2.4,2.4,.05,soot,3,.35);
    box(-50,50,-9.5,-8.5,-2.4,2.4,.05,soot,3,.35);
    box(-50,50,-20,-19.2,-2.3,2.3,.06,soot,3,.4);
    for(const s of[-1,1])box(s*51.5,s*52.5,-30,-10,-2.4,-2.0,.06,rim,3,.55);
    for(const sx of[-48,-24,0,24,48])for(const sy of[-30,-20,-10])
      box(sx-.45,sx+.45,sy-.45,sy+.45,2.0,2.55,.09,rim,3,.65);
    for(const sx of[-50,50])for(const sy of[-31,-9])
      box(sx-.6,sx+.6,sy-.6,sy+.6,-2.5,-2.1,.08,rim,3,.6);
    for(const sx of[-40,-20,20,40])box(sx-.4,sx+.4,-32.2,-31.6,2.1,2.5,.08,rim,3,.6);
    /* лоток кабеля по низу доски + стойка */
    tube([[-40,-8.2,2.0],[40,-8.2,2.0]],.12,soot,3,.45,5);
    for(const sx of[-30,-10,10,30])box(sx-.35,sx+.35,-8.6,-7.8,1.7,2.2,.06,iron,3,.55);
    tube([[0,-8,0],[0,-4,0]],.35,iron,3,.45,5);
    box(-3,3,-4.5,-3.2,-1.2,1.2,.1,iron,3,.5);
    /* кронштейн лампы над доской (огонь — фигура в drawGestPost) */
    tube([[0,-32,0],[0,-38,0]],.35,iron,3,.5,5);
    tube([[-3,-34,0],[3,-34,0]],.22,iron,3,.45,5);
    box(-2.2,2.2,-40,-36,-2.2,2.2,.15,soot,3,.45);
    box(-3,3,-38,-36,-1.5,1.5,.12,rim,3,.55);
    box(-2.5,2.5,-41,-39.5,-2.5,2.5,.12,soot,3,.45);
    box(-1.5,1.5,-36,-34,-1.8,1.8,.1,iron,3,.5);
    box(-1,1,-38.5,-37.2,-1.2,1.2,.08,iron,3,.55);
    for(const s of[-1,1])box(s*2-.35,s*2+.35,-28,-24,-1.2,1.2,.08,iron,3,.5);
    const m=h3dPack(V,56,{st:[[0,28],[0,-40]],ne:2.0,kh:.5,gl:.35});
    m.len=64;m.L=[];return m;
  });
}
/* пост на месте спрайта: (x,y) — подножие; k — масштаб экрана */
function bodyGestPost(x,y,k,by,wx,wy){
  if(!bodyGpu())return false;
  const m=bodyGestPostMesh(by),sc=k*(35/(m.R||35));
  if((m.len||64)*sc<BODY.LOD){bodyDot(x,y-20*k,makerGround(by)||[80,80,80],wx,wy,1);return true;}
  return bodyRun(m,x,y-10*k,0,sc,wx,wy,0);
}
