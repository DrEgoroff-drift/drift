      r.appendChild(el("div","nm","<b>Время идёт</b><s>от старта "+far+" из "+CULT_RACE_FAR+
        " секторов"+best+"</s>"));
      if(cultRaceDue()){
        const b=el("button","act gold","ФИНИШ");
        b.onclick=()=>{cultRaceFinish();renderTab();};
        r.appendChild(b);
      }else r.appendChild(el("div","qt","ДАЛЬШЕ"));
