/* ── радиоспектакль: окно и часть ── */
function cultPlayWindow(N){
  if(N===undefined)N=(typeof chronNow==="function")?chronNow():0;
  const n0=N-(N%CULT_PLAY_EVERY);
  return (N-n0<CULT_PLAY_LIVE)?n0:-1;
}
function cultPlayPart(N){
  if(N===undefined)N=(typeof chronNow==="function")?chronNow():0;
  const n0=cultPlayWindow(N);
  if(n0<0)return -1;
  return Math.min(CULT_PLAY.length-1,Math.floor((N-n0)/CULT_PLAY_STEP));
}
function cultPlayLine(wave,N){
  const i=cultPlayPart(N);
  if(i<0)return "";
  wave=wave||((typeof chronWave==="function")?chronWave():"gt");
  /* молчащая волна молчит и здесь: спектакль идёт по эфиру, а не мимо него */
  if(typeof powWaveSilent==="function"&&powWaveSilent(wave))return "";
  const P=CULT_PLAY[i];
  return P[wave]||P.gt;
}
function cultPlayBlock(){
  if(typeof $body==="undefined")return;
  const i=cultPlayPart();
  if(i<0)return;
  const w=(typeof chronWave==="function")?chronWave():"gt";
  const line=cultPlayLine(w);
  if(!line)return;
  $body.appendChild(el("div","sec","РАДИОСПЕКТАКЛЬ · "+CULT_PLAY_RU.toUpperCase()+
    " · "+CULT_PLAY[i].ru.toUpperCase()));
  const r=el("div","row");
  r.appendChild(el("div","nm","<b>"+((typeof POWERS!=="undefined"&&POWERS[w])?POWERS[w].ru:"эфир")+
    "</b><s style='line-height:1.9'>"+line+"</s>"));
  $body.appendChild(r);
}
/* ── экспедиция и обрывок ──
   Дуга «экспедиция» уже есть у Директора (M371). Здесь у неё появляется то,
   ради чего в неё можно вложиться: счётчик сканирований от толпы и страница
   чужого свода в конце. */
function cultExpedition(){
  if(typeof chronArcs!=="function")return null;
  for(const a of chronArcs())if(a.kind==="expedition")return a;
  return null;
}
function cultExpCount(A){
  A=A||cultExpedition();
  if(!A||typeof warLed!=="function"||typeof chronOwner!=="function")return 0;
  const L=warLed(),N=(typeof chronNow==="function")?chronNow():0;
  let q=0;
  for(const n in L){
    if((n|0)<A.t0||(n|0)>N)continue;
    const body=L[n];
    for(const sys in body){
      if(sys==="__votes")continue;
      const p=sys.split(",");
      if(chronOwner(p[0]|0,p[1]|0)!==A.p)continue;
      const cell=body[sys].scan;
      if(cell)q+=cell.q|0;
    }
  }
  return q;
}
function cultExpFound(){
  const A=cultExpedition();
  return !!(A&&cultExpCount(A)>=CULT_EXP_GOAL);
}
/* какой именно обрывок всплыл: от державы и от сводки, в которую началась дуга */
function cultLongDue(){
  const A=cultExpedition();
  if(!A||cultExpCount(A)<CULT_EXP_GOAL)return null;
  const i=hashi(A.p,A.t0,0x10D)%LONG_HOD.length;
  const F=LONG_HOD[i];
  return ((G.longHod||[]).indexOf(F.id)>=0)?null:F;
}
function cultLongTake(){
  const F=cultLongDue();
  if(!F)return false;
  if(!G.longHod)G.longHod=[];
  G.longHod.push(F.id);
  tell("good","«Долгий Ход» · "+F.ru,"ДОЛГИЙ ХОД · "+F.ru+"\n\n"+F.t);
  return true;
}
function cultLongCount(){return (G.longHod||[]).length;}
/* ── новая серия завода ──
   Месяц у одной державы на прилавке своя серия орудий. Кто именно — по
   календарю, как и спектакль: это праздник, а не последствие, и вычислять его
   из состояния значило бы делать вид, что у него есть причина. */
const CULT_SER_RU=["«Зубр»","«Веретено»","«Ковш»","«Стриж-М»","«Ладога»","«Кедр»"];
function cultSeriesWindow(N){
  if(N===undefined)N=(typeof chronNow==="function")?chronNow():0;
  return N-(N%CULT_SERIES);
}
function cultSeriesWho(N){
  const n0=cultSeriesWindow(N);
  return MAKER_KEYS[hashi(n0,0x5E71,0x2C)%6];
}
function cultSeriesOn(by){return !!by&&cultSeriesWho()===by;}
function cultSeriesName(by,N){
  const n0=cultSeriesWindow(N);
  if(!cultSeriesOn(by||cultSeriesWho(N)))return "";
  const h=hashi(n0,0x5E72,0x2C);
  return CULT_SER_RU[h%CULT_SER_RU.length]+"-"+(1+(h>>>4)%9)+(((h>>>8)%2)?"":"0");
}
/* ── олимпиада флота ──
   Гонка по трассе: одна кнопка на старте, одна на финише. Считается чистое
   время между ними; в толпу уходит только ЯВКА, время остаётся вашим (§11.3:
   без имён и без обмена). */
function cultRaceWindow(N){
  if(N===undefined)N=(typeof chronNow==="function")?chronNow():0;
  const n0=N-(N%CULT_RACE_EVERY);
  return (N-n0<CULT_RACE_LIVE)?n0:-1;
}
function cultRaceOn(){return cultRaceWindow()>=0;}
function cultRaceStart(){
  if(!cultRaceOn())return false;
  G.race={t0:Date.now(),sx:G.sx|0,sy:G.sy|0,n:cultRaceWindow()};
  tell("tech","Олимпиада: время пошло",
    "ОЛИМПИАДА\nвремя пошло\nфиниш — на станции не ближе "+CULT_RACE_FAR+" секторов");
  return true;
}
function cultRaceFar(){
  const R=G.race;
  if(!R)return 0;
  return Math.hypot((G.sx|0)-R.sx,(G.sy|0)-R.sy);
}
function cultRaceDue(){
  const R=G.race;
  if(!R||!G.sys||!G.sys.station)return false;
  return cultRaceFar()>=CULT_RACE_FAR;
}
function cultRaceFinish(){
  if(!cultRaceDue())return 0;
  const ms=Date.now()-G.race.t0;
  G.race=null;
  const s=Math.max(1,Math.round(ms/1000));
  if(!G.raceBest||s<G.raceBest)G.raceBest=s;
  if(typeof warPut==="function")warPut("reg",1);
  tell("good","Олимпиада: "+s+" с","ОЛИМПИАДА\nваше время "+s+" с"+
    (G.raceBest===s?"\nэто ваш лучший ход":"\nлучший ваш — "+G.raceBest+" с"));
  return s;
}
