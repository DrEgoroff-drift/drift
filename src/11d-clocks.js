/* ══════════════ часы над концами: сторож темпа (P8, M416) ══════════════
   Последний незакрытый пункт плана ремесла, и он лечит болезнь, которую Эмили
   Шорт назвала болезнью «архитектуры значимого»: игрок честно играет акт, а
   потом БОЛЕЕ ИЛИ МЕНЕЕ СЛУЧАЙНО удовлетворяет все условия конца — и конец
   приходит не вовремя. В «Дрейфе» это не выдумка: строку части VI «Вы просто
   не тянете» отпирали три закрытые двери и больше ничего. Три двери можно
   закрыть в первый вечер — и получить самую тяжёлую реплику игры до того, как
   в ней вообще что-то прожито.

   Договор написан в `docs/DESIGN-arc.md` («The pacing guard», 2026-08-29) и
   здесь исполняется дословно:

     1. У КАЖДОГО КОНЦА СВОИ ЧАСЫ. Часы идут от ПОСТУПКА и ВРЕМЕНИ: сегмент
        засчитывается только за названное дело и только если с прошлого
        сегмента прошло сколько-то небесных суток. Наблюдение не двигает
        часы никогда.
     2. КОНЕЦ ПРИХОДИТ ТОЛЬКО В СВОЁ ОКНО: свои часы полны И прожито не
        меньше стольких-то суток. Условия, сошедшиеся рано, просто ЖДУТ —
        невидимо, и ничто не истекает.
     3. СТОРОЖ НЕ ПИШЕТ НИЧЕГО. Ни строки, ни записи в журнал, ни намёка, что
        окно есть. Он не история — он вахтёр.
     4. Эталон — медкомиссия (M161): часы у неё — двенадцать лет стажа, место
        — стойка ядра, и приходит она предложением, а не засадой. Остальные
        концы повторяют её форму.
     5. Движка раньше потребителей не бывает. Он и не появился: первый конец
        второго акта построен (M225–M231), и только теперь сторож встаёт над
        всеми тремя разом.

   ЧТО ЭТО ДАЁТ СВЕРХ ТРЁХ ПРОВЕРОК. Одно место, где ОБЪЯВЛЕНЫ все окна.
   Пока каждый конец сторожил себя сам, четвёртый мог родиться вовсе без
   окна — и родился: `toldOffBlock` не смотрел на время ни секунды. Теперь
   новый конец не пишется без строки в этой таблице, и набор это проверяет. */

/* сутки — небесные (`celDay`), потому что вся прожитая жизнь в этой игре
   меряется ими: и стаж в трудовой, и год до подарка */
const CLOCKS={
  /* эталон: часы — стаж, место — стойка ядра. Числа не трогаем, они прожиты */
  record:{ru:"медкомиссия", day:365*12, seg:0,  gap:0,
          note:"двенадцать лет стажа и стойка ядра (11aa)"},
  /* подарок: пять поступков и год. Свои условия у него уже были — сторож их
     только называет вслух, чтобы они стояли рядом с остальными. Сегменты он
     не ведёт: их давно считает тетрадь доброты, и заводить второй счёт того
     же — это способ рассинхронизировать их через десять версий */
  gift:  {ru:"«Тихоня»",    day:365,    seg:5,  gap:0,
          segOf:()=>((typeof ledgerAll==="function"?ledgerAll():null)||{}).n|0,
          note:"тетрадь доброты, год жизни и дом (11at)"},
  /* и тот, у кого окна не было вовсе. Три двери — это часы; но три двери,
     закрытые за один вечер, — это неудачный вечер, а не прожитая жизнь.
     Поэтому между сегментами двадцать суток, а до окна — двести. */
  toldoff:{ru:"тот один",   day:200,    seg:3,  gap:20,
          note:"три двери с промежутком и двести суток (11ar)"}
};
const CLOCK_KEYS=Object.keys(CLOCKS);
/* ── состояние ──
   Сегменты и сутки последнего сегмента. Это НЕ производная от seed: она
   описывает, что и когда сделал игрок, — значит хранится (14-save). */
function clockAll(){
  if(!G.clocks||typeof G.clocks!=="object")G.clocks={};
  return G.clocks;
}
function clockOf(key){
  const C=clockAll();
  if(!C[key]||typeof C[key]!=="object")C[key]={n:0,last:-9999};
  return C[key];
}
/* ── сегмент ──
   Засчитывается за ДЕЛО и только если с прошлого прошло `gap` суток. Возвращает
   true, если часы сдвинулись, — но никто этого не показывает. */
function clockPush(key){
  const K=CLOCKS[key];if(!K)return false;
  const c=clockOf(key),d=(typeof celDay==="function")?celDay():0;
  if(K.gap&&(d-(c.last|0))<K.gap)return false;
  c.n=(c.n|0)+1;c.last=d;
  return true;
}
/* ── сколько сегментов набрано ──
   У одних концов сторож ведёт счёт сам (дверь части VI), у других счёт уже
   есть в мире и второй был бы ложью (тетрадь доброты). `segOf` — про это. */
function clockSeg(key){
  const K=CLOCKS[key];
  if(K&&typeof K.segOf==="function"){try{return K.segOf()|0;}catch(e){return 0;}}
  return clockOf(key).n|0;
}
/* ── окно ──
   Единственное, что сторож умеет отвечать: «ещё нет» или «можно». */
function clockOpen(key){
  const K=CLOCKS[key];if(!K)return true;          /* нет строки — нет запрета */
  const d=(typeof celDay==="function")?celDay():0;
  if(d<K.day)return false;
  return clockSeg(key)>=(K.seg|0);
}
/* почему закрыто — для набора, а НЕ для игрока: в игре эта строка не звучит
   нигде и звучать не должна (правило 3) */
function clockWhy(key){
  const K=CLOCKS[key];if(!K)return "";
  const d=(typeof celDay==="function")?celDay():0;
  if(d<K.day)return "рано: сутки "+d+" из "+K.day;
  if(clockSeg(key)<(K.seg|0))return "мало дел: "+clockSeg(key)+" из "+K.seg;
  return "";
}
