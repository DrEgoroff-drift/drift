const BOOKS_BY={};BOOKS.forEach(b=>BOOKS_BY[b.id]=b);
function bookAll(){if(!Array.isArray(G.books))G.books=[];return G.books;}
function bookHas(id){return bookAll().indexOf(id)>=0;}
function bookCount(){return bookAll().length;}
/* ── находка ──
   Из обломков и только из них. Семя места решает, какая книга там лежит: одно
   и то же место всегда отдаёт одну и ту же — иначе обломки становятся
   генератором, а книга вещью без адреса. */
function bookFind(seed,where){
  const have=bookAll();
  if(have.length>=BOOKS.length)return null;
  const r=rng(hashi(seed|0,0x0B00,11));
  /* обходим список от места, назначенного семенем, и берём первую ненайденную */
  const start=Math.floor(r()*BOOKS.length);
  for(let i=0;i<BOOKS.length;i++){
    const b=BOOKS[(start+i)%BOOKS.length];
    if(bookHas(b.id))continue;
    have.push(b.id);
    thingAdd("find","Книга · "+b.ru,b.by+" · "+(where||"из обломков")+
      " · читается дома, из кресла",{book:b.id});
    logAdd("good","Книга: "+b.ru+" · собрано "+have.length+" из "+BOOKS.length);
    if(typeof recordAdd==="function"&&have.length===BOOKS.length)
      recordAdd("полка","собраны все сорок книг");
    return b;
  }
  return null;
}
/* шанс книги в обломках: не в каждом остове, иначе полка соберётся за вечер */
function bookRoll(seed,where,chance){
  const r=rng(hashi(seed|0,0x0B0C,13));
  if(r()>(chance==null?0.34:chance))return null;
  return bookFind(seed,where);
}
