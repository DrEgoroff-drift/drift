/* ══════════════ поздний час у стойки ══════════════
   M225, часть III дуги («Соседи»): первые два просёра из трёх
   (`docs/saga/ДУГА.md` §5; третий — «ляпнул лишнего» — построен как M194).

   ЗАБУХАЛ. Стойка — честно лучшее место, где что-то узнают: некоторые вещи
   говорят только поздно и только там. Платится ЧАСАМИ — а часы закрывают
   окна: возможности (11ah) живут по G.t, и просиженное время старит их молча,
   вместе со сменами, нуждами и всем календарём. Это и есть счёт, и приходит
   он позже и без единого слова.

   ПРИСТАЛ НЕ К ТОМУ. Иногда рядом оказывается человек, с которым хорошо и
   который ничего не просит. Ничего плохого не происходит. Он просто постоял
   рядом час десять — дороже обычной посиделки, и взамен ровно ничего, кроме
   самого разговора. Никто не сердится — вот что тяжелее всего.

   ПРАВИЛА, БЕЗ КОТОРЫХ ЭТО НЕ ДУГА, А ЛОВУШКА (docs/DESIGN-arc.md):
   1. Игра никогда не заставляет оступиться: кнопка — выбор, и каждый раз он
      в ту минуту хорош. Выпивший получает НАСТОЯЩЕЕ: строку, которой нет
      больше нигде, а изредка — именную возможность.
   2. Никто не упрекает. Ни предупреждения на кнопке, ни счётчика часов, ни
      «вы уверены». Двери закрываются вежливо и в другом месте.
   3. Правда не произносится. Нигде не написано «это стоило вам окна»: игрок
      замечает сам — или не замечает.

   Хранится только счётчик посиделок текущей смены (G.late) — защита от
   фарма: к концу смены стойка пустеет, и до следующей там нечего ловить. */

const LATE_SIT=Math.round(CEL_DAY*.15);     /* час-другой: ~3.5 часа мира */
const LATE_LONG=Math.round(CEL_DAY*.24);    /* «час десять» не того человека */
const LATE_CAP=3;                           /* посиделок за смену, потом пусто */

/* то, что говорят только поздно. Не задания и не лор — услышанное краем уха,
   и в половине строк лежит настоящий адрес или настоящая цена */
const LATE_LINES=[
  {t:"…на «{st}» второй месяц никто не возит лёд. Совсем никто. Делай выводы.",info:"price"},
  {t:"…диспетчер с узла говорил: у них берут топливо без очереди, если прийти к концу смены.",info:null},
  {t:"…видел твой борт на площадке. Держишь в порядке. Это тут замечают, просто не говорят.",info:null},
  {t:"…{st} — вот там сейчас платят. Только это между нами, я туда сам собирался.",info:"price"},
  {t:"…бармен наливает третью бесплатно не по доброте: после третьей люди говорят адреса.",info:null},
  {t:"…институтские опять что-то ищут. Кто им первым привезёт — того запомнят.",info:null},
  {t:"…не летай через {sx}:{sy} порожняком, там смотрят, кто чем гружён.",info:null},
  {t:"…тот, кто на прошлой неделе снял людей с гибнущей баржи, — его тут поминали. Добром.",info:null}
];
/* не тот человек: с ним просто хорошо. Каждая строка — целый час десять */
const LATE_WRONG=[
  "Рядом сел человек и стал рассказывать, как в молодости водил лихтер по льду. Красиво рассказывал. Час десять как не было.",
  "Сосед по стойке весь вечер называл вас «капитан» и рассказывал про сына. Хороший, наверное, сын. Время шло.",
  "Человек рядом молчал так, что уходить было неловко. Просидели вдвоём. О чём — не вспомнить.",
  "Незнакомец угостил и ничего не спросил. Разговор был лучший за месяц. Больше вы его не видели."
];

function lateAll(){
  if(!G.late||typeof G.late!=="object")G.late={shift:-1,n:0};
  return G.late;
}
/* сколько ещё нальют в эту смену */
function lateLeft(){
  const L=lateAll(),shift=Math.floor(G.t/OFFER_SHIFT);
  if(L.shift!==shift){L.shift=shift;L.n=0;}
  return LATE_CAP-L.n;
}
/* ── посидеть ──
   Время уходит вперёд по-настоящему: G.t прыгает, и всё, что живёт по нему —
   окна возможностей, смены, нужды, календарь неба, — стареет молча. */
function lateSit(){
  if(!G.st||lateLeft()<=0)return null;
  const L=lateAll();
  L.n++;
  const r=rng(hashi(G.sx,G.sy,Math.floor(G.t)|0)>>>0);
  /* не тот человек: заметно реже, чем строки, — он должен оставаться случаем,
     а не жанром */
  if(r()<.18){
    G.t+=LATE_LONG;
    const s=LATE_WRONG[Math.floor(r()*LATE_WRONG.length)];
    logAdd("talk",s);
    return {kind:"wrong",line:s};
  }
  G.t+=LATE_SIT;
  /* именная возможность — редкая и только от того, кто помнит хорошо: некоторые
     вещи действительно говорят только поздно */
  if(typeof offerAdd==="function"&&r()<.22){
    const who="st:"+G.sys.key,f=folkOf(who);
    if(f.good){
      const kinds=["word","route","bay","run"];
      const o=offerAdd(kinds[Math.floor(r()*kinds.length)],who,true);
      if(o){
        const K=OFFER_KIND[o.kind];
        const s="Поздний сосед наклонился ближе: «Тебе скажу, раз ты тут. "+
          K.ru[0].toUpperCase()+K.ru.slice(1)+" — "+K.note+"»";
        logAdd("talk",s);
        return {kind:"offer",line:s};
      }
    }
  }
  /* строка позднего часа; в «price» подкладывается настоящая станция с
     настоящей ценой — и она же ложится на бумагу, как всё услышанное */
  let pick=LATE_LINES[Math.floor(r()*LATE_LINES.length)];
  let line=pick.t;
  if(line.indexOf("{st}")>=0||pick.info==="price"){
    const S=(typeof nearestStation==="function")?nearestStation(G.sx+3,G.sy+2):null;
    if(S&&S.station){
      line=line.replace("{st}",S.station.name);
      if(pick.info==="price"&&typeof pricesHeard==="function"){
        const P=marketFor(S);let best=null;
        for(const k of TRADE_KEYS)if(!best||P[k]>P[best])best=k;
        pricesHeard(S,best,P[best],S.station.fuelPrice);
      }
    }else line=line.replace("{st}","дальний узел");
  }
  line=line.replace("{sx}:{sy}",(G.sx+2)+":"+(G.sy-1));
  logAdd("talk","у стойки: "+line);
  return {kind:"line",line};
}
/* ── блок в кантине ──
   Стоит в самом низу зала. Кнопка не предупреждает и не отговаривает: выбор
   хорош в ту минуту, когда делается. Когда налито три — стойка пустеет, и
   это единственная форма отказа. */
function lateBlock(){
  if(typeof $body==="undefined"||!$body)return;
  const left=lateLeft();
  if(left<=0){
    $body.appendChild(el("div","row","<div class='nm'><s>стойка опустела: бармен протирает "+
      "стаканы и составляет табуреты. До следующей смены здесь тихо.</s></div>"));
    return;
  }
  const r=el("div","row");
  r.appendChild(el("div","nm","<b>Остаться у стойки</b><s>час-другой; некоторые вещи "+
    "говорят только поздно и только тут</s>"));
  const b=el("button","act","ОСТАТЬСЯ");
  b.onclick=()=>{
    const got=lateSit();
    if(got)say(got.line,got.kind==="wrong"?420:320);
    sfx("ui");
    renderTab();
  };
  r.appendChild(b);
  $body.appendChild(r);
}
