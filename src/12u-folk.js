const FOLK_IDS=Object.keys(FOLK);

function folkState(){
  if(!G.folkSay||typeof G.folkSay!=="object")G.folkSay={};
  return G.folkSay;
}
/* ── кто здесь сегодня ──
   Один человек на станцию и не каждый раз: если они будут стоять на каждом
   причале, они перестанут быть людьми и станут мебелью. Кто именно — держится
   местом и сменой, чтобы в одну смену тут был один и тот же. */
function folkHere(){
  if(!G.sys||!G.sys.station)return null;
  const shift=Math.floor(G.t/OFFER_SHIFT);
  const h=hashi(G.sx,G.sy,shift)>>>0;
  if((h%100)<45)return null;                    // чаще всего никого
  return FOLK_IDS[h%FOLK_IDS.length];
}
/* ── одна реплика за заход ──
   Берётся на стыковке и держится, пока не отстыкуешься. Иначе экран, который
   перерисовывается после каждой кнопки, заставлял бы человека тараторить:
   взял груз — он сказал новое, продал — ещё новое. Люди так не разговаривают.
   Строки идут по кругу: пока не сказаны все, старые не повторяются. */
let folkNow=null;
function folkVisit(){
  folkNow=null;
  const id=folkHere();
  if(!id||!FOLK[id])return null;
  const S=folkState();
  const n=(S[id]|0);
  S[id]=n+1;
  folkNow={id,line:FOLK[id].say[n%FOLK[id].say.length]};
  return folkNow;
}
function folkShown(){return folkNow;}
function folkLeave(){folkNow=null;}
/* ── он может назвать твой позывной ──
   Возможность с лицом весит больше безымянной. Называют не всегда и только
   те, кто помнит хорошо; Птица не называет никогда — он предлагает сам, и это
   совсем другое дело. */
function folkOffer(id){
  if(id==="ptica")return null;
  if(typeof offerAdd!=="function")return null;
  const who="folk:"+id;
  const f=folkOf(who);
  if(!f.good)return null;
  const shift=Math.floor(G.t/OFFER_SHIFT);
  if(f.shift===shift)return null;
  f.shift=shift;
  const r=rng(hashi(G.sx,G.sy,shift^0x5AF)>>>0);
  if(r()<.55)return null;
  const kind=id==="gusya"?"bay":(id==="ryba"?"run":"route");
  return offerAdd(kind,who,true);
}
