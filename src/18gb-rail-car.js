/* ══ поездка на движке (M828): вагон и ПАЗик — тела, остановки — бусины под тем же светом ══
   Экран поездки — карта галактики; вагон на ней такое же тело под одной звездой, как корабль в системе
   (17c2e): сетка набора h3dKit, свет, своя тень, свои огни. Звезда поездки — ядро галактики: свет идёт
   к нулю карты, с той же стороны ловят его кромку и бусины остановок. Остановка мельче порога тела
   (BODY.LOD) — по закону 17c2e это огонёк, а не сетка: кольцо-тор с освещённой дугой и лампой в
   середине; пройденная гаснет. Имена, строка сверху и подсказка — подписи оверлея (domLabel).
   Прежняя 2D-кисть drawRail (засечки, имена, метка вагона, строки — 14 вызовов ctx за кадр) снята тем
   же ходом: кадр поездки ctx не красит. Сетка строится носом по +x и лежит креном до RAIL_CAR_ROLL —
   видно крышу и борт с окнами; строго сверху вагон читался бы плоской таблеткой. Крен клонит крышу
   к свету: при низком свете сбоку плоская крыша ПАЗика, отвёрнутая от него, лежала серой плитой.
   Борт в тени — со своими окнами, ими и читается. Крен идёт плавно от курса, без щелчка на поворотах */
const RAIL_CAR_ROLL=.5,RAIL_CAR_LEN=26;
const RAIL_CREAM=[238,234,224],RAIL_GLASS=[22,28,38],RAIL_WIN=[255,234,196];
/* свет ядра — свечение 17z3, наполовину к белому: кремовый короб под ним не уходит в персик */
const RAIL_CORE_LIGHT=[255,196,164];

/* сетка: kind — род линии (полоса по борту её цвета), bus — ПАЗик маршрутки */
function railCarMesh(kind,bus){
  return bodyMesh("rc:"+(bus?"bus":kind),4,()=>{
    const K=h3dKit(),C=K.C,L=[],SP=-.35,glass=C(RAIL_GLASS);   /* «−»: своей тени по полю корпуса у капсулы нет */
    /* окно на борту: грань чуть над поверхностью, своим светом; s — борт (+1/−1) */
    const win=(x0,x1,y,z0,z1,c,em)=>K.face([[x0,y,z0],[x1,y,z0],[x1,y,z1],[x0,y,z1]],[(x0+x1)/2,0,(z0+z1)/2],c,3,-.1,em);
    if(bus){
      /* ПАЗик: кремовый короб, красная полоса по поясу, светлая крыша, тёмные бамперы, ряд окон
         по обоим бортам, табличка маршрута над лобовым — янтарём */
      K.box(-13,11,-5.4,5.4,-4.2,3.4,.9,C([233,220,174]),3,SP);
      /* крыша серее короба и с двумя люками: светлая гладкая плита под прямым светом выгорала в белое пятно */
      K.box(-12.4,10.4,-4.6,4.6,3.4,4.4,.8,C([204,198,184]),3,SP);
      for(const x0 of [-8,1.5])K.box(x0,x0+3.4,-1.8,1.8,4.4,4.95,.25,C([132,134,138]),3,SP);
      K.box(-13.08,11.08,-5.5,5.5,-1.6,.2,.1,C([200,64,47]),3,SP);
      K.box(-13.6,-12.8,-4.8,4.8,-4.2,-1.8,.2,C([30,32,36]),3,SP);K.box(10.8,11.6,-4.8,4.8,-4.2,-1.8,.2,C([30,32,36]),3,SP);
      /* окна — тёмное стекло с тёплым огнём внутри: кремовый огонь на кремовом коробе пропадал */
      for(const s of [-1,1])for(let i=0;i<5;i++){const x0=-10.5+i*4.2;win(x0,x0+3,s*5.46,.5,3,glass,0);win(x0+.5,x0+2.5,s*5.5,.9,2.6,C(RAIL_WIN),.55);}
      K.face([[11.06,-3.6,.6],[11.06,3.6,.6],[11.06,3.6,3],[11.06,-3.6,3]],[0,0,0],glass,3,-.1,0);   /* лобовое */
      K.face([[11.1,-2.2,3.05],[11.1,2.2,3.05],[11.1,2.2,4.1],[11.1,-2.2,4.1]],[0,0,0],C([242,178,92]),3,-.1,1.2);
      L.push({x:11.4,y:-3.4,z:-2.4,c:[255,244,214],r:.8,g:5,a:.4},{x:11.4,y:3.4,z:-2.4,c:[255,244,214],r:.8,g:5,a:.4},
        {x:-13.5,y:-3.6,z:-2.4,c:[255,70,50],r:.6,g:3,a:.3},{x:-13.5,y:3.6,z:-2.4,c:[255,70,50],r:.6,g:3,a:.3});
    }else{
      /* вагон: капсула вращения, нос скруглён, корма — торец с переходом; по борту лента окон
         и полоса цвета линии под ней (по ней род линии узнаётся издали, как прежде по цвету линии) */
      const P=[[0,3.2],[.5,4.2],[1.2,4.6],[20,4.6],[21.6,4.3],[23.2,3.5],[24.3,2.2],[24.9,.4]];
      K.lathe(-13,0,0,P,C(RAIL_CREAM),3,SP,0,18,[C([60,62,68]),SP,0],null);
      const lc=C(mixc(RAIL_COL[kind]||RAIL_COL.radial,[0,0,0],.12)),r=4.66;
      for(const s of [-1,1]){
        /* ленты стоят на окружности сечения: окна — от 35° до 62° над бортом, полоса — от 18° до 30° */
        const at=(x,deg)=>{const t=deg*Math.PI/180;return [x,s*Math.cos(t)*r,Math.sin(t)*r];};
        const band=(x0,x1,d0,d1,c,em)=>K.face([at(x0,d0),at(x1,d0),at(x1,d1),at(x0,d1)],[(x0+x1)/2,0,0],c,3,-.1,em);
        /* стекло — узкой тёмной лентой, окна в ней — редкими огоньками: широкая лента тёплых окон
           заливала весь ближний борт янтарём, и вагон читался рыжей палочкой, а не телом */
        band(-11.4,9.6,42,58,glass,0);
        for(let i=0;i<7;i++){const x0=-10.4+i*2.9;band(x0,x0+1.3,45,55,C(RAIL_WIN),.6);}
        band(-12.2,10.4,22,32,lc,.1);
      }
      L.push({x:11.95,y:0,z:0,c:[255,244,214],r:1,g:6,a:.45},{x:-13.1,y:0,z:0,c:[255,70,50],r:.6,g:3,a:.3});
    }
    const m=h3dPack(K.V,14,{st:[[13,.3],[-13,.3]],ne:2.2,kh:.5,gl:.5});
    m.L=L;return m;});
}
/* огни вагона поверх тела: точки сетки (x,y,z) — тем же креном и курсом, что у h3d rot */
function railCarLights(pass,m,x,y,a,sc,roll){
  const ca=Math.cos(a),sa=Math.sin(a),cb=Math.cos(roll),sb=Math.sin(roll),D=[],A=[];
  for(const q of m.L){const y1=q.y*cb-q.z*sb,px=x+(q.x*ca-y1*sa)*sc,py=y+(q.x*sa+y1*ca)*sc,r=Math.max(.7,q.r*sc);
    D.push([1,px,py,r,0,0,0,q.c[0],q.c[1],q.c[2],.95]);A.push([1,px,py,r*.5,0,0,q.g*sc,q.c[0],q.c[1],q.c[2],q.a]);}
  gpuShapes(pass,D);gpuShapes(pass,A,{blend:"add"});
}
/* вагон на экран: tx,ty — место, a — курс, cell — пикселей на сектор, (wx,wy) — место в секторах (свет к ядру) */
function railCarDraw(pass,R,tx,ty,a,cell,wx,wy){
  if(!bodyGpu())return;
  const T=bodyT0();if(!T)return;
  const m=railCarMesh(R.l.kind,!!R.bus),sc=clamp(cell*.7,26,50)/RAIL_CAR_LEN,[lx,ly]=sysLightDir(wx,wy);
  /* маршрутку качает на выбоинах, как прежнюю метку */
  const ang=R.bus?a+Math.sin(G.t*.31)*.05:a;
  /* крыша при крене b уходит по экрану в −sin b·(ось борта); ось борта — (−sin a, cos a) */
  const d=-Math.sin(ang)*lx+Math.cos(ang)*ly,roll=lx||ly?-RAIL_CAR_ROLL*clamp(d*3,-1,1):RAIL_CAR_ROLL;
  if(h3dRun(m,T,tx,ty,ang,sc,roll,lx,ly,null,0,null,null,RAIL_CORE_LIGHT))railCarLights(pass,m,tx,ty,ang,sc,roll);
}
/* остановка — огонёк тела: тор с дугой к свету, лампа в середине; пересадка — тор в торе.
   done — пройденная: дуга и лампа гаснут, тор остаётся. (lx,ly) — к ядру; [0,0] — свет ровный сверху */
function railStopShapes(SH,AD,x,y,jn,done,lx,ly){
  const R=jn?6:4.5,k=done?.42:1,lit=Math.hypot(lx,ly)>0,ph=Math.atan2(ly,lx);
  const torus=r=>{
    SH.push([3,x,y,r+.9,0,.55,.4,6,8,12,.7],[3,x,y,r,0,1.5,.5,64,70,82,.95]);
    /* освещённая дуга: короткие отрезки по стороне к свету; без стороны — кольцо целиком, тише */
    if(!lit){SH.push([3,x,y,r,0,.7,.4,236,232,220,.5*k]);return;}
    const n=7;for(let i=0;i<n;i++){const t0=ph-1.15+i/n*2.3,t1=ph-1.15+(i+1)/n*2.3,w=1-Math.abs((i+.5)/n-.5)*1.4;
      SH.push([2,x+Math.cos(t0)*r,y+Math.sin(t0)*r,x+Math.cos(t1)*r,y+Math.sin(t1)*r,.75,.4,240,236,222,.9*w*k]);}};
  torus(R);if(jn)torus(2.6);
  if(done){SH.push([1,x,y,1,0,0,.4,150,150,150,.35]);return;}
  SH.push([1,x,y,1.3,0,0,.4,255,236,200,.95]);AD.push([1,x,y,.7,0,0,4.5,255,226,170,.4]);
}
