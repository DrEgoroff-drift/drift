/* цилиндр по оси y (или x/z): n граней, крышки; нормали наружу */
function sectCyl(m,c,r,h,axis,col,mat,glow,n){
  n=n||10;const P=(a,t)=>{const u=Math.cos(a)*r,v=Math.sin(a)*r;
    return axis==="x"?[c[0]+t,c[1]+u,c[2]+v]:axis==="z"?[c[0]+u,c[1]+v,c[2]+t]:[c[0]+u,c[1]+t,c[2]+v];};
  const N=a=>{const u=Math.cos(a),v=Math.sin(a);return axis==="x"?[0,u,v]:axis==="z"?[u,v,0]:[u,0,v];};
  for(let i=0;i<n;i++){
    const a0=i/n*Math.PI*2,a1=(i+1)/n*Math.PI*2,am=(a0+a1)/2;
    sectQuad(m,P(a0,0),P(a1,0),P(a1,h),P(a0,h),N(am),col,mat,glow);
  }
  const ax=axis==="x"?[1,0,0]:axis==="z"?[0,0,1]:[0,1,0],cap=(t,s)=>{
    const o=axis==="x"?[c[0]+t,c[1],c[2]]:axis==="z"?[c[0],c[1],c[2]+t]:[c[0],c[1]+t,c[2]];
    for(let i=0;i<n;i++){const a0=i/n*Math.PI*2,a1=(i+1)/n*Math.PI*2;
      sectQuad(m,o,P(a0,t),P(a1,t),o,plnMul(ax,s),col,mat,glow);}
  };
  cap(0,-1);cap(h,1);
}

