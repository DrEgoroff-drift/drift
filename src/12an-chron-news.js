/* ── сроки по-человечески ──
   Четыре сводки — сутки. Переводим в речь, потому что «шестнадцать сводок» —
   это единица измерения канцелярии, а не человека. */
function newsSpan(n){
  n=n|0;
  const d=n/4;
  if(n<=2)return "до вечера";
  if(d<=1)return "сутки";
  if(d<=2)return "двое суток";
  if(d<=3)return "трое суток";
  if(d<=4)return "четверо суток";
  if(d<=5)return "пять суток";
  if(d<=7)return "неделю";
  if(d<=10)return "десять суток";
  return Math.round(d)+" суток";
}
