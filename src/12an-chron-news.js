/* ── заметка целиком ──
   Три доли, из которых вторая обязана быть правдой. Пустые доли выпадают: у
   события без последствия остаются подробность и голос, и это честнее, чем
   выдуманное «влияет на цены». */
function newsOf(L,st){
  if(!L)return "";
  const sys=newsSysOf(L,st);
  const out=[];
  const s=newsScene(L,sys);if(s)out.push(newsSent(s));
  const c=newsCost(L);if(c)out.push(newsSent(c));
  const t=newsTail(L);if(t)out.push("«"+t+"»");
  return out.slice(0,NEWS_LINES).join(" ");
}
