    box(-3.5,3.5,7.2,7.8,-.3,.3,.1,shoe,3,.5);
    tube([[0,6,0],[0,7.2,0]],.3,g,3,.4,6);
    for(let i=0;i<4;i++){const t=i/4*TAU;
      box(Math.cos(t)*4.2-.2,Math.cos(t)*4.2+.2,6.8,7.4,Math.sin(t)*4.2-.2,Math.sin(t)*4.2+.2,.05,blk,3,.55);}
    for(const s of[-1,1])box(s*3.2,s*3.8,5.8,6.4,-.4,.4,.08,blk,3,.55);
    for(let i=0;i<6;i++){const t=i/6*TAU;
      box(Math.cos(t)*3.9-.15,Math.cos(t)*3.9+.15,-.2,.4,Math.sin(t)*3.9-.15,Math.sin(t)*3.9+.15,.04,blk,3,.6);}
    for(let i=0;i<4;i++){const t=i/4*TAU;
      box(Math.cos(t)*3.9-.12,Math.cos(t)*3.9+.12,5.2,5.8,Math.sin(t)*3.9-.12,Math.sin(t)*3.9+.12,.04,blk,3,.55);}
