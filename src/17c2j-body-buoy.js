/* бакен на месте спрайта: a — курс (поперёк полосы), s — масштаб экрана */
function bodyBuoy(x,y,a,s,wx,wy){
  if(!bodyGpu())return false;
  const m=bodyBuoyMesh(),sc=s*(LANE_BUOY.R/(m.R||14));
  if((m.len||24)*sc<BODY.LOD){bodyDot(x,y,[59,69,83],wx,wy,1);return true;}
  return bodyRun(m,x,y,a,sc,wx,wy,0);
}
