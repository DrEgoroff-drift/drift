    box(-.2,.2,-5,6,-3.8,-3.2,.08,lit,3,.7);
    for(let i=0;i<4;i++)box(-.3,.3,0,2.2,-4+i*2,-4+i*2+2.0,.08,i%2?yel:blk,3,.55);
    box(-.25,.25,3.2,4.6,-1.2,1.2,.1,cat,3,.4);
    box(-.6,.6,4.0,4.8,-4.0,-3.4,.08,blk,3,.55);
