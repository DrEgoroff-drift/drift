function holMap(){if(!G.hol||typeof G.hol!=="object")G.hol={};return G.hol;}
/* какой сегодня праздник по НАСТОЯЩЕМУ календарю игрока */
function holNow(at){
  const d=at?new Date(at.getTime()):new Date();
  const m=d.getMonth()+1, day=d.getDate();
  for(const h of HOLIDAYS){
    const [fm,fd]=h.from,[tm,td]=h.to;
    /* праздник через новый год: декабрь-январь — один отрезок, а не два */
    const inSpan=(fm<tm||(fm===tm&&fd<=td))
      ? ((m>fm||(m===fm&&day>=fd))&&(m<tm||(m===tm&&day<=td)))
      : ((m>fm||(m===fm&&day>=fd))||(m<tm||(m===tm&&day<=td)));
    if(inSpan)return h;
  }
  return null;
}
function holIs(id){const h=holNow();return !!(h&&h.id===id);}
function holTreeUp(){const h=holNow();return !!(h&&h.tree);}
/* строка в эфир: приёмник подмешивает её к обычным голосам (25e) */
function holEtherLine(){
  const h=holNow();if(!h)return "";
  const L=HOL_ETHER[h.id]||[];
  if(!L.length)return "";
  const r=rng(hashi(Math.floor(Date.now()/60000),h.id.length,0x0801));
  return L[Math.floor(r()*L.length)];
}
/* ── радиограммы ──
   Раз в год, при первой стыковке в праздник. Поздравляют те, кто есть в
   книжке: их имена уже написаны, придумывать некого. */
function holDock(){
  const h=holNow();if(!h)return false;
  const d=new Date();
  const year=d.getMonth()+1>=7?d.getFullYear():d.getFullYear()-1;   /* год ПРАЗДНИКА, а не календаря */
  const key=(h.id==="ny"?year:d.getFullYear())+":"+h.id;
  const M=holMap();
  if(M[key])return false;
  M[key]=1;
  const R=(typeof recordAll==="function")?recordAll():{e:[]};
  /* поздравляют ЛЮДИ. Учреждения из книжки вычеркнуты — и сам праздник тоже:
     он оставляет в книжке строку от своего имени, и на следующий год «Новый
     год» слал поздравление сам себе. Поймано тестом на число радиограмм. */
  const bad=/^(медкомиссия|санаторий|вымпел|лаборатория|зимовка|институт)/i;
  const hols=HOLIDAYS.map(x=>x.ru);
  const who=[];
  for(const e of (R.e||[]))
    if(!bad.test(e.a)&&hols.indexOf(e.a)<0&&who.indexOf(e.a)<0)who.push(e.a);
  const L=HOL_GREET[h.id]||[];
  const r=rng(hashi(year,h.id.length*7,0x0901));
  let n=0;
  for(const a of who.slice(0,6)){
    const line=L[Math.floor(r()*L.length)];
    thingAdd("letter","Радиограмма · "+a,line,{hol:h.id});
    n++;
  }
  if(n)logAdd("good",h.ru+": радиограмм "+n+" · на столе");
  else logAdd("dim",h.ru+". Поздравить вас пока некому.");
  /* мандарины бывают только на Новый год и только если баржа дошла */
  if(h.id==="ny"&&r()<.8)
    thingAdd("find","Мандарины · полсетки","привезли баржой · пахнут так, что слышно в коридоре",{hol:"ny"});
  recordAdd(h.ru,n?("встречен в рейсе · радиограмм "+n):"встречен в рейсе");
  tell("good",h.ru,h.ru.toUpperCase()+(n?"\nРАДИОГРАММ "+n:"")+"\nна столе");
  if(typeof parrotHas==="function"&&parrotHas()&&h.id==="ny")
    logAdd("dim","Попугай нашёл мандарин и унёс. Отдавать не собирается.");
  return true;
}
/* ── ёлка ──
   Одна функция на все места, где она стоит: кантина и дом. Не пирамида из
   треугольников — три яруса лап разной ширины, ствол виден снизу, игрушки
   висят НА лапах, а не парят рядом, и фольга ловит тот свет, что в комнате. */
function holTree(c,x,fy,hh,acc){
  const w=hh*0.52;
  c.fillStyle="rgba(0,0,0,.30)";
  c.beginPath();c.ellipse(x,fy+2,w*0.42,hh*0.035,0,0,TAU);c.fill();
  /* крестовина и ствол */
  c.fillStyle="rgba(96,72,50,.95)";
  c.fillRect(x-w*0.06,fy-hh*0.14,w*0.12,hh*0.14);
  c.fillRect(x-w*0.20,fy-hh*0.03,w*0.40,Math.max(2,hh*0.030));
  /* три яруса лап, снизу шире */
  for(let i=0;i<3;i++){
    const q=i/2;
    const bw=w*(1-q*0.42), by=fy-hh*(0.14+q*0.30), bh=hh*0.34;
    c.fillStyle=i%2?"rgba(58,102,64,.96)":"rgba(70,118,74,.96)";
    c.beginPath();
    c.moveTo(x,by-bh);
    c.lineTo(x+bw*0.5,by);
    /* нижняя кромка лапы зубчатая: ровный треугольник читается пирамидкой */
    for(let k=4;k>=0;k--){
      const t2=k/5;
      c.lineTo(x-bw*0.5+bw*t2,by-((k%2)?bh*0.06:0));
    }
    c.lineTo(x-bw*0.5,by);
    c.closePath();c.fill();
    c.fillStyle="rgba(255,255,255,.07)";
    c.beginPath();
    c.moveTo(x,by-bh);c.lineTo(x+bw*0.5,by);c.lineTo(x+bw*0.12,by);
    c.closePath();c.fill();
  }
  /* игрушки: висят на кромках лап */
  const r=rng(hashi(x|0,fy|0,0x0E1C));
  for(let i=0;i<9;i++){
    const q=r();
    const bw=w*(1-q*0.42);
    const bx=x+(r()-0.5)*bw*0.86;
    const by=fy-hh*(0.16+q*0.60);
    c.fillStyle=["rgba(214,84,64,.95)","rgba(228,190,90,.95)","rgba(120,168,214,.95)"][i%3];
    c.beginPath();c.arc(bx,by,Math.max(1.6,hh*0.026),0,TAU);c.fill();
    c.fillStyle="rgba(255,255,255,.45)";
    c.beginPath();c.arc(bx-hh*0.008,by-hh*0.008,Math.max(1,hh*0.009),0,TAU);c.fill();
  }
  /* фольга: две нити наискось, ловят свет комнаты */
  c.strokeStyle=acc||"rgba(232,214,150,.55)";
  c.lineWidth=Math.max(1,hh*0.012);
  for(const s of [0,1]){
    c.beginPath();
    c.moveTo(x-w*0.42+s*w*0.2,fy-hh*0.30-s*hh*0.22);
    c.quadraticCurveTo(x,fy-hh*0.42-s*hh*0.20,x+w*0.42-s*w*0.2,fy-hh*0.28-s*hh*0.24);
    c.stroke();
  }
  /* звезда */
  c.fillStyle="rgba(240,214,120,.95)";
  c.beginPath();
  for(let i=0;i<10;i++){
    const a=-Math.PI/2+i*Math.PI/5, rr=i%2?hh*0.030:hh*0.062;
    const px=x+Math.cos(a)*rr, py=fy-hh*0.80+Math.sin(a)*rr;
    i?c.lineTo(px,py):c.moveTo(px,py);
  }
  c.closePath();c.fill();
}
