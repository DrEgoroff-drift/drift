/* ══════════════ «Тихоня»: подарок, которого никто не считал ══════════════
   M231, часть VIII дуги — конец. «Долги возвращаются не в том порядке, не тем
   способом и без слова "долг"» (docs/saga/ДУГА.md §6).

   Однажды, поздно, у причала вашего дома стоит яхта. В замке ключ. Записки
   нет. Всё.

   ОТКУДА ОНА. Платит тетрадь доброты (11ai) — то, что сделано даром и без
   свидетелей, взвешенное бедностью в момент поступка. Игрок об этом не узнает
   НИКОГДА: ни строки, ни намёка, ни «за что». Правда этой игры не
   произносится (правило 4 дуги) — если где-то появится фраза, из которой
   следует, что яхту оставили за доброту, её надо вычеркнуть вместе со сценой.

   ПРАВИЛА (docs/DESIGN-arc.md, правило 5 — дословно):
   1. У подарка нет цены. Она нигде не показывается, потому что её нет.
   2. Его нельзя продать. Корпуса в этой игре не продаются вовсе — и это
      единственный корпус, для которого это устройство мира, а не ограничение.
   3. Мир не поздравляет. Строка в журнале — плоская: яхта стоит, ключ в
      замке. Никакого «вы заслужили».

   КОГДА. Три условия, и все три — про прожитую жизнь, а не про счёт:
   тетрадь полна (несколько настоящих поступков с настоящим весом), прошёл
   год со старта, и есть дом — потому что оставить её больше негде.
   Приходит по прилёте в родной сектор: подарок застают, а не получают. */

const GIFT_DEEDS=5;        /* поступков — не меньше */
const GIFT_W=260;          /* суммарный вес: несколько настоящих, не мелочь */
const GIFT_DAY=365;        /* год прожитой жизни, раньше — рано */

function giftDue(){
  if(G.uniqueShips&&G.uniqueShips.gift1)return false;      /* уже стоит */
  /* то же окно, но названное вслух в одном месте со всеми (P8, M416): числа
     здесь свои и прежние, сторож их только повторяет */
  if(typeof clockOpen==="function"&&!clockOpen("gift"))return false;
  const L=(typeof ledgerAll==="function")?ledgerAll():null;
  if(!L||(L.n|0)<GIFT_DEEDS||(L.w||0)<GIFT_W)return false;
  if(celDay()<GIFT_DAY)return false;
  const H=G.home;
  if(!H||!H.tier||H.sx===undefined)return false;
  return true;
}
/* по прилёте в сектор дома: её застают у причала */
function giftArrive(){
  if(!giftDue())return false;
  const H=G.home;
  if(G.sx!==H.sx||G.sy!==H.sy)return false;
  /* сама яхта: люкс по устройству (tier) и по классу (yacht) — лак, тик,
     латунь и имя вместо номера рисует 03c по этим двум полям */
  const seed=hashi(H.sx,H.sy,0x71C0)>>>0;
  G.uniqueShips.gift1={
    ru:"Тихоня",cls:"яхта",hcls:"yacht",tier:"luxe",seed,
    thr:1.1,turn:1.15,fuel:150,cargo:120,hull:188,price:0,
    col:"#e0d28a",unique:1,gift:1,
    note:"стояла у вашего причала. В замке был ключ. Записки не было."
  };
  G.owned.gift1=true;
  /* мир не поздравляет: строка плоская, вещь на столе — тоже */
  logAdd("dim","У причала стоит яхта. В замке ключ. Записки нет.");
  if(typeof thingAdd==="function")
    thingAdd("paper","Ключ от яхты","лежал в замке. «Тихоня». Чья была — никто не говорит.");
  if(typeof say==="function")say("У причала — яхта.\nВ замке ключ. Записки нет.",420);
  return true;
}
