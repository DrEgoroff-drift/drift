/* ══════════════ корабль стареет ══════════════
   Гараж (M93) стоял без дела: домой не за чем было возвращаться, потому что
   корпус приходил в негодность только в бою, а бой чинят на любой станции за
   четырнадцать кредитов. Корабль ничего не помнил о прожитых часах.

   Здесь у корпуса появляется НАЛЁТ. Он копится сам, от часов в полёте, и быстрее
   там, где грязно: пояс точит абразивом, шахта пылит, атмосфера газового гиганта
   травит краску. Налёт видно — потёртости, пылевые дорожки, выгоревшая на солнце
   полоса, — и он немного стоит: изношенная машина хуже слушается руля и тяги.

   Чинить и обслуживать — разные вещи, и это главное правило этой вехи. Станция
   латает пробоины (`repairCost`), но налёт снимают только руками и с временем:
   на верфи за деньги и наполовину, дома в гараже — до чистого и бесплатно, потому
   что дом не берёт денег (правило M83). Домой возвращаются не потому, что
   сломалось, а потому, что накопилось. */
const WEAR_FULL=180*60*60;      /* кадров полёта до полного износа: три часа за рулём */
/* Где корабль пачкается быстрее: не «сложность режима», а грязь вокруг него */
const WEAR_RATE={system:1,map:0,dock:0,belt:1.7,dig:1.5,cave:1.2,scoop:2.1,
                 landing:1.3,surface:.4,base:0,raid:0,barge:.6};
function wearAll(){if(!G.wear||typeof G.wear!=="object")G.wear={};return G.wear;}
/* Налёт живёт на КОРПУСЕ, а не на игроке: пересесть на второй корабль — это
   способ дать первому постоять, а не обнулить его историю */
function wearOf(id){
  return clamp((wearAll()[id||G.shipId]||0)/WEAR_FULL,0,1);
}
function wearTick(dt){
  const r=WEAR_RATE[G.mode];
  if(!r)return;
  if(typeof quietNoWear==="function"&&quietNoWear())return;   /* тихий уезд (11n): машины не ломаются */
  const W=wearAll(),id=G.shipId;
  W[id]=(W[id]||0)+dt*r;
}
/* Цена износа: рулёжка и тяга. Не корпус и не топливо — облезлая машина
   слушается хуже, а не разваливается; потолок в 12% заметен рукой и никогда
   не превращает полёт в наказание. */
function wearMul(){return 1-.12*wearOf();}
const WEAR_RU=[[.12,"свежий"],[.35,"запылённый"],[.6,"потёртый"],[.85,"выгоревший"],[2,"облезлый"]];
function wearRu(w){
  w=(w===undefined)?wearOf():w;
  for(const [t,ru] of WEAR_RU)if(w<t)return ru;
  return"облезлый";
}
function wearLine(id){
  const w=wearOf(id);
  return"НАЛЁТ "+Math.round(w*100)+"% · "+wearRu(w).toUpperCase()+
    (w>.12?" · РУЛЬ И ТЯГА −"+Math.round(12*w)+"%":"");
}
/* Обслуживание. `part` — доля, которую снимают: гараж дома снимает всё и не
   берёт ничего. Верфь работает не долей, а ПОЛОМ — `wearServiceTo` ниже. */
function wearService(part,id){
  id=id||G.shipId;
  const W=wearAll(),before=wearOf(id);
  if(before<=0)return 0;
  W[id]=Math.max(0,(W[id]||0)*(1-clamp(part,0,1)));
  return before-wearOf(id);
}
/* ── пол верфи (M235) ──
   Верфь снимала ПОЛОВИНУ налёта, а нажать можно было сколько угодно раз:
   100 → 50 → 25 → 12 → 6, пять кнопок и пять с половиной тысяч кредитов —
   и корабль чист. То есть правило «до чистого доводят только дома» покупалось
   деньгами, а вместе с ним пропадал и повод возвращаться домой (автор поймал
   это на второй вечер игры). Теперь у верфи есть ПОЛ: ниже него она не берётся
   никогда, сколько ни плати. Пол зависит от того, куда ты пришёл: настоящая
   верфь доводит почти до свежего, торговый узел — до трети, а в глуши руки
   хуже везде — тот же градиент, на котором в игре стоит всё остальное.
   Полом же снимается и второй страх: летать облезлым не придётся — на 30%
   налёта руль и тяга теряют 3.6%, это не наказание, а повод однажды заехать
   домой, где снимут до нуля и не возьмут денег. */
function wearFloor(sys){
  sys=sys||G.sys;
  const st=(G.st&&G.st.stype)||(sys&&sys.station&&sys.station.stype)||"trade";
  const base=(st==="yard")?.18:(st==="indust"?.38:.32);
  const d=(typeof sysDanger==="function"&&sys)?sysDanger(sys.sx,sys.sy):0;
  return clamp(base+d*.18,.15,.5);
}
/* Снять налёт до пола: возвращает снятое. Ниже пола не идёт — второе нажатие
   не делает ничего и поэтому кнопки под него уже нет. */
function wearServiceTo(floor,id){
  id=id||G.shipId;
  const W=wearAll(),before=wearOf(id);
  floor=clamp(floor,0,1);
  if(before<=floor)return 0;
  W[id]=floor*WEAR_FULL;
  return before-floor;
}
/* Цена верфи считается от того, сколько налёта снимут: платить за полировку
   свежего корабля игрок не должен, и кнопка это показывает числом. */
function wearYardCost(){
  const w=wearOf(),f=wearFloor();
  return w<=f+.02?0:Math.round(140+(w-f)*2600*(typeof repShipMul==="function"?repShipMul(G.sys):1));
}
/* ── налёт на кадре ──
   Рисуется ВНУТРИ обрезки по корпусу (`drawHull`), поэтому ни одна царапина не
   выходит за силуэт. Всё детерминировано от seed корпуса: корабль обязан
   стареть одинаково от кадра к кадру, иначе это не износ, а рябь.
   Три слоя и ровно в таком порядке: выгорание краски (большое и мягкое),
   пылевые дорожки по потоку (длинные), задиры и сколы (мелкие и последние) — от
   общего к частному, как и всё остальное в этой графике. */
function drawWear(h,w){
  if(w<=.02)return;
  const R=rng(hashi(h.seed||1,0x9E17,5));
  const L=h.len,bw=h.bw;
  ctx.save();
  /* Первый проход красил корабль ровным серым по всему борту: на трети налёта
     разведчик уже терял свой цвет и делался цементным. Налёт СОБИРАЕТСЯ ПО
     МЕСТАМ, а не покрывает: выгорает верх, куда бьёт свет (тот же верх, где у
     корпуса блик, — свет в кадре один), пылевые дорожки тянутся по потоку от
     носа к корме, копоть садится у сопел. Между этими тремя местами краска
     остаётся краской. */
  /* ── выгорает КРАСКА, а не корпус ──
     Мягкая пелена поверх борта не читалась ничем, кроме тумана: на полётном
     масштабе корабль был неотличим от свежего. Выгорать должно то, что и есть
     окраска, — продольная полоса цвета: с часами она садится к цвету борта, и
     корабль теряет опознавательный знак раньше, чем обзаводится царапинами.
     Это видно и в кадре размером с ноготь. */
  const P=h.prof,S1=h.stripe;
  if(P&&S1){
    const i0=Math.floor(S1.from*(P.length-1)),i1=Math.ceil(S1.to*(P.length-1));
    ctx.beginPath();
    for(let i=i0;i<=i1;i++)ctx.lineTo(P[i][0],-P[i][1]*S1.a);
    for(let i=i1;i>=i0;i--)ctx.lineTo(P[i][0],-P[i][1]*S1.b);
    ctx.closePath();
    ctx.fillStyle=rgba(h.body,(.75*w).toFixed(3));ctx.fill();
    /* поверх выцветшей полосы — тёплая пыль: краска не просто темнеет,
       она пылится, и это единственное тёплое пятно на холодном корпусе */
    ctx.fillStyle="rgba(196,182,158,"+(.10*w).toFixed(3)+")";ctx.fill();
  }
  /* выгорание сверху, куда бьёт свет: слабое, только чтобы верх не остался
     единственным чистым местом */
  const sg=ctx.createLinearGradient(0,-bw,0,0);
  sg.addColorStop(0,"rgba(214,202,178,"+(.09*w).toFixed(3)+")");
  sg.addColorStop(1,"rgba(214,202,178,0)");
  ctx.fillStyle=sg;ctx.fillRect(h.tail,-bw,L,bw);
  /* пылевые дорожки: длинные, тонкие и вдоль потока. Толстые короткие мазки
     первого прохода читались смазанной грязью на стекле, а не следом хода */
  const nd=Math.round(4+w*14);
  ctx.lineCap="round";
  for(let i=0;i<nd;i++){
    const x=h.tail+R()*L*.9,len=L*(.18+R()*.34);
    /* прижаты к бортам: середина борта обдувается, грязь держится у рёбер */
    const y=(R()<.5?-1:1)*bw*(.45+R()*.5);
    ctx.strokeStyle="rgba(26,22,17,"+(.05+.13*w*R()).toFixed(3)+")";
    ctx.lineWidth=.35+R()*.5;
    ctx.beginPath();ctx.moveTo(x,y);
    ctx.lineTo(Math.max(h.tail,x-len),y+(R()*2-1)*.8);
    ctx.stroke();
  }
  /* задиры: светлый металл из-под краски, и только по передней кромке — там,
     куда прилетает пыль на ходу. По всему борту они читались снегом */
  if(w>.25){
    const ns=Math.round((w-.25)*26);
    for(let i=0;i<ns;i++){
      const x=h.nose-R()*L*.45,y=(R()<.5?-1:1)*bw*(.3+R()*.65);
      ctx.strokeStyle="rgba(232,238,242,"+(.07+.20*R()*w).toFixed(3)+")";
      ctx.lineWidth=.35+R()*.5;
      ctx.beginPath();ctx.moveTo(x,y);ctx.lineTo(x-1-R()*3,y+(R()*2-1)*1.2);ctx.stroke();
    }
  }
  /* копоть у сопел — единственная грязь, которую корабль делает сам */
  if(w>.45){
    const cg=ctx.createLinearGradient(h.tail,0,h.tail+L*.26,0);
    cg.addColorStop(0,"rgba(10,8,8,"+(.30*w).toFixed(3)+")");
    cg.addColorStop(1,"rgba(10,8,8,0)");
    ctx.fillStyle=cg;ctx.fillRect(h.tail,-bw,L*.26,bw*2);
  }
  ctx.lineCap="butt";
  ctx.restore();
}
