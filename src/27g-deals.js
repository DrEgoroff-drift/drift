/* ── кто сегодня за столиками ──
   Двое-трое на станцию, детерминированно по seed и бакету. Один и тот же
   человек не сидит вечно: ушли и вернулись — другие дела. */
function stationDeals(sys){
  if(!sys||!sys.station)return [];
  const r=rng(hashi(sys.seed,0xDEA1,timeBucket()));
  /* Своим предлагают больше: репутация станции добавляет столик и убирает его
     у тех, кого тут не ждут. Это единственное, чем репутация правит кантину, —
     содержание дел она не трогает, иначе вышла бы «прокачка доступа». */
  const rep=(typeof repAt==="function")?repAt(sys):0;
  const n=clamp(1+Math.floor(r()*2.4)+(rep>=3?1:0)-(rep<=-3?1:0),1,4);
  const out=[],used={};
  for(let i=0;i<n*4&&out.length<n;i++){
    const D=DEAL_KINDS[(r()*DEAL_KINDS.length)|0];
    if(used[D.id])continue;used[D.id]=1;
    const seed=hashi(sys.seed,D.id.length*977+i*131,timeBucket());
    out.push({key:sys.key+"|"+timeBucket()+"|"+D.id,def:D,seed,
      name:genName(rng(seed))});
  }
  return out;
}
function dealTaken(key){return !!(G.dealsDone&&G.dealsDone[key]);}
/* ── ответ ──
   Немедленная часть исполняется здесь же, отложенная уходит в журнал делом
   с адресом и сроком (`11a-quests`). Позже её закрывает `dealsTick`. */
function dealAnswer(d,i){
  const opt=d.def.opts[i];if(!opt)return false;
  if(opt.cost&&G.credits<opt.cost){say("Не хватает кредитов");return false;}
  if(!G.dealsDone)G.dealsDone={};
  G.dealsDone[d.key]=1;
  if(opt.cost){G.credits-=opt.cost;}
  if(opt.gain){earn(opt.gain,"deal");}
  if(opt.data){G.data+=opt.data;}
  /* поступок стоит отношения: поручиться — рискнуть именем, отказать — ничего */
  if(opt.rep)repAdd(opt.rep);
  tell("","«"+d.name+"»: "+opt.said,d.name+"\n— "+opt.said);
  if(opt.later){
    const L=opt.later;
    if(!G.dealsWait)G.dealsWait=[];
    const key="deal:"+d.key;
    G.dealsWait.push({key,at:Date.now()+L.mins*60000,odds:L.odds,
      good:L.good,bad:L.bad,ru:L.ru});
    questAdd(key,{ru:L.ru,kind:"deal",from:"кантина «"+G.st.name+"»",
      note:L.note,sx:G.sx,sy:G.sy,until:Date.now()+L.mins*60000,
      reward:"как выйдет: договаривались на слово"});
  }
  return true;
}
/* ── чем кончилось ──
   Исход решается броском, но бросок сделан ЗАРАНЕЕ (по ключу дела), а не в
   момент проверки: одно и то же дело не может кончиться по-разному от того,
   когда игрок открыл журнал. */
function dealsTick(){
  const w=G.dealsWait;if(!w||!w.length)return;
  const now=Date.now();
  for(let i=w.length-1;i>=0;i--){
    const d=w[i];
    if(now<d.at)continue;
    w.splice(i,1);
    const good=rng(hashi(d.key.length*7717,d.at&0xffff,0xD0))()<d.odds;
    const R=good?d.good:d.bad;
    if(R.credits>0)earn(R.credits,"deal");
    else if(R.credits<0)G.credits=Math.max(0,G.credits+R.credits);
    if(R.hull)G.hull=Math.max(1,G.hull+R.hull);
    if(R.crew&&typeof crewGift==="function")crewGift();
    if(R.node&&typeof nodeDrop==="function")nodeDrop(R.node,.6,hashi(d.at,7,3));
    /* чем кончилось — тем и запомнят: удачное дело красит имя, провал портит */
    repAdd(good?1:-1);
    if(good)questDone(d.key,R.say);else questFail(d.key,R.say);
    tell(good?"good":"warn",R.say,R.say);
  }
}
