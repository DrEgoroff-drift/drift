/* ══════════════ тишина: двери закрыты, мир предлагает ══════════════
   M230, часть IV/VII дуги («Счёт», «Тишина»): доигрывание того, что M226
   начал. Двери закрываются по одной (folkShut), мир продолжает предлагать
   холодное — это уже так. Не хватало ДВУХ вещей, которыми это состояние
   слышно, и обе — по книге (docs/saga/ДУГА.md §6):

   ТИШИНА. «Не назван никем. Работы столько же.» Когда закрыты три двери и
   больше, у стойки изредка называют — но не тебя: «Петровича борт? Нет?
   Ладно, жду Петровича». Игрок слышит, как именование происходит РЯДОМ, и
   в этом всё: ни числа, ни упрёка, ни слова о нём самом. Одиночество имеет
   право быть только в этой части — поэтому строки не звучат, пока дверей
   меньше трёх.

   ОДИН, КТО СКАЖЕТ ПРЯМО. Правило дуги: «Никто не упрекает. Ровно один
   персонаж говорит это в лицо, и он неправ». Часть VI, «Раскол»: раз за всю
   игру, в кантине, человек у стойки говорит: «Вы просто не тянете». Игра
   его не подтверждает НИЧЕМ: ни числом, ни последствием, ни строкой в
   журнале — потому что он неправ, а узнать это можно, только прожив ещё
   лет пять.

   ПРАВИЛА ФАЙЛА:
   1. Правда не произносится: нигде не написано «вас перестали называть».
   2. Счётчик дверей не показывается никому и нигде.
   3. Хранится только G.toldOff — что тот один уже сказал. */

/* сколько дверей закрыто: считается по памяти людей, не хранится */
function doorsShut(){
  const F=(typeof folkAll==="function")?folkAll():{};
  let n=0;for(const k in F)if(F[k]&&F[k].shut)n++;
  return n;
}
function worldQuiet(){return doorsShut()>=3;}
/* строки, в которых называют не тебя. Никогда — о тебе */
const QUIET_LINES=[
  "— Петровича борт? Не Петровича. Ладно, жду Петровича.",
  "— Соболеву скажи, что его ждут на третьем. Соболеву, говорю. А, вы не к нему.",
  "— Кто от Тарасова — без очереди. Остальные по списку.",
  "— «Крапиву» ждём. Она обещала. Она всегда обещала — и всегда приходила.",
  "— Это не тот борт. Тот придёт позже, его встретят."
];
/* реплика тишины: втискивается в очередь у стойки не чаще каждой третьей
   посадки, и только когда мир затих. Возвращает null, если говорить не время */
function quietDoorLine(){
  if(!worldQuiet())return null;
  const v=(typeof visitHere==="function")?visitHere():0;
  if(v%3!==1)return null;
  const r=rng(hashi(G.sx,G.sy,0xD00A+v)>>>0);
  return QUIET_LINES[Math.floor(r()*QUIET_LINES.length)];
}
/* ── тот один ──
   Раз за игру, в кантине, при затихшем мире. Строка стоит рядом с залом и
   исчезает навсегда после первого показа. Игра не подтверждает его ничем. */
function toldOffBlock(){
  if(typeof $body==="undefined"||!$body)return;
  if(G.toldOff||!worldQuiet())return;
  /* ── и своё окно (P8, M416) ──
     До сторожа сюда вело ровно одно условие — три закрытые двери, — а три
     двери можно закрыть в первый вечер. Самая тяжёлая реплика игры приходила
     раньше, чем в ней что-то прожито. Теперь она ждёт своего окна, молча и
     не истекая: часы `toldoff` в `11d-clocks`. */
  if(typeof clockOpen==="function"&&!clockOpen("toldoff"))return;
  G.toldOff=1;
  $body.appendChild(el("div","row","<div class='nm'><s style='color:#cfe3ea;line-height:1.9'>"+
    "Человек у стойки допил, поставил стакан и сказал, не поворачиваясь: "+
    "«Вы просто не тянете. Я таких видел». Заплатил и вышел.</s></div>"));
  if(typeof logAdd==="function")logAdd("talk","«Вы просто не тянете. Я таких видел»");
}
