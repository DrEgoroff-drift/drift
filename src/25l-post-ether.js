/* ══════════════ ночной эфир ══════════════
   M191. У приёмника (25e) четыре диапазона, и они всегда на месте. Пятый —
   ночная почта — на месте НЕ всегда: он появляется на самом низу шкалы после
   девяти вечера и пропадает к двум. Так ведут себя длинные волны на настоящем
   приёмнике, и так же должна вести себя вещь, ради которой стоит включить
   игру вечером.

   ВРЕМЯ ЗДЕСЬ НАСТОЯЩЕЕ, а не игровые сутки. Дорожный спутник (M168) уже
   доказал, что игра умеет жить в одном времени с человеком; окно по игровым
   суткам (минута каждые) не окно, а мигание. И только настоящий вечер даёт
   то, ради чего всё затевалось: в этот час никакого уведомления не нужно —
   ЭФИР И ЕСТЬ УВЕДОМЛЕНИЕ.

   КАРТОЧКУ НЕ ПОКАЗЫВАЮТ, ЕЁ ДОСЛУШИВАЮТ. Диктор читает её по строке, как
   читали телеграммы; уйти с волны на середине — значит не получить ничего.
   Дочитанная карточка ложится на стол стопкой, и ответ в ней уже открыт.

   ДВЕ ЗА ВЕЧЕР. Не потому, что жалко, а потому что третья обесценивает
   первую: вечер должен кончаться раньше, чем интерес.

   ПРАВИЛА ФАЙЛА:
   1. Ничего не хранится, кроме счёта за вечер. Читаемая карточка эфемерна:
      оборвалась связь — оборвалась и передача, как в жизни.
   2. Диапазона нет, когда нет ни ночи, ни сети. Пустой диапазон, который
      «иногда работает», — это сломанный приёмник, а не примета. */
const ETH_LO=0.02, ETH_HI=0.10;    /* самый низ шкалы: длинные волны */
const ETH_H0=21, ETH_H1=2;         /* с девяти вечера до двух ночи, по местным */
const ETH_CATCH=2;                 /* карточек за вечер */
const ETH_HOLD=2;                  /* тиков консоли на строку (тик ~секунда) */
let ethCard=null,ethLine=0,ethHold=0,ethAsk=0;

/* час можно подставить: иначе проверить окно можно было бы только вечером,
   то есть никогда — а окно тут вся веха */
function mailNight(h){
  h=(h==null)?new Date().getHours():h;
  return h>=ETH_H0||h<ETH_H1;
}
/* вечер считается по календарю ВЕЧЕРА, а не суток: час ночи принадлежит
   вчерашнему вечеру, иначе счёт «две за вечер» обнуляется в полночь и
   получается четыре */
function mailEve(at){
  const d=at?new Date(at.getTime()):new Date();
  if(d.getHours()<ETH_H1)d.setDate(d.getDate()-1);
  return d.getFullYear()+"-"+(d.getMonth()+1)+"-"+d.getDate();
}
function mailNightLeft(){
  const M=mailAll(),e=mailEve();
  if(M.eve!==e){M.eve=e;M.caught=0;}
  return Math.max(0,ETH_CATCH-(M.caught|0));
}
/* диапазон существует, только когда есть и ночь, и сеть */
function ethOn(){return mailNight()&&mailOn();}
function ethBandAt(f){return ethOn()&&f>=ETH_LO&&f<=ETH_HI;}

/* ── ход передачи ──
   Зовётся из consoleTick, когда ручка стоит в ночном диапазоне. Возвращает
   строку, которую слышно прямо сейчас. Ничего не рисует и ничего не решает
   за игрока: сойти с волны можно на любой строке. */
function ethTick(q){
  if(!ethOn())return null;
  /* на краю диапазона слышно шум — но ход передачи НЕ сбрасываем: consoleTick
     у стойки зовёт radioTune второй раз с соседней частотой, и сброс съедал бы
     паузу между строками */
  if(q<.55)return "…шшш…";
  if(!ethCard){
    /* тишина между карточками: эфир не выдаёт их подряд без паузы */
    if(ethHold>0){ethHold--;return "…";}
    if(mailNightLeft()<=0)return "…на сегодня эфир пуст…";
    const now=Date.now();
    if(now-ethAsk<12000)return "…";
    ethAsk=now;
    mailCall("ask").then(j=>{
      if(!j||!j.ok||!j.card||!j.ch)return;
      ethCard={ch:String(j.ch),card:j.card,mv:j.mv||null,lines:postLines(j.card)};
      ethLine=0;ethHold=0;
      sfx("ui",{f:520,to:820,d:.09,v:.16});
    });
    return "…";
  }
  if(ethHold>0){ethHold--;return ethCard.lines[Math.min(ethLine,ethCard.lines.length-1)];}
  const line=ethCard.lines[ethLine];
  ethHold=ETH_HOLD;
  ethLine++;
  if(ethLine>=ethCard.lines.length){
    /* дочитано: карточка ложится на стол, и ответ в ней уже открыт. Экран при
       этом НЕ распахивается сам — правило «только то, что нужно прямо сейчас,
       висит над миром» сильнее желания показать награду немедленно */
    const st=mailPush(ethCard.ch,ethCard.card,false);
    /* если с карточкой пришёл ход — он ложится в партию этой цепочки (M192) */
    if(ethCard.mv&&typeof chessTake==="function")chessTake(ethCard.ch,ethCard.mv);
    const M=mailAll();
    M.caught=(M.caught|0)+1;
    if(typeof mailOpen!=="undefined"){
      mailOpen=M.st.indexOf(st);
      mailPick=mailOpen;
      mailBack=-1;
    }
    logAdd("ether","Из ночного эфира принята карточка · стопка на столе, ответ открыт");
    tell("good","Карточка принята из ночного эфира","ПРИНЯТО\nстопка на столе\nответ открыт");
    ethCard=null;ethLine=0;ethHold=6;
    if(tableOpenNow)tableRender();
  }
  return line;
}
/* оборвалась ночь или сеть — оборвалась и передача */
function ethReset(){ethCard=null;ethLine=0;ethHold=0;}
