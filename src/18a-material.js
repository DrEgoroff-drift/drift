/* ══════════════ материал грунта ══════════════ */
/* Большая заливка одним цветом мгновенно выдаёт «нарисовано фигурами», сколько
   бы объектов сверху ни стояло. Поэтому у каждой планеты есть свой материал —
   бесшовный тайл 256×256, посчитанный один раз при заходе на посадку и дальше
   работающий обычным паттерном: на кадр это один fillRect по клипу.

   В тайле три масштаба сразу:
   макро  — геологические пятна и выветренные поля;
   средний— осадочные потёки, трещины, минеральные жилы;
   микро  — зерно, крошка, редкие вкрапления кристаллов.
   Ещё один масштаб добавляется при отрисовке: тот же тайл кладётся вторым
   проходом с увеличением 3.7×, и повторяемость 256 px перестаёт читаться. */

/* шум, бесшовный по обеим осям: решётка берётся по модулю L, поэтому правый
   край сходится с левым, а нижний с верхним — без этого швы видны сразу */
function tnoise(x,y,L,s){
  const fx=x*L,fy=y*L;
  const i=Math.floor(fx),j=Math.floor(fy),u=fx-i,v=fy-j;
  const su=u*u*(3-2*u),sv=v*v*(3-2*v);
  const m=(a,b)=>h01(((a%L)+L)%L,((b%L)+L)%L,s);
  return lerp(lerp(m(i,j),m(i+1,j),su),lerp(m(i,j+1),m(i+1,j+1),su),sv);
}
function tfbm(x,y,L,s,oct){
  let v=0,a=.5,f=1,n=0;
  for(let i=0;i<oct;i++){v+=a*tnoise(x,y,L*f,s+i*97);n+=a;a*=.5;f*=2;}
  return v/n;
}
/* хребтовой шум: из него получаются трещины и жилы — узкие ветвящиеся линии,
   а не пятна. Степень задаёт, насколько тонкой выходит линия. */
const ridged=(v,p)=>Math.pow(1-Math.abs(1-2*v),p);
/* минеральная примесь: у каждой планеты своя, иначе все жилы одного цвета */
const MINERAL=[[210,180,110],[120,210,220],[220,130,150],[150,230,160],
               [190,160,240],[240,190,120],[120,160,230],[230,230,240]];
const MAT_S=256;
/* ── характер породы ──
   Шум с трещинами и жилами читается КАМНЕМ, и это правильно для восьми миров
   из двенадцати. Но кристаллический мир в нём выходит сиреневым камнем, а
   металлический — серым: тип остаётся только в подписи. Поэтому четырём
   поздним мирам добавлен свой закон формы поверх общего шума. Форма, а не
   оттенок: оттенок уже есть в палитре, и его одного не хватило.

   `facet` — ячейки-грани со светлой кромкой: излом, а не склон.
   `plate` — крупные плиты с тёмным швом, потёками окисла и резким бликом.
   `moss`  — пятнистый полог: свет падает кляксами, трещин почти нет.
   `rubble`— прямоугольные блоки по осям: рукотворная кладка под пылью. */
/* У каждого типа мира — своя макроформа породы, не только палитра: дюнная рябь,
   плиты льда, корка лавы с тлеющими швами, раскисшие берега, слоистая почва.
   Шесть миров одной клеточной фактурой в шести цветах и были «одним телом» (G1). */
const MAT_CHAR={crystal:"facet",metal:"plate",jungle:"moss",ruin:"rubble",
  desert:"dune",ice:"frost",volcanic:"crust",toxic:"sludge",terran:"soil",ocean:"soil"};
/* ячейка с рваной кромкой, бесшовная по тайлу: сетка берётся по модулю N,
   границы размыты тем же шумом, что и всё остальное */
function matCell(u,v,N,sd,warp){
  const uu=u+warp*.5, vv=v+warp*.5;
  const fx=uu*N, fy=vv*N;
  let i=Math.floor(fx),j=Math.floor(fy);
  const du=fx-i, dv=fy-j;
  i=((i%N)+N)%N;j=((j%N)+N)%N;
  /* расстояние до ближайшей грани ячейки — по нему рисуется кромка */
  const edge=Math.min(du,1-du,dv,1-dv);
  return {tone:h01(i,j,sd)-.5, edge, du, dv, tilt:h01(i,j,sd+404)-.5};
}
/* ── и печётся она ПО КАДРАМ (M418) ──
   Замер в браузере 07.09.2026: `planetMat` на землеподобной планете идёт
   **383 мс одним куском**. Это 256×256 точек, и в каждой от двух до пяти
   многооктавных шумов. На телефоне это секунды — и в журнале сервера ровно
   один настоящий провал кадра за всё время наблюдений: «кадр стоял 2766 мс»,
   Pixel 8, девятая секунда жизни страницы. Столько эта выпечка и стоит.

   Лечится тем же приёмом, каким в игре уже печётся развёртка планеты
   (`planetStripTick`, 07-planet): работа режется на строки, за кадр отдаётся
   пара миллисекунд, а пока не готово — рисуется БЕЗ материала. Все, кто его
   спрашивает, уже умеют получить пустоту: `drawGround` кладёт ровную заливку
   силуэта, `drawRocks` — валун без породы, пещера и шахта проверяют так же.
   Ничего не пропадает: первые полсекунды у грунта нет зерна.

   ПОЧЕМУ НЕ ВОРКЕР. Тайл строится из наших же чистых функций (`tfbm`, `h01`),
   но воркеру пришлось бы отдать половину `01-core` и палитру, а вернуть он
   может только пиксели — и всё это ради работы, которая после нарезки
   перестаёт быть заметной вовсе. */
/* ── бюджет мерился, а не назначался (M418) ──
   Первый заход брал по восемь строк между сверками с часами. Замер в браузере:
   одна порция — 11–14 мс, то есть весь кадр целиком, и на телефоне это тридцать
   три подряд заикания вместо одного провала. Строка тайла стоит около 1.4 мс
   здесь, значит сверяться надо КАЖДУЮ строку, и тогда порция укладывается в
   бюджет с перебором на одну строку, а не на восемь. */
const MAT_MS=3;              /* столько миллисекунд кадра отдаём выпечке */
const MAT_ROWS=1;            /* через сколько строк сверяться с часами */
/* ── и потолок на случай СТОЯЩИХ ЧАСОВ ──
   Бюджет в миллисекундах хорош ровно до тех пор, пока часы идут. В стенде
   наборов их нет вовсе: `--virtual-time-budget` останавливает время внутри
   синхронного блока, и замер показал ноль миллисекунд на тридцати миллионах
   корней. Значит цикл «пока не вышел бюджет» там не выходит НИКОГДА и печёт
   весь тайл разом — то есть ровно то, от чего мы уходили. В настоящем браузере
   часы идут и потолок не срабатывает; он для всего остального. */
const MAT_CAP=8;             /* строк за одну порцию, что бы ни говорили часы */
let MAT_JOB=null;
/* Возвращает готовый материал — или null, пока печётся. Заказ ставится сам */
function planetMat(p){
  if(p.mat)return p.mat;
  /* спрашивают про ДРУГУЮ планету — печём её: игрок стоит на ней, а не на
     той, что осталась в задании. Иначе первая незаконченная выпечка держала бы
     все следующие, и материал не приходил бы вовсе (поймано набором) */
  if(!MAT_JOB||MAT_JOB.p!==p)MAT_JOB=matJobMake(p);
  return null;
}
/* допекаем по кадрам — зовётся из planetDraw рядом с развёрткой */
function matTick(){
  const J=MAT_JOB;if(!J)return;
  const t0=performance.now();
  let rows=0;
  while(J.y<J.S){
    matJobRows(J,MAT_ROWS);rows+=MAT_ROWS;
    if(rows>=MAT_CAP||performance.now()-t0>MAT_MS)return;
  }
  matJobDone(J);MAT_JOB=null;
}
/* когда материал нужен ПРЯМО СЕЙЧАС и кадра нет — из набора, из стенда, из
   снимка: печём целиком и платим те самые 383 мс, потому что платить некому */
function planetMatNow(p){
  if(p.mat)return p.mat;
  if(!MAT_JOB||MAT_JOB.p!==p)MAT_JOB=matJobMake(p);
  const J=MAT_JOB;
  while(J.y<J.S)matJobRows(J,64);
  matJobDone(J);MAT_JOB=null;
  return p.mat;
}
function matJobMake(p){
  const S=MAT_S,cn=document.createElement("canvas");cn.width=cn.height=S;
  const c=cn.getContext("2d"),img=c.createImageData(S,S),d=img.data;
  /* ── вторая плитка: СОБЫТИЯ (гризайль P4, M422) ──
     В первую идёт СВЕТЛОТА — зерно, трещины, грани, швы, крошка: её красит
     лессировка светом этой звезды под этим небом. Во вторую — то, чего из
     светлоты не достать: минеральные жилы, дисперсия ребра и искра кристалла,
     светлый ледяной шов, тлеющий лавовый, потёки окисла на плите. Восемь
     оттенков `MINERAL` на мир, и жила с кромкой грани дают одну светлоту при
     разных тонах: обратно их не разделить, значит и сводить нельзя.
     Вторая плитка почти вся прозрачная и кладётся ПОСЛЕ лессировки. */
  const hn=document.createElement("canvas");hn.width=hn.height=S;
  const hc=hn.getContext("2d"),himg=hc.createImageData(S,S),hd=himg.data;
  const pal=p.T.pal,sd=(p.seed^0x4D41)>>>0;
  const PT=pal[pal.length-1];
  const PAL_TOP_LUM=PT[0]*.3+PT[1]*.59+PT[2]*.11;
  const mn=MINERAL[sd%MINERAL.length];
  /* сколько чего на этой планете: выветренность, трещиноватость, богатство жил.
     Две каменистые планеты благодаря этому не выглядят одной и той же породой. */
  const r=rng(sd);
  let wear=.35+r()*.5, crackK=.25+r()*.85, veinK=r()*r()*.75, grainK=.5+r()*.9;
  /* характер берёт ведущий тип: у смеси поверхность всё-таки одна, и
     полуграни-полукладка читались бы браком, а не смешанным миром */
  const ch=MAT_CHAR[p.type]||null;
  /* общий шум под характерной формой приглушается, иначе грани тонут в пятнах */
  if(ch==="facet"){crackK*=.35;veinK*=1.4;wear*=.5;}
  /* Светлая минеральная жила ветвится по всей плоскости и на металле читалась
     сетью трещин в сухой грязи — сильнее, чем сами плиты. Металл держится на
     плите и шве, а не на прожилках */
  else if(ch==="plate"){crackK*=.5;wear*=.6;veinK*=.18;}
  else if(ch==="moss"){crackK*=.25;veinK*=.4;}
  else if(ch==="rubble"){crackK*=.7;}
  else if(ch==="dune"){crackK*=.12;veinK*=.1;wear*=.5;grainK*=1.3;}
  else if(ch==="frost"){crackK*=.3;veinK*=.15;wear*=.4;grainK*=.5;}
  else if(ch==="crust"){crackK*=.4;veinK*=.05;wear*=.7;}
  else if(ch==="sludge"){crackK*=.15;veinK*=.2;wear*=.8;grainK*=.7;}
  else if(ch==="soil"){crackK*=.35;veinK*=.3;}
  const cellN=ch==="facet"?9:(ch==="plate"?4:(ch==="rubble"?7:(ch==="frost"?5:(ch==="crust"?6:6))));
  return {p,S,cn,c,img,d,hn,hc,himg,hd,y:0,pal,sd,mn,PAL_TOP_LUM,
          wear,crackK,veinK,grainK,ch,cellN};
}
/* одна порция строк: та же арифметика, что и была, только внешний цикл снаружи */
function matJobRows(J,rows){
  const S=J.S,d=J.d,hd=J.hd,pal=J.pal,sd=J.sd,mn=J.mn,PAL_TOP_LUM=J.PAL_TOP_LUM;
  const wear=J.wear,crackK=J.crackK,veinK=J.veinK,grainK=J.grainK,ch=J.ch,cellN=J.cellN;
  const yEnd=Math.min(S,J.y+rows);
  for(let y=J.y;y<yEnd;y++)for(let x=0;x<S;x++){
    const o=(y*S+x)*4,u=x/S,v=y/S;
    /* макро: крупные поля породы */
    const macro=tfbm(u,v,3,sd,4);
    /* средний: осадочные потёки — растянуты по горизонтали, как намытый слой */
    const sed=tfbm(u*.55,v*2.2,6,sd+11,3);
    let t=clamp(macro*.66+sed*.34,0,1);
    /* выветривание сдвигает светлоту пятнами, а не ровно */
    t=clamp(t+(tfbm(u,v,9,sd+71,2)-.5)*wear,0,1);
    /* диапазон палитры сжат к середине: во всю ширину порода прыгает от
       глубокой тени до снега и читается как камуфляж, а не как камень */
    /* грани, плиты, полог и кладка: форма считается ДО того, как выбран цвет,
       и двигает саму ступень палитры — тогда светлая кромка берёт верхний
       конец палитры, а не просто подсветку поверх готового цвета */
    let edgeHi=0, edgeLo=0, seam=0, darkK=1;
    if(ch){
      const warp=(tfbm(u,v,4,sd+13,3)-.5)*(ch==="rubble"?.10:.42);
      const C=matCell(u,v,cellN,sd+61,warp);
      if(ch==="facet"){
        /* Грань плоская внутри, а по излому светится ОДНО ребро — то, что
           повёрнуто к свету; противоположное уходит в тень. Первый заход
           подсвечивал весь периметр ячейки, и поверхность читалась рыбьей
           чешуёй: замкнутый светлый контур — это шов, а не излом.
           Размер граней тоже неровный: крупные друзы вперемешку с мелкой
           крошкой, иначе видно ровную сетку. */
        const C2=matCell(u,v,cellN*2+1,sd+77,warp*1.5);
        const CC=tfbm(u,v,3,sd+151,2)>.52?C:C2;
        t=clamp(t*.28+.5+CC.tone*.66,0,1);
        const s=CC.tilt>0;
        const dU=s?CC.du:1-CC.du, dV=s?CC.dv:1-CC.dv;
        edgeHi=Math.pow(clamp(1-Math.min(dU,dV)*9,0,1),1.9);
        edgeLo=Math.pow(clamp(1-Math.min(1-dU,1-dV)*9,0,1),1.9);
      }else if(ch==="plate"){
        t=clamp(t*.45+.42+C.tone*.34,0,1);
        seam=Math.pow(clamp(1-C.edge*7,0,1),2.0);
        /* блик по верхнему ребру плиты: металл без резкого света — не металл,
           а серый камень. Ребро узкое и холодное, в отличие от тёплой грани
           кристалла */
        edgeHi=Math.pow(clamp(1-Math.min(C.du,C.dv)*16,0,1),2.4)*.7;
      }else if(ch==="rubble"){
        /* Кладка по осям: рукотворное узнают по прямому углу. Но кладка не
           везде — она пятнами, между ними обычный грунт. Сплошная сетка во
           весь экран читалась миллиметровкой, а не руинами: пол планеты. */
        const site=clamp((tfbm(u,v,3,sd+211,3)-.42)*3.4,0,1);
        const big=tfbm(u*.7,v*.7,2,sd+233,2)>.5;
        const B=matCell(u,v,big?cellN:Math.round(cellN*1.8),sd+61,0);
        /* выбитый блок: провал вместо камня, иначе кладка выглядит целой,
           а она тысячу лет как брошена */
        const gone=h01(Math.floor(u*cellN*3),Math.floor(v*cellN*3),sd+307)>.86;
        t=clamp(t*.55+.36+B.tone*.30*site-(gone?.22*site:0),0,1);
        seam=Math.pow(clamp(1-B.edge*11,0,1),2.6)*site;
      }else if(ch==="moss"){
        /* Полог: свет падает кляксами. Первый заход дал ровную зелёную стену —
           пятна вышли крупными и почти без контраста, а под пологом важно
           обратное: темно, и лишь местами пробивает. Отсюда высокая степень
           и подстилка мелким зерном поверх. */
        const d1=tfbm(u*1.7,v*1.7,9,sd+91,4);
        const litter=tfbm(u*3.4,v*3.4,19,sd+97,2);
        t=clamp(t*.28+.12+Math.pow(d1,2.6)*1.15+(litter-.5)*.22,0,1);
        /* корни расползаются по земле — тёмные, а не светлые, как жилы */
        const root=ridged(tfbm(u,v,6,sd+123,4),22);
        if(root>.02)darkK=1-clamp(root,0,.5)*.5;
      }else if(ch==="dune"){
        /* Рябь: волны по горизонтали, гребень светлый, подветренная сторона
           в тени; волны гнёт крупный шум, чтобы не было линейки. Песок без
           трещин и жил — его форма и есть его фактура. */
        const bend=tfbm(u*.8,v*.8,3,sd+401,3)*3.2;
        const ph=(v*26+bend+(tfbm(u,v,7,sd+409,2)-.5)*.6)*TAU;
        const rip=.5+.5*Math.sin(ph);
        const crest=Math.pow(rip,3.2);
        t=clamp(t*.42+.30+rip*.22+crest*.12,0,1);
        /* наветренная сторона чуть темнее — рябь читается рельефом, а не полосами */
        if(Math.cos(ph)<0)darkK=.94;
      }else if(ch==="frost"){
        /* Плиты льда: трещины светлые (лёд в изломе белый), внутри плита
           уходит в синеву, и чем крупнее плита, тем глубже. */
        const C2=matCell(u,v,cellN*2,sd+77,warp*.7);
        const CC=tfbm(u,v,3,sd+151,2)>.5?C:C2;
        t=clamp(t*.30+.46+CC.tone*.36,0,1);
        seam=-Math.pow(clamp(1-CC.edge*9,0,1),2.2);   // минус: шов светлый, не тёмный
        edgeHi=Math.pow(clamp(1-Math.min(CC.du,CC.dv)*14,0,1),2.2)*.35;
      }else if(ch==="crust"){
        /* Остывшая корка: тёмные плиты, между ними швы; где жар ближе к
           поверхности — швы тлеют. Это единственный светлый штрих на
           вулканическом мире, и потому он читается издалека. */
        t=clamp(t*.5+.18+C.tone*.22,0,1);
        seam=Math.pow(clamp(1-C.edge*8,0,1),2.4);
        const heat=clamp((tfbm(u,v,2,sd+511,3)-.42)*3.2,0,1);
        if(seam>.05&&heat>.02)edgeLo=-seam*heat*1.6;   // минус: метка «тлеет», см. ниже
      }else if(ch==="sludge"){
        /* Раскисшие берега: мягкие лужи светлее, ил между ними темнее и с
           ободком у кромки; ни граней, ни трещин — всё оплыло. */
        const pool=tfbm(u,v,5,sd+601,3);
        const rim=Math.pow(clamp(1-Math.abs(pool-.5)*9,0,1),2);
        t=clamp(t*.4+.28+(pool>.5?.22:0)+(pool-.5)*.3,0,1);
        darkK=1-rim*.28;
      }else if(ch==="soil"){
        /* Почва: слоистость — тонкие горизонтальные прослои, гнутые, и чаще
           крошка. Сдержанно: это фон для флоры, а не сама достопримечательность. */
        const bend=tfbm(u*.6,v*.6,3,sd+701,3)*2.4;
        const bed=.5+.5*Math.sin((v*38+bend)*TAU);
        t=clamp(t*.6+.2+Math.pow(bed,4)*.16,0,1);
      }
    }
    const c0=ramp(pal,ch==="facet"?(.10+t*.86):(.26+t*.5));
    /* ── СВЕТЛОТА вместо цвета (гризайль) ──
       Раньше брался тон из палитры и слегка сводился к собственной светлоте.
       Теперь берётся одна светлота, НОРМИРОВАННАЯ по верхней ступени палитры:
       серый проход обязан мерить «сколько света отражает эта точка от полностью
       освещённой», а не абсолютную яркость тона. Без нормировки палитра
       множится дважды — здесь и в лессировке, — и разрез уходит в плоскую
       оливу (замер первого захода, 07.09). */
    let V=(c0[0]*.3+c0[1]*.59+c0[2]*.11)*(255/Math.max(1,PAL_TOP_LUM));
    let hR=0,hG=0,hB=0,hA=0;
    const hue=(r2,g2,b2,w)=>{
      if(w<=0)return;
      const wn=clamp(w,0,1);
      hR=lerp(hR,r2,wn);hG=lerp(hG,g2,wn);hB=lerp(hB,b2,wn);
      hA=hA+(1-hA)*wn;
    };
    /* трещины: тонкая тёмная сеть, глубже в углублениях */
    /* трещина должна быть волосяной: широкая «жила» ридж-шума читается
       кишками, а не разломом — отсюда высокая степень и мелкая решётка */
    const crack=ridged(tfbm(u,v,17,sd+29,3),17)*crackK;
    const k=1-clamp(crack,0,.40);
    V*=k;
    /* жилы: узкие прожилки минерала, редкие. Их оттенок — во вторую плитку */
    const vein=ridged(tfbm(u,v,5,sd+53,4),38)*veinK;
    if(vein>.01)hue(mn[0],mn[1],mn[2],clamp(vein,0,.55));
    /* микро: зерно породы и редкая крошка */
    const g=(h01(x,y,sd+7)-.5)*15*grainK;
    V+=g;
    /* кромка грани и шов плиты кладутся последними: они рисуют форму, и любая
       фактура поверх них снова превратила бы излом в склон */
    if(edgeHi>.01){
      const top=pal[pal.length-1];
      /* кромка грани поднимает СВЕТЛОТУ: это форма излома, а не краска */
      V=lerp(V,255*(top[0]*.3+top[1]*.59+top[2]*.11)/Math.max(1,PAL_TOP_LUM),edgeHi*.85);
      /* Дисперсия: у прозрачной грани ребро не белое — оно уводит в холод или
         в тепло, у каждой грани по-своему. Это ОТТЕНОК, и он во второй плитке:
         ровно белые рёбра давали брусчатку, а лессировка их бы и сравняла. */
      const disp=(h01(Math.floor(u*cellN),Math.floor(v*cellN),sd+909)-.5)*2;
      if(Math.abs(disp)>.15)
        hue(top[0]+disp*26,top[1]-Math.abs(disp)*10,top[2]-disp*22,edgeHi*.55);
      /* и редкая искра на самом ребре: то, чем кристалл отличается от камня */
      if(ch==="facet"&&edgeHi>.55&&h01(x,y,sd+1717)>.986){V=250;hue(250,248,255,1);}
    }
    if(darkK<1)V*=darkK;
    if(edgeLo>.01)V*=1-edgeLo*.55;
    if(seam>.01)V*=1-seam*.62;
    /* лёд: шов светлый и холодный; лава: тлеющий. Светлота сюда, холод и жар —
       во вторую плитку: без них ледяной мир теряет синеву шва, а вулканический
       единственное тёплое пятно на весь кадр */
    if(seam<-.01){const w3=-seam*.6;V=lerp(V,245,w3);hue(226,240,255,w3*.9);}
    if(edgeLo<-.01){const w4=clamp(-edgeLo*1.4,0,1);V=lerp(V,200,w4);hue(255,118,34,w4);}
    if(ch==="plate"){
      /* потёки окисла вниз по плите: без них металл читается пластиком */
      /* Узкие вертикальные потёки, а не широкие ленты: первый заход красил
         половину планеты в розово-бежевый, и металл читался песчаником.
         Окисел бурый и тёмный — светлая ржавчина выглядит мясом. */
      const rust=Math.pow(clamp(tfbm(u*7.5,v*.5,14,sd+131,3)-.54,0,1)*3.2,1.7);
      if(rust>.02){const w2=clamp(rust,0,.7)*.55;
        V=lerp(V,(104*.3+54*.59+32*.11)*255/Math.max(1,PAL_TOP_LUM),w2*.5);
        hue(104,54,32,w2);}
    }
    const peb=h01(x>>1,y>>1,sd+13);
    if(peb>.982)V+=(peb-.982)*36*70;
    else if(peb<.006)V*=.62;
    /* ── подмалёвок пишут КОНТРАСТНЕЕ готового ──
       Два композитных залива лессировки сжимают шкалу: тень поднимается на
       `dark`, свет упирается в `light`. Гризайль «в натуральную светлоту»
       после неё читается плоской — замер первого захода дал «пусто» 41 → 50.
       Растягиваем вокруг середины ровно настолько, насколько потом сожмёт. */
    const q=clamp(128+(clamp(V,0,255)-128)*GREY_K,0,255);
    d[o]=q;d[o+1]=q;d[o+2]=q;d[o+3]=255;
    hd[o]=clamp(hR,0,255);hd[o+1]=clamp(hG,0,255);hd[o+2]=clamp(hB,0,255);
    hd[o+3]=clamp(hA*255,0,255);
  }
  J.y=yEnd;
}
function matJobDone(J){
  J.c.putImageData(J.img,0,0);
  J.hc.putImageData(J.himg,0,0);
  J.p.mat=J.c.createPattern(J.cn,"repeat");
  J.p.matHue=J.hc.createPattern(J.hn,"repeat");
  J.p.matCn=J.cn;
  return J.p.mat;
}
/* плитка событий того же мира: печётся вместе с формой, спрашивается порознь */
function planetMatHue(p){
  if(!p.matHue&&!p.mat)return null;      /* ещё не готово — и не надо */
  return p.matHue||null;
}
/* положить материал в уже построенный путь (путь должен быть текущим).
   Два прохода: свой масштаб и увеличенный — второй убивает видимую сетку 256. */
/* bnd — прямоугольник в текущих координатах, которым ограничен залив. Без него
   заливались бы все W×H на каждый вызов: на сорока валунах это восемьдесят
   полноэкранных заливок за кадр, то есть вся производительность режима. */
function fillMaterial(mat,camx,camy,a1,a2,P,bnd){
  if(!mat)return;
  const bx=bnd?bnd.x:-4, by=bnd?bnd.y:-4;
  const bw=bnd?bnd.w:W+8, bh=bnd?bnd.h:H+8;
  ctx.save();
  if(P)ctx.clip(P);   // без пути клипа нет: ctx.clip() по пустому пути вырезал всё (G3)
  ctx.globalAlpha=a1;
  ctx.translate(-camx,-camy);
  ctx.fillStyle=mat;
  ctx.fillRect(camx+bx,camy+by,bw,bh);
  ctx.restore();
  if(a2<=0)return;
  /* второй проход — тот же тайл крупно и в режиме overlay: он добавляет
     светлые и тёмные поля масштабом с полэкрана, из-за которых сетка 256
     перестаёт читаться, но цвет породы не уезжает */
  ctx.save();
  if(P)ctx.clip(P);   // без пути клипа нет: ctx.clip() по пустому пути вырезал всё (G3)
  ctx.globalCompositeOperation="overlay";
  ctx.globalAlpha=a2;
  const K=3.7, PH=91;
  /* Смещение второго прохода обязано быть таким же, как у первого (делённым на
     масштаб), иначе крупный слой ползёт относительно мелкого при движении
     камеры. Именно это читалось как «камни что-то отражают»: на валуне ползущее
     светлое поле выглядит скользящим по нему бликом, а не породой.
     Развожу проходы постоянной фазой PH, а не разной скоростью. */
  ctx.scale(K,K);
  ctx.translate(-(camx+PH)/K,-(camy+PH)/K);
  ctx.fillStyle=mat;
  ctx.fillRect((camx+PH+bx)/K,(camy+PH+by)/K,bw/K,bh/K);
  ctx.restore();
}
