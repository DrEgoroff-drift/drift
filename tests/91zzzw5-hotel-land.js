/* ══════════════ причальная полоса не перебивает посадку (0.493.4) ══════════════
   Гостиница и чебуречная стоят у причальной полосы станции, планета по орбите
   проходит мимо — и «ДЕЙСТВИЕ — К СТОЙКЕ» / «ЧЕБУРЕКИ! ГОРЯЧИЕ!» глушили
   «ДЕЙСТВИЕ — ПОСАДКА»: сесть было нельзя, пока планета рядом со станцией
   (нашла проба · экономика). Закон: планета в зоне посадки главнее всего, что
   стоит у полосы; без планеты рядом полоса на месте. Планета в кадре считается
   от орбиты каждый кадр — двигаем корабль к ней, не её к кораблю. */
TEST_SUITES.push(() => suite("причальная полоса уступает посадке",{tier:"node"}, () => {
  resetWorld();
  const here0=hotelHere;
  try{
    G.mode="system";G.running=true;G.ap=null;G.orbit=null;
    const sh=G.ship,p=G.sys.planets.find(q=>q.type!=="gas")||G.sys.planets[0];
    ok(!!p,"в системе есть планета");
    stepWorld(1);
    /* гостиница там же, где корабль; корабль — в зоне посадки у планеты */
    hotelHere=()=>({x:sh.x,y:sh.y,by:"km",sign:"",name:"ЮПИТЕР"});
    sh.x=p.x+p.radius+40;sh.y=p.y;sh.vx=p.vx||0;sh.vy=p.vy||0;
    stepWorld(1);
    ok(/ПОСАДКА|ГАЗОВЫЙ ГИГАНТ/.test(G.prompt),"у планеты зовёт посадка: «"+G.prompt.split("\n")[0]+"»");
    ok(!/К СТОЙКЕ/.test(G.prompt),"стойка молчит, пока планета в зоне посадки");
    /* планета далеко — стойка на месте */
    sh.x=p.x+p.radius+3000;sh.vx=0;sh.vy=0;
    stepWorld(1);
    ok(/К СТОЙКЕ/.test(G.prompt),"без планеты рядом стойка зовёт: «"+G.prompt.split("\n")[0]+"»");
  }finally{hotelHere=here0;}
}));
