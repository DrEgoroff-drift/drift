/* ══════════════ что не имеет права идти вспять (M359) ══════════════
   Есть свойства, которые игрок чувствует раньше, чем формулирует: сделал
   больше — стало не хуже; улетел дальше — стало опаснее; продал много —
   цена упала, но не в пропасть, и со временем вернулась. Ломаются они не
   падением, а тихим переворотом знака в формуле, и тогда игра начинает
   наказывать за старание. Ни одного набора на это нет.

   Три закона, каждый проверяется перебором, а не примером:
   1. ступень не падает от доброго дела — сколько бы дел ни прибавили,
      `rungOf` не может стать меньше;
   2. опасность растёт с удалением от начала (`sysDanger` — сквозное правило
      «градиент с самого начала»), и растёт монотонно;
   3. цена под давлением остаётся в своих потолках и возвращается со временем,
      а не падает навсегда. */

TEST_SUITES.push(() => suite("вспять: ступень не падает от того, что игрок сделал больше", () => {
  resetWorld();
  if(typeof rungOf!=="function"){ok(true,"ступени в этой сборке нет — пропуск");return;}
  const key=G.sx+","+G.sy;
  /* ворота открыты: садились, бурили, оставили дрона — иначе ступень заперта
     потолком и рост не виден вовсе */
  G.place[key+"/0"]={f:1,l:1,n:1,take:1,hurt:0,care:1};
  const H=G.hold[key]=G.hold[key]||{};
  H.deeds={drone:1,drill:1,cargo:0};
  H.bld={};
  const bad=[];
  let prev=rungOf(G.sx,G.sy);
  const start=prev;
  /* прибавляем дела по одному и следим, чтобы ступень только росла */
  for(let i=1;i<=40;i++){
    H.deeds.cargo=(H.deeds.cargo|0)+50;
    if(i%4===0)H.deeds.drone=Math.min(9,(H.deeds.drone|0)+1);
    if(i%6===0)H.deeds.drill=Math.min(9,(H.deeds.drill|0)+1);
    if(i%5===0){const id="b"+i;H.bld[id]={lvl:1,t0:0,ready:0,my:{},got:{}};}
    const r=rungOf(G.sx,G.sy);
    if(r<prev)bad.push("после дела №"+i+" ступень упала: "+prev+" → "+r);
    prev=r;
    if(bad.length>2)break;
  }
  ok(prev>start,"ступень выросла за сорок дел: "+start+" → "+prev);
  eq(bad.slice(0,3).join(" ;; "),"","ступень ни разу не пошла вспять");
  /* и уровень постройки тоже только вверх */
  const before=rungOf(G.sx,G.sy);
  for(const id in H.bld)H.bld[id].lvl=(H.bld[id].lvl|0)+2;
  ok(rungOf(G.sx,G.sy)>=before,"достроенное не понижает ступень: "+before+" → "+rungOf(G.sx,G.sy));
  resetWorld();
}));

TEST_SUITES.push(() => suite("вспять: опасность растёт с удалением, а не как придётся", () => {
  /* «Градиент с самого начала» (PLAN, сквозные правила): sysDanger задаёт тир
     частей, уровень баз, редкость ресурсов и качество наёмных рук. Если он
     перестанет расти — исчезнет вся дальняя половина игры, и молча. */
  resetWorld();
  const bad=[];
  let prev=-1;
  for(let r=0;r<=60;r+=4){
    const d=sysDanger(r,0);
    if(!(d>=0&&d<=1))bad.push("на удалении "+r+" опасность вне [0,1]: "+d);
    if(d<prev-1e-9)bad.push("на удалении "+r+" опасность упала: "+prev.toFixed(3)+" → "+d.toFixed(3));
    prev=d;
  }
  eq(sysDanger(0,0),0,"в начале координат опасности нет");
  ok(sysDanger(10,10)>sysDanger(2,2),"дальше — опаснее: "+sysDanger(2,2).toFixed(2)+" → "+sysDanger(10,10).toFixed(2));
  eq(sysDanger(1000,1000),1,"на краю опасность упирается в единицу, а не растёт без предела");
  /* по кругу одинакова: опасность от РАССТОЯНИЯ, а не от стороны света */
  const ring=[[10,0],[0,10],[-10,0],[0,-10],[7,7]];
  const vals=ring.map(c=>+sysDanger(c[0],c[1]).toFixed(3));
  ok(Math.max(...vals)-Math.min(...vals)<.02,"по кольцу опасность одна: "+vals.join(", "));
  eq(bad.slice(0,3).join(" ;; "),"","опасность растёт монотонно и не выходит за берега");
  resetWorld();
}));

TEST_SUITES.push(() => suite("вспять: цена под давлением не падает в пропасть и возвращается", () => {
  /* Продажа давит цену вниз (`m.pressure`), покупка поднимает запрос. Оба
     зажаты в clamp(.4, 1.8) — иначе на одной станции можно было бы обвалить
     товар навсегда. И давление отпускает со временем: рынок помнит часами, а
     не вечно (12-economy). */
  resetWorld();
  const sys=(typeof mkSystems==="function")?mkSystems(6)[0]:null;
  if(!sys){ok(true,"станции нет — пропуск");return;}
  G.sx=sys.sx;G.sy=sys.sy;G.sys=sys;G.st=sys.station;
  const k=TRADE_KEYS[0];
  G.market={};
  /* Первая продажа закрывает «нужду» станции (×2 к цене, M152e), а это не
     давление, а разовая надбавка. Меряем ПОСЛЕ неё — иначе сравнивается цена
     с надбавкой и без, и любой потолок кажется пробитым. */
  for(const q of RES_KEYS)G.cargo[q]=0;
  G.cargo[k]=5;sellCargo(sys,k,5);
  const base=marketPrice(sys,k);
  ok(base>0,"цена спокойного прилавка: "+base);
  /* сваливаем на прилавок гору товара */
  for(let i=0;i<40;i++){
    for(const q of RES_KEYS)G.cargo[q]=0;
    G.cargo[k]=50;
    sellCargo(sys,k,50);
  }
  const low=marketPrice(sys,k);
  ok(low<base,"цена просела от вала: "+base+" → "+low);
  /* давление зажато в −0.35: ниже 65 % от спокойной цены прилавок не опустится */
  ok(low>=Math.floor(base*.65),"но не в пропасть: "+low+" при потолке вниз "+Math.floor(base*.65));
  /* и возвращается со временем. Полураспад давления — 10 800 «секунд» рынка,
     а секунда рынка это шестьдесят кадров (12-economy): двое суток игры это
     всего два десятка минут по этой мерке, поэтому и ждём по-настоящему. */
  G.t+=10800*60*2;
  const back=marketPrice(sys,k);
  ok(back>low,"через два полураспада цена пошла обратно: "+low+" → "+back);
  ok(back<=base+1,"и не выше спокойной: "+back+" против "+base);
  /* обратная сторона: запрос от покупок тоже имеет потолок */
  G.credits=5000000;
  for(let i=0;i<40;i++)buyCargo(sys,k,10),G.cargo[k]=0;
  const ask=buyPriceFor(sys,k);
  ok(ask<=Math.round(base*2.6),"запрос после сорока покупок в берегах: "+ask+" при базе "+base);
  resetWorld();
}));
