/* Ноги растений и зверей в пещере держатся в .25 м от пола игры (раньше растение вмуровано +0.5 м). */
TEST_SUITES.push(()=>suite("пещера: ноги вещей у пола игры",()=>{
  ok(Math.abs(cave3FootY(10,10.5)-10.25)<1e-9,"+0.5 м → срезано до +0.25: "+cave3FootY(10,10.5));
  ok(Math.abs(cave3FootY(10,9.2)-9.75)<1e-9,"-0.8 м → срезано до -0.25: "+cave3FootY(10,9.2));
  ok(cave3FootY(10,10.1)===10.1,"малый сдвиг не меняется");
}));
