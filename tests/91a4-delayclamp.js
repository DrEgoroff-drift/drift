/* Задержка радио: время в пределах линии createDelay(2), без предупреждения Web Audio. */
TEST_SUITES.push(()=>suite("радио: задержка не выходит за 2 с",()=>{
  ok(radioDelayS(.75,3)===1.99*0+Math.min(1.99,.75*3),"обычный темп не меняется: "+radioDelayS(.75,3));
  ok(radioDelayS(1.5,3)<=1.99,"медленный темп: 1.5×3 = 4.5 → в пределе: "+radioDelayS(1.5,3));
  ok(radioDelayS(-1,3)===0,"отрицательное — ноль");
}));
