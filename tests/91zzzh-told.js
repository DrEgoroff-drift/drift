/* ══════════════ автотесты: ляпнул лишнего ══════════════
   Третий просёр (11aj). Сторожится ровно то, из-за чего он может перестать быть
   выбором и стать наказанием. */
TEST_SUITES.push(()=>suite("рассказал: покупает имя сейчас, платит потом",()=>{
  resetWorld();
  G.told=[];G.lastDig=null;G.folk={};
  eq(toldWorth(),null,"пока ничего не копал — рассказывать нечего");
  /* мелочь не в счёт: пустая болтовня ничего не стоит и ничего не покупает */
  G.lastDig={sx:1,sy:2,pi:0,res:"ice",n:3};
  eq(toldWorth(),null,"взял по мелочи — не рассказ");
  G.lastDig.n=9;
  ok(toldWorth(),"взял заметно — есть о чём сказать");
  /* рассказал: человек за стойкой запомнил тёплым, и это настоящая плата */
  const who="st:"+G.sys.key;
  ok(!folkOf(who).warm,"до рассказа он никого не запоминал");
  ok(toldDo(),"рассказал");
  ok(folkOf(who).warm,"и его запомнили тёплым — следующее придёт именным");
  eq(toldWorth(),null,"про это место второй раз не расскажешь");
  /* и сразу ничего не случилось: место ещё не выработано */
  ok(!toldWorked(1,2,0),"в тот же день туда никто не прилетел");
}));

TEST_SUITES.push(()=>suite("рассказал: возвращается чужим голосом, один раз",()=>{
  resetWorld();
  G.told=[];G.lastDig={sx:4,sy:5,pi:1,res:"iron",n:12};G.folk={};
  toldDo();
  const t=G.told[0];
  /* до срока — молчание */
  eq(toldEther(),false,"до срока в эфире ничего");
  eq(G.log.filter(e=>/навёл/.test(e.s)).length,0,"и в журнале ничего");
  /* после срока — одна строка, и больше никогда */
  t.d-=TOLD_LAG+1;
  ok(toldWorked(4,5,1),"место выработали");
  eq(toldEther(),true,"в эфире прошла строка");
  eq(toldEther(),false,"второй раз она не приходит");
  const said=G.log.filter(e=>/навёл/.test(e.s));
  eq(said.length,1,"строка ровно одна");
  ok(said[0].s.indexOf("ноль-семь")<0&&said[0].s.indexOf("вы ")<0,
     "и она не называет игрока");
}));

TEST_SUITES.push(()=>suite("рассказал: не забывается перезагрузкой",()=>{
  resetWorld();
  G.told=[];G.lastDig={sx:7,sy:8,pi:2,res:"ice",n:10};
  toldDo();
  G.told[0].d-=TOLD_LAG+1;
  ok(toldWorked(7,8,2),"место выработано");
  const s=snapshot();applySave(s);
  ok(toldWorked(7,8,2),"и после загрузки оно всё ещё выработано");
  /* залежи на выработанном месте беднее — их считает генератор посадки */
  eq(typeof toldWorked,"function","проверка доступна генератору залежей");
}));
