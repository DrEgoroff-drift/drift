/* ══════════════ черпак на видеокарте (G9, 19a1) ══════════════
   Коридор сбора рисует шейдер, а столкновения считает scoopCenter (19a). Если числа,
   которые уходят в шейдер, разойдутся с правилом, картинка соврёт игроку, где
   собирается газ. Шейдер в Node не запускается — проверяем его входы: центр коридора,
   собранный из фаз по модулю, совпадает с правилом на всём экране и на длинном пути,
   где fp32 без модуля уже рябил бы. И свет: звезда даёт единичное направление к себе,
   день в 0..1, солнце на конечных координатах. */
TEST_SUITES.push(() => suite("черпак на видеокарте: коридор шейдера — тот же, что в правилах", () => {
  resetWorld();
  const sys=e2eFind(q=>(q.planets||[]).some(p=>p.type==="gas"));
  if(!ok(sys,"газовый гигант поблизости"))return;
  G.sx=sys.sx;G.sy=sys.sy;G.sys=sys;
  startScoop(sys.planets.find(q=>q.type==="gas"));
  const S=G.scoop;
  if(!ok(S,"черпак начался"))return;
  let worst=0,worstAt="";
  for(const x of [0,700,1500,4321.25,98765.5,512345]){
    S.x=x;
    const L=scoopSunAt(S),U=scoopFlowU(S,0,L);
    for(let X=-16;X<=W+16;X+=37){
      const d=Math.abs(scoopFlowBandAt(U,X)-scoopCenter(S.x+(X-W*.34)/SCOOP_PX));
      if(d>worst){worst=d;worstAt="путь "+x+", X "+X;}
    }
    ok(U[44]>=0&&U[44]<TAU&&U[45]>=0&&U[45]<TAU,"фазы коридора в одном обороте на пути "+x);
    ok(U[51]>=0&&U[51]<16&&U[48]<40960&&U[54]<737280,"фазы взвеси, пунктира и штрихов в своих периодах на пути "+x);
    const n=Math.hypot(L[0],L[1]);
    near(n,1,1e-6,"направление к звезде единичное на пути "+x);
    ok(L[1]<0,"свет приходит сверху (к звезде — вверх по экрану) на пути "+x);
    ok(L[2]>=0&&L[2]<=1&&L[3]>=0&&L[3]<=1,"день и тёплость в 0..1 на пути "+x);
    ok(isFinite(L[4])&&isFinite(L[5]),"солнце на конечных координатах на пути "+x);
  }
  ok(worst<.01,"центр коридора в шейдере совпал с правилом (худшее "+worst.toFixed(5)+" px, "+(worstAt||"—")+")");
  resetWorld();
}));
