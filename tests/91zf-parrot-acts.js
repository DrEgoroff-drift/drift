/* ══ M117a: репертуар птицы ══
   Сторож замысла: покой — это все степени свободы в нуле; повадка пишет только
   свои и всегда доходит до конца; настроения покрывают всю таблицу; дрёма
   кончается по часам, а не по жребию. Всё это уже ломалось руками: разворот с
   единицей в покое расплющил птицу в нитку, а сонливость без конца фазы
   усыпляла её на три четверти времени. */
TEST_SUITES.push(()=>suite("трепло: репертуар",{tier:"browser"},()=>{
  resetWorld();
  const DOF=["roll","tuck","step","turn","stretch","footUp","fan","yawn",
             "shiver","bow","hang"];

  /* 1. Покой — это нули. Если у какой-то степени свободы «спокойное»
        значение не ноль, любое обнуление записи ломает рисунок.

     ── птицу надо СПЕРВА УСПОКОИТЬ (0.417.0) ──
     `PAR` живёт на модуле, а не в мире: `resetWorld` его не трогает. Набор
     читал живое состояние — и если соседний набор оставил птицу посреди
     повадки, «в покое bow равно нулю» краснело на 0.29. Так и случилось,
     когда рядом появился набор про жёрдочку. Успокаиваем честно: снимаем
     повадку, глушим их запуск на время и даём степеням свободы осесть —
     они затухают на 0.9 за кадр, две секунды хватает с запасом.

     Проверок здесь две, и они про РАЗНОЕ. Первая — что ОБЪЯВЛЕННЫЙ покой
     нулевой: читаем саму таблицу `PAR` в исходнике страницы, как сеть имён
     читает свои таблицы. Вторая — что птица в этот покой ВОЗВРАЩАЕТСЯ: сняли
     повадку, приглушили запуск новых, дали осесть. Первая ловит ненулевое
     значение в объявлении, вторая — степень свободы, которая не затухает
     (у `turn` затухания нет вовсе — его гасят сами повадки, и это держится
     только на них). */
  const src=(document.scripts&&document.scripts[0])
    ?document.scripts[0].textContent:"";
  if(ok(src,"исходник страницы виден набору")){
    const i=src.indexOf("const PAR={"),j=src.indexOf("};",i);
    ok(i>0&&j>i,"таблица PAR найдена в исходнике");
    const decl=src.slice(i,j);
    for(const k of DOF)ok(new RegExp("[{,\\s]"+k+":0[,\\s]").test(decl),
      "в объявлении «"+k+"» покоится в нуле");
  }
  /* ── шаг оседает медленнее всех, и это не поломка (0.421.1) ──
     `step` — это МЕСТО на жёрдочке, а не поза: птица, шагнувшая вбок, не
     отскакивает назад за секунду, а сползает к середине на .995 за кадр —
     около двадцати восьми секунд с прыжка в 20. Двухсот кадров ему мало, и
     набор краснел по жребию: если соседний набор оставил птицу посреди
     прыжка, «step» держал −7 (найдено 09.09.2026 на полном ярусе, дважды за
     день, один раз −0.31). Поэтому позы проверяются через две секунды, а
     место — через полминуты, и медленный шаг назван, а не спрятан. */
  const realActs=parActs;
  try{
    parActs=function(){};
    PAR.act=null;PAR.actT=0;PAR.actDur=0;
    for(let i=0;i<200;i++)parStep(1/60);
    for(const k of DOF)if(k!=="step")near(PAR[k]||0,0,.005,"птица вернулась в покой по «"+k+"»");
    for(let i=0;i<1800;i++)parStep(1/60);
  }finally{parActs=realActs;}
  near(PAR.step||0,0,.005,"и на место на жёрдочке — за полминуты, по «step»");

  /* 2. Ни одна повадка не выдаёт нечисло ни на одном кадре. */
  let bad="";
  for(const a of PAR_ACT){
    for(let i=0;i<=20;i++){
      const S={};
      a.f(i/20,S);
      for(const k of DOF)if(!isFinite(PAR[k])){bad=a.ru+"/"+k;break;}
      if(!isFinite(PAR.flap)||!isFinite(PAR.crest))bad=a.ru+"/пружина";
      if(bad)break;
    }
    if(bad)break;
  }
  eq(bad,"","ни одна повадка не выдаёт нечисло");

  /* 3. Настроений три, и вместе они покрывают всю таблицу: повадка, до которой
        нельзя добраться ни в одном настроении, — то же враньё, что перк без
        кода. */
  const moods=["c","x","s"];
  const reachable=PAR_ACT.filter(a=>!a.m||moods.indexOf(a.m)>=0);
  eq(reachable.length,PAR_ACT.length,"у каждой повадки настроение из списка");
  for(const m of moods)
    ok(PAR_ACT.some(a=>a.m===m),"в настроении «"+m+"» есть своя повадка");
  ok(PAR_ACT.length>=50,"репертуар не усох: "+PAR_ACT.length+" повадок");

  /* 4. Секвенсор доходит до конца и отпускает: повадка не может застрять. */
  PAR.act=PAR_ACT[0];PAR.actT=0;PAR.actDur=1;PAR.st={};
  for(let i=0;i<40;i++)parActs(.05);
  eq(PAR.act,null,"повадка кончается сама");

  /* 5. Дрёма — фаза, а не финал. Полчаса наблюдения без единого тычка: птица
        не должна спать больше половины времени. Эта проверка стоит здесь
        потому, что две предыдущие модели проваливали её на 0.75 и 0.8. */
  PAR.sleep=0;PAR.mad=0;PAR.napT=0;PAR.act=null;PAR.actNext=0;
  let sleepy=0;const N=36000;
  for(let i=0;i<N;i++){parStep(.05);if(parMood()==="s")sleepy++;}
  ok(sleepy/N<.5,"дрёма занимает меньше половины времени: "+(sleepy/N).toFixed(2));
  ok(sleepy>0,"но птица всё-таки засыпает");

  /* 6. Тычок делает птицу взвинченной, и это состояние живёт достаточно долго,
        чтобы успела начаться сердитая повадка (при старом затухании злости она
        не выпадала ни разу за час). */
  parrotFind(4242,"борта «Проба»");
  PAR.sleep=0;PAR.mad=0;
  parrotPoke(0,-200);
  ok(PAR.mad>.25,"после тычка птица взвинчена");
  eq(parMood(),"x","и настроение это видит");
  let held=0;
  for(let i=0;i<400;i++){parStep(.05);if(parMood()==="x")held++;}
  ok(held>60,"злость держится дольше трёх секунд: "+(held*.05).toFixed(1)+" с");

  /* 7. Одна и та же повадка не идёт подряд: без этого случайность выдаёт
        «переступить, переступить, переступить» именно тогда, когда смотрят. */
  let same=0,prev=null;
  for(let i=0;i<400;i++){
    const a=parPickAct();
    if(a===prev)same++;
    prev=a;
  }
  eq(same,0,"повадка не повторяется подряд");
}));
