TEST_SUITES.push(()=>suite("части: первое поколение генератора не меняется никогда",()=>{
  resetWorld();
  const bad=[];
  for(const row of GUN_FIX_G1){
    const p=genPart(row[0],row[1],row[2],1);
    const aff=p.aff.map(a=>a.k+":"+a.v).join("|");
    if(p.name!==row[3])bad.push(row[0]+" имя: "+p.name+" ≠ "+row[3]);
    if(p.cap!==row[4])bad.push(row[0]+" место: "+p.cap+" ≠ "+row[4]);
    if(aff!==row[5])bad.push(row[0]+" аффиксы: "+aff+" ≠ "+row[5]);
  }
  eq(bad.slice(0,3).join(" ;; "),"","двадцать зёрен первого поколения совпадают");
  /* и через сейв: упакованная часть возвращается СВОИМ поколением */
  const p=genPart(GUN_FIX_G1[0][0],GUN_FIX_G1[0][1],"gun",1);
  p.id="pfix";
  const back=unpackPart(packPart(p));
  eq(back.gen,1,"поколение уехало в сейв и вернулось");
  eq(back.name,p.name,"…и часть та же самая");
  eq(back.aff.map(a=>a.k+":"+a.v).join("|"),p.aff.map(a=>a.k+":"+a.v).join("|"),"вплоть до аффиксов");
}));
