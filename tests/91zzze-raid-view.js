/* ══════════════ автотесты: абордаж — куда смотрит «вверх» ══════════════

   Автор, 2026-08-25, на кадре пиратской базы: «не очень понятно, посмотри на
   перспективу», и в разборе — «человек стоит на потолке». Так и было,
   буквально. Система координат абордажа левая (x — вправо, y — вверх,
   z — ВПЕРЁД), а вектор верха брался как right × fwd, по правилу правой руки.
   В левой системе это ровно «вниз»: измеренный вектор был [0, −0.987, −0.158].
   Кадр рисовался зеркально по вертикали — пол уходил в верхнюю половину,
   потолок в нижнюю, у ходока ноги проецировались выше головы, а контактные
   тени глушила страховка «тень только ниже тела».

   Отсек почти симметричен сверху вниз, поэтому перевёрнутый коридор всё ещё
   выглядел коридором: ошибка прожила от M35 до M180 и была видна только там,
   где в кадр попадали стоящие фигуры и освещение. Глазом такой знак не
   стеречь — его стережёт этот набор. */
TEST_SUITES.push(()=>suite("абордаж: «вверх» смотрит вверх",()=>{
  /* камера смотрит вдоль +Z с небольшим наклоном вниз — как в drawRaid */
  const mk=a=>{
    const fwd=[Math.sin(a),-.16,Math.cos(a)];
    const fl=Math.hypot(fwd[0],fwd[1],fwd[2]);
    fwd[0]/=fl;fwd[1]/=fl;fwd[2]/=fl;
    const right=[Math.cos(a),0,-Math.sin(a)];
    return {fwd,right,up:raidUp(fwd,right)};
  };
  for(const a of [0,1.1,2.4,-0.8,3.9]){
    const v=mk(a);
    ok(v.up[1]>.9,"на курсе "+a.toFixed(1)+" верх направлен вверх (y="+v.up[1].toFixed(3)+")");
    /* верх обязан быть перпендикулярен взгляду и борту — иначе это не базис */
    const d1=v.up[0]*v.fwd[0]+v.up[1]*v.fwd[1]+v.up[2]*v.fwd[2];
    const d2=v.up[0]*v.right[0]+v.up[1]*v.right[1]+v.up[2]*v.right[2];
    ok(Math.abs(d1)<1e-9&&Math.abs(d2)<1e-9,"и стоит поперёк взгляда и борта");
    ok(Math.abs(Math.hypot(v.up[0],v.up[1],v.up[2])-1)<1e-9,"и он единичный");
  }
}));

/* Проверка не вектора, а КАДРА: повторяем проекцию drawRaid целиком и
   спрашиваем у неё то, что спрашивал автор — где пол, где потолок и где у
   человека ноги. Такой тест переживёт любую переделку камеры: он не знает
   про cross product, он знает, что пол должен быть внизу. */
TEST_SUITES.push(()=>suite("абордаж: пол внизу, потолок вверху, ноги под головой",()=>{
  const W=1280,H=800,back=118,camY=78,CEIL=170;
  const cam=[0,camY,-back];
  const fwd=[0,-.16,1];const fl=Math.hypot(fwd[0],fwd[1],fwd[2]);
  fwd[0]/=fl;fwd[1]/=fl;fwd[2]/=fl;
  const right=[1,0,0], up=raidUp(fwd,right);
  const F=Math.min(W,H)*.95, CY=H*.44;
  const py=(x,y,z)=>{
    const vx=x-cam[0],vy=y-cam[1],vz=z-cam[2];
    const zc=vx*fwd[0]+vy*fwd[1]+vz*fwd[2];
    if(zc<8)return null;
    return CY-(vx*up[0]+vy*up[1]+vz*up[2])*F/zc;
  };
  /* «Ниже на экране» — это БОЛЬШЕЕ y: ось канвы растёт вниз. */
  for(const z of [200,400,800,1600]){
    ok(py(0,0,z)>py(0,CEIL,z),"на глубине "+z+" пол ниже потолка");
  }
  /* Пол уходит к горизонту снизу вверх, потолок — сверху вниз, и оба сходятся
     в одну линию: это и есть читаемое пространство. */
  ok(py(0,0,200)>py(0,0,800)&&py(0,0,800)>py(0,0,3000),"пол поднимается к горизонту");
  ok(py(0,CEIL,200)<py(0,CEIL,800)&&py(0,CEIL,800)<py(0,CEIL,3000),"потолок опускается к горизонту");
  const hzF=py(0,0,90000),hzC=py(0,CEIL,90000);
  ok(Math.abs(hzF-hzC)<2,"и сходятся в один горизонт ("+Math.round(hzF)+" и "+Math.round(hzC)+")");
  /* Горизонт выше середины кадра — кадрирование открыткой (M180): пол
     получает больше кадра, чем потолок. */
  ok(hzF<H*.5,"горизонт выше середины кадра ("+Math.round(hzF)+" из "+H+")");
  /* И то, с чего всё началось: у стоящего человека ноги ниже головы. */
  for(const z of [0,300,900]){
    ok(py(0,0,z)>py(0,60,z),"на глубине "+z+" ноги ниже головы");
  }
}));
