/* ══════════════ картина не портится молча (M336) ══════════════
   С M241 кадр меряется: `lookAll` обходит сцены и печатает пять чисел на
   каждую. Числа эти читает человек — и только когда сам решит посмотреть. А
   картинка портится обычно не тогда, когда её правят, а когда правят соседнее:
   поменял тон облака — потемнело небо во всех дневных сценах; тронул кэш
   растра — перестала печься развёртка планеты; поправил порядок слоёв — ушёл
   контраст. Ни один тест этого не видит: сцены рисуются «не пустыми», кнопки
   нажимаются, исключений нет.

   Поэтому здесь эталон: числа сцен, снятые 04.09.2026 на 1280×800, с широкими
   полями допуска. Это не мишень (мишени живут в `LOOK_TARGET` и часть сцен их
   честно не берёт) — это СЕТЬ: она ловит не «некрасиво», а «стало заметно
   другим, чем было, и никто этого не заметил».

   Поле — не вкус, а шум прибора: сцены с погодой и часом гуляют, поэтому
   контраст ±0.18, массы ±16 пунктов, тона ±3. Провал означает не «плохо», а
   «посмотри глазами и обнови эталон, если так и хотел». */

/* сцена → четыре числа осевшего кадра. Снято 04.09.2026, 1280×800, 40 кадров
   на сцену, после починки воспроизводимости сцен (M336) */
const LOOK_BASE = {
  "система": { tones: 5, mass: 20, contrast: .88, empty: 63 },
  "карта": { tones: 4, mass: 5, contrast: .25, empty: 61 },
  "заход": { tones: 2, mass: 39, contrast: .37, empty: 69 },
  "грунт день": { tones: 3, mass: 30, contrast: .53, empty: 47 },
  "грунт ночь": { tones: 4, mass: 6, contrast: .20, empty: 63 },
  "шахта": { tones: 5, mass: 43, contrast: .36, empty: 56 },
  "пещера": { tones: 3, mass: 11, contrast: .35, empty: 78 },
  "пояс": { tones: 4, mass: 4, contrast: .33, empty: 61 },
  "рейд": { tones: 2, mass: 12, contrast: .33, empty: 56 },
  "черпак": { tones: 10, mass: 44, contrast: .62, empty: 22 },
  "база": { tones: 5, mass: 7, contrast: .34, empty: 74 },
  "дом": { tones: 3, mass: 16, contrast: .44, empty: 46 }
};
TEST_SUITES.push(() => suite("картина: ни одна сцена не уехала от эталона кадра", () => {
  /* прибор мерит настоящий кадр, а в телефонном окне кадр другой: там свой
     разбор, свои пэды и свой масштаб. Эталон снят на 1280×800 — в другом
     окне не судим, чтобы не врать числами */
  if (W < 1000 || H < 600) { ok(true, "окно не то, в котором снят эталон (" + W + "×" + H + ") — пропуск"); return; }
  /* ── меряем ОСЕВШИЙ кадр, а не первый ──
     Развёртка планеты печётся по кадрам (`planetStripTick`, бюджет на кадр), и
     после M332 растр покинутых систем отпускается — значит, придя в сцену, мы
     застаём её холодной. Три кадра давали планету плоским диском: контраст
     0.15 вместо 0.88 и 83% пустоты вместо 53. Игрок этого кадра не видит — он
     видит устоявшийся, — поэтому и прибор смотрит на устоявшийся. */
  resetWorld();
  const rows = [];
  for (const sc of lookScenes()) {
    resetWorld();
    let set = true;
    try { set = sc.set() !== false; } catch (e) { continue; }
    if (!set || G.mode === "none") continue;
    try {
      for (let i = 0; i < 40; i++) { G.t++; stepWorld(1); drawWorld(); }
      rows.push(Object.assign({ "сцена": sc.id }, lookFrame()));
    } catch (e) { rows.push({ "сцена": sc.id, "ошибка": e.message }); }
  }
  ok(rows.length >= 8, "сцен измерено: " + rows.length);
  const bad = [], seen = [];
  for (const r of rows) {
    const B = LOOK_BASE[r["сцена"]];
    if (!B) { seen.push(r["сцена"] + " (нет в эталоне)"); continue; }
    if (r["ошибка"]) { bad.push(r["сцена"] + ": " + r["ошибка"]); continue; }
    seen.push(r["сцена"]);
    if (Math.abs(r.contrast - B.contrast) > .18) bad.push(r["сцена"] + " · контраст " + r.contrast + " против " + B.contrast);
    if (Math.abs(r.mass - B.mass) > 16) bad.push(r["сцена"] + " · вторая масса " + r.mass + " против " + B.mass);
    if (Math.abs(r.tones - B.tones) > 3) bad.push(r["сцена"] + " · тонов " + r.tones + " против " + B.tones);
    if (Math.abs(r.empty - B.empty) > 18) bad.push(r["сцена"] + " · пусто " + r.empty + "% против " + B.empty + "%");
  }
  ok(seen.length >= 8, "сверено с эталоном: " + rows.map(r => r["сцена"] + " " + r.tones + "/" + r.mass + "/" + r.contrast + "/" + r.empty).join(" | "));
  eq(bad.slice(0, 4).join(" ;; "), "", "картина держится эталона (поле: контраст ±.18, масса ±16, тона ±3, пусто ±18)");
  resetWorld();
}));
