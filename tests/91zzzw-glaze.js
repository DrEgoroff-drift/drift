/* ══════════════ лессировка P4: форму печёт серое, цвет даёт свет ══════════════
   Десятый закон ремесла (`docs/DESIGN-craft.md` § P4, `src/18a1-glaze.js`).
   Набор держит не картинку, а АЛГЕБРУ под нею: заявлено, что двухточечная
   лессировка — это тот же `litRGB`, у которого ламбертов множитель взят из
   серого прохода. Если это правда, её можно проверить числами и без канвы;
   если однажды перестанет быть правдой, свет разъедется, и никакой снимок
   этого не назовёт — скажет только «стало хуже».

   Здесь же прибит и порядок проходов: серое значит «покрась меня», цвет —
   «я свой». Рисовальщик, забывший спросить проход, красит дважды. */

TEST_SUITES.push(()=>suite("лессировка P4: свет вместо палитры, и это тот же свет",()=>{
  resetWorld();
  const p=G.sys.planets.find(x=>x.type!=="gas")||G.sys.planets[0];
  const base=[190,176,150];
  const sun=starRGB(), amb=ambRGB(p), k=ambK(p), df=.78;

  /* ── концы лессировки — это концы litRGB ──
     светлый конец: полностью освещено, I = df; тёмный: только небо. */
  const st=glazeStops(base,p,df);
  for(let i=0;i<3;i++)
    near(st.light[i],base[i]*(k*amb[i]/255+df*sun[i]/255),.6,
      "светлый конец — небо плюс звезда, канал "+i);

  /* ── и настоящий litRGB лежит МЕЖДУ ними ──
     Вот ради чего закон написан: раньше свет считался для одной ленты склона,
     теперь тот же отрезок достаётся всему разрезу. Если litRGB вышел за концы,
     значит лессировка светит НЕ ТЕМ светом, и разрез разойдётся с полосами. */
  const lit=litRGB(base,0,p,sun,amb,k,df);
  for(let i=0;i<3;i++){
    ok(lit[i]>=Math.floor(st.dark[i])-1,"плоский склон не темнее тени, канал "+i+
      " ("+lit[i]+" против "+Math.round(st.dark[i])+")");
    ok(lit[i]<=Math.ceil(st.light[i])+1,"и не светлее полного света, канал "+i+
      " ("+lit[i]+" против "+Math.round(st.light[i])+")");
  }

  /* ── пол тени ходит вместе с днём ──
     Днём небо в трещину не достаёт: его перекрывает освещённая порода, и пол
     душит тень до GLAZE_FLOOR. Ночью перекрывать нечем — небо единственный
     свет, и пол обязан уйти в единицу, иначе грунт вне фонаря чернеет
     (замер 09.09.2026: tones 6 → 4 и чёрная пустота на кадре). */
  const celReal=celSun;
  const floorAt=()=>GLAZE_FLOOR+(1-GLAZE_FLOOR)*(1-clamp(dayKq(p),0,1));
  try{
    celSun=()=>({alt:1,az:0});                 /* полдень */
    const day=glazeStops(base,p,df), ambDay=ambRGB(p), flDay=floorAt();
    celSun=()=>({alt:-1,az:0});                /* полночь */
    const night=glazeStops(base,p,df), ambNight=ambRGB(p), flNight=floorAt();
    eq(flNight,1,"в полночь пол ушёл в единицу");
    ok(flDay<flNight,"а в полдень он ниже: "+flDay.toFixed(2)+" против "+flNight);
    for(let i=0;i<3;i++){
      near(day.dark[i],base[i]*(k*ambDay[i]/255)*flDay,.6,
        "в полдень тень задушена полом, канал "+i);
      near(night.dark[i],base[i]*(k*ambNight[i]/255),.6,
        "в полночь небо доходит до дна целиком, канал "+i);
    }
  }finally{celSun=celReal;}

  /* ── серое той же светлоты ──
     Рисовальщик, который брал тон из палитры, теперь берёт из неё светлоту.
     Значит порядок слоёв обязан пережить перевод: что было светлее по цвету,
     остаётся светлее по серому, иначе пласты поменяются местами. */
  const g1=greyOf([200,180,140]),g2=greyOf([90,80,60]);
  const v=s=>+s.slice(4).split(",")[0];
  ok(/^rgb\((\d+),\1,\1\)$/.test(g1),"серое и правда серое: "+g1);
  ok(v(g1)>v(g2),"светлее по цвету — светлее по серому: "+v(g1)+" > "+v(g2));

  /* ── подмалёвок пишут контрастнее готового ──
     Два залива сжимают шкалу, значит гризайль растягивают вокруг середины
     ровно на столько же. Середина — неподвижная точка, края не убегают. */
  eq(greyStretch(128),128,"середина шкалы на месте");
  ok(greyStretch(200)>200,"светлое уходит выше");
  ok(greyStretch(60)<60,"тёмное уходит ниже");
  eq(greyStretch(255),255,"и за белое не вылезает");
  eq(greyStretch(0),0,"и за чёрное тоже");
}));

TEST_SUITES.push(()=>suite("лессировка P4: серое значит «покрась меня», цвет — «я свой»",()=>{
  /* Девять событий пекла не выводятся из светлоты: жила и кромка грани дают
     ОДНУ светлоту при разных тонах. Свести их в один канал можно, разделить
     обратно нельзя — поэтому они рисуются ПОСЛЕ лессировки и под неё не
     попадают. Проход глобальный, и это единственное, что их разводит. */
  const was=GLAZE_PASS;
  try{
    GLAZE_PASS="";
    ok(glazeIsForm()&&glazeIsHue(),"вне пекла рисовальщик кладёт всё разом");
    GLAZE_PASS="form";
    ok(glazeIsForm(),"в проходе формы — форма");
    ok(!glazeIsHue(),"и ни одного собственного цвета: его перекрасит лессировка");
    GLAZE_PASS="hue";
    ok(!glazeIsForm(),"в проходе оттенка форма уже испечена");
    ok(glazeIsHue(),"а цвет ложится поверх");
  }finally{GLAZE_PASS=was;}
}));
