/* ══════════════ цели кадра зала переживают смену станции (24.10, телефон) ══════════════ */
/* 27f4a: цели кадра зала (MSAA цвета и дыма, глубина, отсвет — 116 МБ при ×2 на телефоне) зависят от экрана, не от
   станции. hallRelease (новая станция в заготовке) их освобождал, и первый же шаг заготовки заводил их заново: на S23
   видеокарта стояла 50 мс через 0,23 с после каждого прыжка в систему со станцией (тестер, раунд 9). Теперь уходят
   только привязки холста — они держат текстуры прежней станции */
TEST_SUITES.push(()=>suite("зал станции: цели кадра переживают смену станции",{tier:"browser"},()=>{
  if(!ok(GPU.ok&&!!GPU.dev&&!!$st,"видеокарта и док поднялись"))return;
  resetWorld();
  const cn=hallCanvas();hallSize(cn);const R=rpgGet(cn);
  if(!ok(!!R&&r3Dev(),"холст зала на движке"))return;
  const T=r3Targets(R,cn.width,cn.height);R.bg.set("прежняя станция",{});
  const open=HALL.open;HALL.open=false;
  try{hallRelease();}finally{HALL.open=open;}
  ok(R.r3===T,"цели кадра те же: новая станция их не заводит");
  eq(R.bg.size,0,"привязки холста прежней станции ушли");
  ok(r3Targets(R,cn.width,cn.height)===T,"шаг заготовки на новой станции берёт готовые цели");
}));
