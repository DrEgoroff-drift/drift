/* ══════════════ печь: сколько растра игра держит и сколько печёт заново (M358) ══════════════
   «Жёсткое зависание» автора ищут с M238. Списки в состоянии не растут (M329),
   документ не растёт (M332), растр в кэше систем стоит на полке (M332). Оставался
   третий подозреваемый, которого не мерил никто: РАСТР ЖИВОГО КАДРА — ломти
   грунта, тайлы дальних гряд и пещеры, экранные слои. Он лежит не в SYS_CACHE,
   а на `G`, и потому мимо набора «вечер прыжков» проходил целиком.

   Меряем две разные беды, и обе не видны ни в одном кадре по отдельности:

   1. ПЕЧЬ РАБОТАЕТ КАЖДЫЙ КАДР. Ключ слоя или ломтя, в который попала
      непрерывно меняющаяся величина (час, сила погоды, точная камера), даёт
      промах на каждом кадре: игра печёт полноэкранный холст шестьдесят раз в
      секунду и тут же его выбрасывает. Ни память, ни консоль об этом не скажут
      ни слова — скажет только счётчик испечённого. Стоя на месте игра обязана
      печь считанные разы за сотни кадров (сейчас 7 на 300 — это час суток
      сдвинул подмес воздуха, и так и должно быть).

   2. УРОВЕНЬ, А НЕ РОСТ. Растр не течёт — он просто стоит высоко. Меряем в
      ЭКРАНАХ (пиксели растра / пиксели кадра), потому что мегабайты здесь
      ничего не значат: холсты пекутся плотнее кадра в `DPR*SCK` раз, и то же
      число на ретине с большим окном означает вдевятеро больше памяти
      (`RAST_MAX` держит `DPR*SCK` не выше 3, то есть площадь — не выше
      девятикратной). Замер 05.09.2026 в окне 1248×641 при DPR=1: поверхность
      держит около шестнадцати экранов, из них farA 10 тайлов при шести
      рисуемых, farB 16 при восьми, рельеф 6 при трёх — то есть каждое
      хранилище держит вдвое против кадра. Это запас на ход камеры, он нужен;
      но он же означает, что у пользователя с ретиной счёт идёт на сотни
      мегабайт, и порог ниже — это уже разговор о размене «память против
      перепекания», а не молчаливая правка.

   Сторож ловит удвоение того и другого. */
function bakeCount(fn){
  const orig=document.createElement.bind(document);
  let made=0;
  document.createElement=function(t){
    if(String(t).toLowerCase()==="canvas")made++;
    return orig(t);
  };
  try{fn();}finally{document.createElement=orig;}
  return made;
}
/* растр, лежащий на живом состоянии, в ЭКРАНАХ кадра */
function liveScreens(){
  const px=memPixels(G,8).px+[...SCREEN_LAYERS.values()].reduce((a,c)=>a+c.width*c.height,0);
  return px/Math.max(1,W*H*DPR*SCK*DPR*SCK);
}

TEST_SUITES.push(() => suite("печь: стоя на месте игра не печёт заново каждый кадр", () => {
  resetWorld();
  plLand(G.sys, G.sys.planets.find(p => p.type !== "gas") || G.sys.planets[0]);
  const spin = n => { for (let i = 0; i < n; i++) { try { stepWorld(1); drawWorld(); } catch (e) {} G.t += 1; } };
  spin(40);                                   /* прогрев: первый кадр имеет право испечь всё */
  const still = bakeCount(() => spin(150));
  ok(still < 25, "поверхность стоя: испечено " + still + " холстов на 150 кадров");
  /* ход камеры печёт новые ломти — это законно, но по РАССТОЯНИЮ, а не по
     кадрам: 3000 px мира это шесть ломтей по 512, а не триста */
  const walk = bakeCount(() => {
    for (let i = 0; i < 150; i++) { G.surf.x += 20; G.surf.cam.x += 20; try { stepWorld(1); drawWorld(); } catch (e) {} G.t += 1; }
  });
  ok(walk < 90, "поверхность идя 3000 px: испечено " + walk + " холстов (законно — новые ломти)");
  resetWorld();
  G.mode = "system";
  spin(40);
  const sys = bakeCount(() => spin(150));
  ok(sys < 25, "система: испечено " + sys + " холстов на 150 кадров");
  resetWorld();
}));

TEST_SUITES.push(() => suite("печь: живой кадр держит растра не больше, чем нужно кадру", () => {
  resetWorld();
  plLand(G.sys, G.sys.planets.find(p => p.type !== "gas") || G.sys.planets[0]);
  for (let i = 0; i < 30; i++) { try { stepWorld(1); drawWorld(); } catch (e) {} G.t += 1; }
  for (let i = 0; i < 200; i++) { G.surf.x += 48; G.surf.cam.x += 24; try { stepWorld(1); drawWorld(); } catch (e) {} G.t += 1; }
  const surf = liveScreens();
  /* Порог — не «сколько сейчас», а «сколько нельзя»: замер дал ~16 экранов,
     держим вдвое. Уедет за 30 — значит кто-то удвоил запас, и на ретине это
     сотни мегабайт, о которых никто не узнает до чужого зависания. */
  ok(surf < 40, "поверхность после прогулки держит " + surf.toFixed(1) + " экранов растра" +
    " (окно " + Math.round(W) + "×" + Math.round(H) + ", DPR " + DPR + ", SCK " + SCK.toFixed(2) + ")");
  /* и каждое хранилище держит не больше, чем впятеро против рисуемого в кадре:
     запас на ход камеры законен, склад — нет */
  const held = st => (st && st.map) ? st.map.size : 0;
  const a = held(G.surf.farA), b = held(G.surf.farB), c = held(G.surf.tr && G.surf.tr.chunks);
  ok(a <= TILE_KEEP && b <= TILE_KEEP, "тайлы дальних гряд в пределах TILE_KEEP: farA " + a + ", farB " + b + " из " + TILE_KEEP);
  ok(c <= CHUNK_KEEP, "ломтей рельефа в пределах CHUNK_KEEP: " + c + " из " + CHUNK_KEEP);
  resetWorld();
}));
