/* ══════════════ автотесты: что уезжает в crash.log (0.419) ══════════════
   Логгер (01a-crashlog) шлёт на сервер всё, что похоже на ошибку, и это верно.
   Неверным было другое: до 0.419 письмо уходило на КАЖДЫЙ «warn» судового
   журнала, а «warn» в игре — это новость, а не беда. Дрон встал в док, пираты
   закрепились в секторе, смотритель ворчит про голый процент: за четверо суток
   сто строк из ста шестнадцати в crash.log оказались игрой, и настоящую улику в
   этой стене стало не найти. Улику теперь называет тот, кто её нашёл — `logShip`.
   Проверять это в Node напрямую нельзя: `crashShip` на стенде молчит нарочно.
   Поэтому набор читает саму сборку — так же, как набор летописи читает её на
   дробную математику. */
TEST_SUITES.push(()=>suite("crash.log: на сервер уходят улики, а не новости",()=>{
  const src=document.scripts[0].textContent;
  ok(src.indexOf("function logShip(")>0,"улику шлёт logShip");
  /* ровно одно место во всей сборке шлёт журнал на сервер — сам logShip */
  /* иглы собираются по кускам: набор лежит в той же сборке и нашёл бы сам себя */
  const needle="crashShip("+'"journal"';
  eq(src.split(needle).length-1,1,"журнал уходит на сервер ровно из одного места");
  /* и никакой подмены logAdd, которая отправляла бы каждый «warn» */
  ok(src.indexOf("const la="+"logAdd;logAdd=function")<0,"logAdd никто не подменяет ради отправки");
  /* улики, которые обязаны доезжать */
  for(const s of ["Браузер не даёт записывать","Запись не собралась","Облако: вход устарел",
                  "Облако: запись слишком велика","Летопись разошлась"])
    ok(src.indexOf('logShip("'+s)>0,"улика едет на сервер: "+s);
  /* а обычные новости журнала — нет */
  for(const s of ["Дрон ","Пираты закрепились","на голом проценте"])
    ok(src.indexOf('logShip("'+s)<0,"новость на сервер не едет: "+s);
}));
