/* ══════════════ перо ══════════════
   Одно перо на всю птицу — остальное делают инстансы.

   ФОРМА взята с настоящего контурного пера, а не выдумана: узкая ножка
   (очин), быстрое расширение, самое широкое место чуть ниже середины, мягкий
   овальный кончик — и лёгкая АСИММЕТРИЯ, потому что у пера две половины
   опахала разной ширины. Симметричный лист читается лепестком.

   ПРАВИЛО (то же, что в двумерной птице): щель между перьями заметнее самого
   пера. Ряды кладутся черепицей с перекрытием, и под ними всегда лежит тёмная
   масса тела.

   Прозрачности нет ни грамма: контур пера — это геометрия. Так перья честно
   попадают в карту теней и не требуют сортировки. */
/* ── ПУХ ОТДЕЛЬНОЙ ФОРМОЙ ──
   Пушистость не берётся числом перьев: три яруса одинаковых овалов дают
   бронированную чешую, сколько их ни клади. Пух — это другая ФОРМА: широкое
   мягкое основание и длинный сходящий на нить кончик, который торчит из
   кладки наружу. Именно эти нити и рвут силуэт, а рваный силуэт и читается
   как пух. */
function buildFeather(cols,rows,flight,downy){
  const M={v:[],i:[],n:0};
  const P=[];
  /* полуширина по длине: очин — почти нить, дальше резкое расширение,
     широкое место на 0.45, к концу мягкий спад и овал */
  const wid=v=>{
    const x=clamp(v,0,1);
    if(downy){
      /* пух: раздувается сразу у корня, к концу сходит на нет — но не в
         иглу. Показатель 1.55 давал ровный шип, и птица вышла репейником:
         пушинка обязана быть широкой почти до конца и только у самого
         кончика сойтись, тогда это пух, а не колючка. */
      const grow=smooth(0.0,0.10,x);
      return grow*Math.pow(1.0-x*x*0.92,0.80)*1.16;
    }
    const grow=smooth(0.0,0.16,x);                 /* очин */
    const body=Math.pow(Math.sin(Math.pow(x,0.62)*Math.PI),flight?0.30:0.44);
    const tipR=Math.sqrt(Math.max(0,1-Math.pow(Math.max(0,(x-0.80)/0.20),2)));
    return grow*body*tipR;
  };
  /* асимметрия: одна половина опахала шире другой — примета настоящего пера */
  const half=(u)=>u<0?1.0:(flight?0.72:(downy?0.94:0.86));
  /* чашка опахала и выгиб стержня; у махового чашка глубже.
     У пуха выгиб СИЛЬНЫЙ: он загибается наружу дугой, и потому лежит не
     плашмя, а поднятым — свет проходит между кончиками */
  const cup=(u,v)=>downy?(-0.10*u*u*wid(v)-0.34*v*v)
                        :(-(flight?0.34:0.26)*u*u*wid(v)-0.13*v*v);
  for(let i=0;i<rows;i++){
    const v=i/(rows-1),row=[];
    for(let j=0;j<cols;j++){
      const u=(j/(cols-1)-0.5)*2;
      row.push([u*wid(v)*half(u)*0.5,cup(u,v),v]);
    }
    P.push(row);
  }
  const at=(i,j)=>P[clamp(i,0,rows-1)][clamp(j,0,cols-1)];
  const V=[];
  for(let i=0;i<rows;i++)for(let j=0;j<cols;j++){
    const du=vSub(at(i+1,j),at(i-1,j)),dv=vSub(at(i,j+1),at(i,j-1));
    let n=vNorm(vCross(dv,du));
    if(n[1]<0)n=vMul(n,-1);
    const u=(j/(cols-1)-0.5)*2,v=i/(rows-1);
    V.push(...at(i,j),...n,u,v);
  }
  const idx=[];
  for(let i=0;i<rows-1;i++)for(let j=0;j<cols-1;j++){
    const a=i*cols+j,b=a+1,c=a+cols,d=c+1;
    idx.push(a,c,b,b,c,d);
  }
  return {verts:new Float32Array(V),index:new Uint16Array(idx),stride:8,
          attrs:[["p",3,0],["n",3,3],["uv",2,6]]};
}

/* ── укладка ──
   Инстанс: матрица 3×4 (12), цвет (3), настройки (4: чашка, выгиб, t хребта,
   род пера). Строится один раз — поза живёт в вершинной программе. */
const FEA_STRIDE=19;
function feaPush(out,p,dir,up,len,wid,col,par,roll){
  const Z=vNorm(dir);
  let Y=vNorm(vSub(up,vMul(Z,vDot(up,Z))));
  if(vLen(Y)<1e-4)Y=basisFrom(Z)[1];
  /* поворот пера вокруг собственной оси: без него пучок перьев лежит в одной
     плоскости и читается веером из бумаги. Часть перьев обязана стоять ребром */
  if(roll){
    const c=Math.cos(roll),s=Math.sin(roll),X0=vCross(Y,Z);
    Y=vAdd(vMul(Y,c),vMul(X0,s));
  }
  const X=vCross(Y,Z);
  /* матрица кладётся тремя строками по четыре: столбцы — оси, четвёртое
     число строки — сдвиг. Так в шейдере она читается тремя vec4 */
  out.push(X[0]*wid,Y[0]*wid,Z[0]*len,p[0],
           X[1]*wid,Y[1]*wid,Z[1]*len,p[1],
           X[2]*wid,Y[2]*wid,Z[2]*len,p[2],
           col[0],col[1],col[2],
           par[0],par[1],par[2],par[3]);
}
/* тангенс «к хвосту» на поверхности тела: перо всегда лежит вдоль потока */
function flowAt(t,a){
  const e=0.012;
  const p1=bodyAt(clamp(t-e,0,1),a),p2=bodyAt(clamp(t+e,0,1),a);
  return vNorm(vSub(p1,p2));      /* от головы к хвосту */
}
/* нормаль берётся из 20-body: одна формула на тело и на перья */
const normalAt=(t,a)=>bodyNormal(t,a);

/* ── оперение корпуса ──
   Ряды снизу вверх, каждый следующий перекрывает предыдущий. Шаг ряда меньше
   длины пера — иначе между рядами видно тело. */
/* шары вдоль клюва и восковицы: перьев внутри них не бывает */
/* шары вдоль клюва: перьев внутри них нет. Радиусы нарочно МЕНЬШЕ самого
   клюва — перья должны наезжать на его основание, иначе между рогом и
   оперением остаётся тёмная щель, как будто клюв приклеили */
const BEAK_BALLS=[
  [0,1.800,0.150,0.104],[0,1.784,0.250,0.106],[0,1.758,0.348,0.100],
  [0,1.714,0.430,0.088],[0,1.656,0.480,0.074],[0,1.672,0.176,0.096]
];
const COAT_STAT={all:0,head:0,cut:0};
const PLUME_STAT=[];
/* Укладка вызывается ДВАЖДЫ: сперва подпушь — мелкое частое перо, потом
   крупные пластины поверх. Иерархия, а не компромисс: подпушь закрывает кожу и
   даёт плотность, пластины держат силуэт. Один и тот же код, разные числа. */
function layoutCoat(rows,dens,scale,seed,downy){
  const out=[],R=rnd(seed||0x7b1d);
  const SC=scale||1;
  const ROWS=rows||34,DENS=dens||52;
  for(let r=0;r<ROWS;r++){
    const t0=mix(0.055,0.995,r/(ROWS-1));
    const S=spineAt(t0);
    const girth=(S.rw+S.rf+S.rb)*0.5;
    /* на голове перьев ВДВОЕ гуще: они там мельче, и той же плотности не
       хватает — между ними проступает кожа. Это не украшение, это единственный
       способ иметь мелкое перо и не облысеть */
    const n=Math.max(7,Math.round(girth*DENS*mix(1.0,3.10,smooth(0.70,0.92,t0))));
    for(let j=0;j<n;j++){
      const a=(j+(r%2)*0.5)/n*TAU+R()*0.10;
      /* ряд не должен читаться рядом: каждое перо гуляет вдоль хребта на
         полшага, и черепица становится оперением, а не кладкой */
      const t=clamp(t0+(R()-0.5)*0.028,0.03,0.998);
      /* Голое место на птице — только клюв, восковица и кольцо у глаза.
         Граница считается по РАССТОЯНИЮ до частей, а не коробкой: коробка
         режет оперение прямой линией, и у основания клюва получался ровный
         вертикальный срез, какого на птице не бывает. */
      const base=bodyAt(t,a);
      let bare=false;
      for(const b of BEAK_BALLS){
        const d=Math.hypot(base[0]-b[0],base[1]-b[1],base[2]-b[2]);
        if(d<b[3]){bare=true;break;}
      }
      /* ВОКРУГ ГЛАЗА ПЛАСТИН НЕТ ВОВСЕ. Пластина лежит по потоку — назад, — и
         та, что растёт перед глазом, накрывает его кончиком: при срезе в 86 мм
         глаз просто зарастал. Но и широкий срез не годится, он и был тем
         гладким блином. Поэтому пластины убраны из всего кольца, а кольцо
         отдано розетке (ниже): её перья смотрят ОТ глаза и закрыть его не
         могут. Подпушь мельче и мягче, ей хватает узкого среза. */
      if(!bare)for(const sx of [-1,1]){
        const d=Math.hypot(base[0]-sx*0.252,base[1]-1.758,base[2]-0.108);
        if(d<(downy?0.100:0.150)){bare=true;break;}
      }
      if(bare){COAT_STAT.cut++;continue;}
      COAT_STAT.all++; if(base[1]>1.60)COAT_STAT.head++;
      const p=normalAt(t,a);
      const dir=flowAt(t,a);
      /* Перо ДЛИННЕЕ шага ряда втрое: у настоящей птицы видно не перья, а их
         кончики — черепица, где каждое следующее прикрывает предыдущее на две
         трети. Пока длина была равна шагу, оперение читалось мозаикой из
         бумажных фишек. */
      /* КРУПНЫЕ МАССЫ. Три тысячи одинаковых перьев дают шум, в котором глазу
         не за что зацепиться: перьев теперь впятеро меньше, и каждое — не
         чешуйка, а пластина. Мелкое остаётся только на голове. */
      /* У ПУХА длина гуляет вдвое сильнее и в среднем БОЛЬШЕ пластины: пух,
         спрятанный под пластинами, не виден вовсе — а виден он только там,
         где вылез наружу. Каждое седьмое пёрышко ещё и вдвое длиннее: это те
         самые волоски, что торчат из птицы против света. */
      const lenK=downy?(0.66+R()*0.52)*(R()<0.07?1.70:1.0):(0.90+R()*0.20);
      const len=mix(0.335,0.072,smooth(0.06,0.72,t))*lenK*SC;
      /* НАСКОЛЬКО поднят конец пера — считается, а не подбирается. Перо
         лежит по касательной, а тело под ним круглое: на голове радиусом
         0.28 перо длиной 0.09 уходит под поверхность на полтора сантиметра
         и пропадает совсем. Первая версия так и потеряла всё оперение
         головы — осталась голубая лысина. Наклон len/2R как раз выводит
         кончик обратно наружу, дальше — вкус. */
      const meanR=Math.max(0.10,(S.rw+S.rf+S.rb)/3);
      /* на голове перо прижато сильнее: мелкие перья с тем же подъёмом, что на
         груди, встают дыбом и читаются щетиной */
      const liftK=mix(1.0,downy?0.80:0.55,smooth(0.72,0.92,t));   /* пуху на голове прижиматься незачем: он и есть мягкость */
      /* ПУШИСТОСТЬ: конец пера поднят выше и гуляет сильнее. Ровно прижатое
         перо даёт гладкую черепицу, а пух — это когда кончики смотрят
         врозь и между ними ходит свет */
      /* У ПУХА кончик задран куда сильнее, и разброс направлений втрое шире.
         Прижатый пух — это просто ещё один слой черепицы; пух работает
         тогда, когда его кончики смотрят врозь и наружу. */
      const lift=downy?(0.14+len/(2.4*meanR)+R()*0.16)*liftK
                      :(Math.min(0.26,0.10+len/(2*meanR))+R()*0.09)*liftK;
      const J=downy?1.55:1.0;
      const d2=vNorm(vAdd(vAdd(dir,vMul(p,lift)),
        [(R()-0.5)*0.16*J,(R()-0.5)*0.10*J,(R()-0.5)*0.16*J]));
      /* пух УЗКИЙ: широкий пух — это опять пластина */
      const wid=len*(downy?mix(0.30,0.46,R()):mix(0.50,0.72,R()));
      const col=bodyColor(t,a);
      /* пух светлее пера: он тоньше, и свет проходит его насквозь */
      const cv=(0.92+R()*0.14)*(downy?1.05:1.0);
      /* каждое шестое перо груди отдаёт в голубой: на листе кремовое поле не
         монолитное, по нему идут холодные канты */
      const cool=R()<0.05?0.10+R()*0.08:0;
      /* тёплый-холодный разброс по перьям: ровное поле одного цвета читается
         краской, а не оперением. Сдвиг мелкий — породу он не трогает. */
      const wc=(R()-0.5)*0.020;
      const cc=cool?vLerp(col,BIRD_C.blueL,cool):col;
      /* пух ВЫГИБАЕТСЯ дугой и стоит вразворот: род -1 — он и в шейдере
         светится на просвет иначе, чем перо (30-shade) */
      feaPush(out,vAdd(base,vMul(p,downy?-0.016:-0.006)),d2,p,len,wid,
        [cc[0]*cv*(1+wc),cc[1]*cv,cc[2]*cv*(1-wc)],
        [1.0,downy?(0.10+R()*0.14):(0.04+R()*0.06),t,downy?-1.0:0.0],
        downy?(R()-0.5)*1.9:0);
    }
  }
  if(downy)return new Float32Array(out);  /* подпушь венца не строит: он поверх */
  /* ── ВЕНЕЦ ──
     На самом темени сечение лофта вырождается в точку: перьев там выходит
     считаные штуки, и между ними видно тёмную кожу полюса — на снимке сверху
     это читается дырой в голове. Венец кладётся отдельно: кольцо перьев вокруг
     полюса, все направлены назад и внахлёст перекрывают макушку. */
  /* ТРИ КОЛЬЦА, а не одно. Одно кольцо из девяти перьев закрывает полюс
     только сверху: стоит отвести камеру на два шага в сторону — и между
     перьями снова видно тёмное темя. Кольца идут внахлёст, азимуты сбиты
     на полшага, и каждое следующее короче: получается не венец, а шапка. */
  {
    const RINGS=[[0.936,17,0.255,0.00],[0.962,14,0.225,0.19],
                 [0.982,11,0.195,0.41],[0.994,8,0.165,0.63]];
    for(const [t,N,len,ph] of RINGS){
      for(let i=0;i<N;i++){
        const a=(i/N+ph)*TAU;
        const base=bodyAt(t,a),p=normalAt(t,a);
        /* перо кладётся НАЗАД И НАРУЖУ: направленное строго от полюса, оно
           встаёт торчком и между соседями всё равно щель */
        const dir=vNorm(vAdd(vNorm([Math.cos(a)*0.62,0.24,-0.90+Math.sin(a)*0.18]),
          vMul(p,0.26)));
        const col=bodyColor(t,a);
        const cv=0.94+R()*0.10;
        feaPush(out,vAdd(base,vMul(p,-0.005)),dir,p,len*(0.92+R()*0.18),len*0.66,
          [col[0]*cv,col[1]*cv,col[2]*cv],[1.0,0.06,t,0.0],(i%2?0.16:-0.16));
      }
    }
    /* и четыре поверх самого полюса веером во все стороны: стык колец
       сходится ровно там, и без крышки он просвечивает */
    for(let i=0;i<4;i++){
      const a=i/4*TAU+0.35;
      const top=bodyAt(0.999,a),pt=normalAt(0.999,a);
      feaPush(out,top,vNorm([Math.cos(a)*0.50,0.30,-0.86+Math.sin(a)*0.24]),pt,
        0.215,0.150,bodyColor(0.99,a),[1.0,0.05,1.0,0.0]);
    }
  }
  /* ── РОЗЕТКА ВОКРУГ ГЛАЗА ──
     Оперение обрывалось ровным кругом, и вокруг глаза стояло гладкое пятно
     кожи с жёсткой кромкой — то самое «некрасиво вокруг глаза». У птицы там
     не срез: перья идут ОТ глаза лучами и мельчают к самому веку, а кромки
     не видно вовсе, потому что её закрывают кончики.
     Кладётся по тем же (t,a), что и весь корпус — тогда перо садится на
     поверхность и красится общим окрасом, — но направление берётся не по
     потоку, а строго от центра глаза. */
  {
    const EYES=[[-0.252,1.758,0.108],[0.252,1.758,0.108]];
    const NT=54,NA=132;
    for(let ti=0;ti<NT;ti++){
      const t=mix(0.80,0.999,ti/(NT-1));
      for(let ai=0;ai<NA;ai++){
        const a=(ai+(ti%2)*0.5)/NA*TAU+R()*0.03;
        const base=bodyAt(t,a);
        for(const ec of EYES){
          const d=Math.hypot(base[0]-ec[0],base[1]-ec[1],base[2]-ec[2]);
          if(d<0.084||d>0.152)continue;
          const p=normalAt(t,a);
          /* «от глаза» по поверхности: разность точек, из которой вычтена
             нормаль — иначе перо у самого века встаёт торчком */
          let away=vSub(base,ec);
          away=vSub(away,vMul(p,vDot(away,p)));
          if(vLen(away)<1e-5)continue;
          away=vNorm(away);
          const k=smooth(0.084,0.152,d);
          const len=mix(0.052,0.115,k)*(0.84+R()*0.32);
          const col=bodyColor(t,a);
          const cv=0.94+R()*0.12;
          feaPush(out,vAdd(base,vMul(p,-0.004)),
            vNorm(vAdd(away,vMul(p,0.16+R()*0.10))),p,
            len,len*0.62,[col[0]*cv,col[1]*cv,col[2]*cv],
            [1.0,0.05+R()*0.05,t,0.0],(ai%2?0.22:-0.22));
        }
      }
    }
  }
  return new Float32Array(out);
}

/* ── маховые, кроющие, хвост, хохол ──
   Крупные перья лежат по своим осям, и каждое видно поимённо.

   СЛОЖЕННОЕ КРЫЛО — не пучок ножей, торчащих из бока. Это слоёная лопасть:
   маховые идут от плеча назад и сходятся кончиками ЗА корнем хвоста, каждое
   следующее чуть ниже и длиннее предыдущего; поверх их основания ложатся
   второстепенные, а поверх тех — кроющие. Поэтому длина пера здесь не
   подбирается на глаз, а считается как расстояние до его кончика: только так
   веер сходится в одну точку, а не рассыпается. */
function layoutPlumes(){
  const out=[],R=rnd(0x51c3);
  const mark=(s)=>{PLUME_STAT.push(s+":"+(out.length/FEA_STRIDE));};
  for(const sx of [-1,1]){
    const flip=a=>sx>0?a:Math.PI-a;
    /* ── КРЫЛО В СВОИХ ОСЯХ ──
       Перья на крыле идут НЕ вдоль тела, а от передней кромки веером назад и
       наружу, рядами внахлёст — это видно на разметке автора. Пока ряды
       раскладывались по длине корпуса, они читались лентами вдоль бока, а не
       крылом.
       Здесь у крыла своя система: `axis` — от плеча к концу крыла, `across` —
       от передней кромки к задней. Слой за слоем ряды сдвигаются назад,
       удлиняются и разворачиваются: янтарные кроющие по кромке, за ними
       сиренево-серые, кремовая полоса, светло-голубые второстепенные и длинные
       маховые. Цвета — с листа. */
    const W0=[sx*0.20,1.30,-0.03];
    const axis=vNorm([sx*0.15,-0.24,-0.96]);
    let across=vNorm(vCross(axis,[sx,0,0]));
    if(across[1]>0)across=vMul(across,-1);
    const wnrm=vNorm(vCross(across,axis));
    /* слой: [сколько, длина, ширина, сдвиг назад, разворот назад, цвет а, цвет б] */
    /* ПЕРЬЕВ ВТРОЕ: на листе автора в каждом слое крыла перьев столько, что
       между ними не видно просвета, а у нас дюжина широких лопастей читалась
       набором ножей. Теперь перья УЖЕ (ширина слоя уменьшена) и их много —
       слой стал слоем, а не гребёнкой. Плюс шестой ряд мелких кроющих по
       самой кромке: он закрывает корни всех остальных. */
    const LAYERS=[
      [14,0.16,0.30,-0.075,0.52,BIRD_C.amber,BIRD_C.amberD],
      [22,0.26,0.26,-0.028,0.46,BIRD_C.amber,BIRD_C.amberD],
      [26,0.40,0.22,0.045,0.38,vLerp(BIRD_C.viol,BIRD_C.creamD,0.30),BIRD_C.blueD],
      [28,0.58,0.19,0.090,0.30,BIRD_C.cream,BIRD_C.creamD],
      [30,0.70,0.16,0.135,0.22,BIRD_C.blueL,BIRD_C.blue],
      [32,0.94,0.13,0.180,0.15,vLerp(BIRD_C.blueL,BIRD_C.blue,0.35),BIRD_C.blue]
    ];
    LAYERS.forEach((L,li)=>{
      const [N,len0,wk,back,turn,cA,cB]=L;
      for(let i=0;i<N;i++){
        /* шаг ряда СБИТ на случайную долю: ровная гребёнка из тридцати перьев
           читается зубчатой рейкой, а перо у соседа должно лежать чуть выше
           или ниже — тогда это оперение */
        const jit=(hashf(i*31+li*13,sx>0?3:4)-0.5)*0.9/N;
        const s=clamp(i/(N-1)+jit,0,1);
        /* вдоль крыла: у корня ряды короче, к концу длиннее */
        const len=len0*mix(0.66,1.12,s)*(0.90+hashf(i*17+li*7,sx>0?1:2)*0.20);
        const base=vAdd(vAdd(W0,vMul(axis,0.06+s*0.52)),
          vMul(across,back+s*0.05+(hashf(i*7+li*29,sx>0?5:6)-0.5)*0.016));
        /* разворот: чем ближе к корню, тем сильнее перо отведено назад */
        /* кончики маховых РАСХОДЯТСЯ: без разброса по s они сходятся в одну точку
           и крыло кончается веником */
        const dir=vNorm(vAdd(vAdd(vMul(axis,1.0),vMul(across,turn*(1.0-s*0.45))),
          vMul([sx,0,0],(s-0.5)*0.22)));
        const c=vLerp(cA,cB,0.15+s*0.55);
        feaPush(out,vAdd(base,vMul(wnrm,0.004*li)),
          vNorm(vAdd(dir,vMul(wnrm,0.05))),wnrm,
          len,len*wk,c,[0.7,0.14,mix(0.62,0.48,s),1.0],(i%2?0.10:-0.10));
      }
    });
    /* тёмная кромка по низу: без неё слоям некуда лечь */
    for(let i=0;i<9;i++){
      const s=i/8;
      const len=mix(0.66,0.94,s);
      const base=vAdd(vAdd(W0,vMul(axis,0.10+s*0.46)),vMul(across,0.235+s*0.04));
      const dir=vNorm(vAdd(axis,vMul(across,0.16)));
      feaPush(out,base,dir,wnrm,len,len*0.15,
        vLerp(BIRD_C.blueD,BIRD_C.body,0.10+s*0.30),[0.7,0.14,0.55,1.0]);
    }
    /* ШТАНЫ: перья бедра свисают на цевку. Без них нога торчит из-под груди
       голой трубкой, а на листе она прикрыта почти до пятки. */
    for(let r=0;r<2;r++)for(let i=0;i<4;i++){
      const k=i/3;
      const t=mix(0.28,0.10,k)-r*0.012;
      const a=flip(-0.50-r*0.20+k*0.34);
      const base=bodyAt(t,a),nrm=normalAt(t,a);
      const dir=vNorm([sx*0.10,-1.0,0.02+k*0.16]);
      const c=vLerp(BIRD_C.creamD,BIRD_C.blueD,0.34+r*0.30+k*0.26);
      feaPush(out,base,vNorm(vAdd(dir,vMul(nrm,0.07))),nrm,
        0.26-r*0.035,0.090,c,[1.0,0.14,t,0.0]);
    }
    /* светлая кайма по кроющим: на листе крыло отделено от корпуса тонкой
       почти белой полосой, и она же не даёт крылу слиться с хвостом.
       КАЙМА — ЭТО КАНТ, А НЕ ПЕРЬЯ. Прежде она строилась «от точки на груди
       до точки в воздухе», и длина выходила из расстояния между ними: на
       плече получалось одинокое перо в четверть птицы, лежащее поперёк белой
       груди. Именно оно и торчало на снимке. Теперь это короткие перья ВДОЛЬ
       потока по передней кромке крыла — узкая светлая полоса, как на листе. */
    for(let i=0;i<16;i++){
      const k=i/15;
      const t=mix(0.72,0.48,k);
      const a=flip(mix(0.16,-0.06,k));
      const base=bodyAt(t,a),nrm=normalAt(t,a);
      const len=mix(0.175,0.130,k)*(0.90+R()*0.20);
      feaPush(out,vAdd(base,vMul(nrm,0.008)),
        vNorm(vAdd(flowAt(t,a),vMul(nrm,0.20))),nrm,
        len,len*0.62,vLerp(BIRD_C.cream,BIRD_C.blueL,0.20+k*0.34),
        [1.0,0.12,t,0.0],(i%2?0.18:-0.18));
    }
    /* кроющие плеча: янтарный эполет, короткие ряды черепицей.
       СДВИНУТ НАЗАД, на плечо. При углах около нуля он выползал на грудь и
       читался нагрудником, а на листе породы янтарь лежит выше и позади —
       там, где крыло сходится с корпусом. */
    for(let r=0;r<3;r++)for(let i=0;i<8;i++){
      const k=i/7,t=mix(0.76,0.56,k)-r*0.014;
      const a=flip(-0.02-r*0.16+k*0.10);
      const base=bodyAt(t,a),nrm=normalAt(t,a);
      const dir=vNorm(vAdd(flowAt(t,a),vMul(nrm,0.18)));
      const c=vLerp(BIRD_C.amber,BIRD_C.amberD,0.26+r*0.20+R()*0.24);
      feaPush(out,base,dir,nrm,0.140-r*0.012,0.098-r*0.008,c,
        [1.0,0.10,t,0.0],(i%2?0.14:-0.14));
    }
  }
  mark("бока");
  /* хвост: длинный, слоёный, средняя пара длиннее всех.
     Перья слегка расходятся веером и лежат друг на друге — сложенный хвост
     это стопка, а не одна доска: первая сборка давала ровно доску. */
  /* ПЯТЬ длинных перьев вместо пятнадцати: хвост должен читаться силуэтом —
     две центральные длиннее, боковые короче и разведены */
  for(let i=0;i<5;i++){
    const k=(i/4-0.5)*2,ak=Math.abs(k);
    const a=Math.PI*1.5+k*0.58;
    const base=bodyAt(0.05,a);
    const dir=vNorm([k*0.24,-0.62-ak*0.08,-1.0]);
    /* длины соседних перьев ступенькой: ровный веер читается одной лопастью */
    /* длины вразнобой: ровный веер из пяти одинаковых перьев читается одной
       синей палкой, а на листе у хвоста видно каждое перо */
    const len=(1.70-ak*0.40)*(0.86+hashf(i*13+7,4)*0.28);
    const c=vLerp(BIRD_C.blue,(i%2)?BIRD_C.blue:BIRD_C.blueD,0.26+ak*0.46);
    /* каждое следующее перо чуть выше предыдущего: стопка, а не плоскость */
    const up=vNorm([k*0.34,1,-0.16]);
    feaPush(out,vAdd(base,vMul(up,0.006*(5-Math.abs(i-5)))),dir,up,
      len,len*0.26,c,[0.55,0.10,0.05,2.0]);
  }
  mark("хвост");
  /* хохол: длинные плюмажи широкой дугой. Цвет идёт по вееру — передние
     янтарные, средние кобальтовые, задние с фиалковым отливом: на листе
     породы хохол трёхцветный, и именно это делает его хохлом, а не гребнем. */
  for(let i=0;i<CREST_N;i++){
    const q=crestQuill(i);
    const s=q.s;
    /* трёхцветный веер: передние янтарные, средние кобальтовые, задние светло-
       голубые с фиалковым отливом. Янтарь берётся чистым — половинчатая
       подмесь в кобальт даёт терракоту, чем первая сборка и кончилась */
    /* тёплые и холодные перья ПЕРЕМЕШАНЫ по вееру, а не разложены по краям:
       пучок оранжевых спереди читается отдельным украшением, а не хохлом */
    /* цвет берётся по ХЕШУ индекса, а не по i%3: раскладка перьев теперь тоже
       идёт по i%3, и янтарные перья сошлись все в один ряд */
    const hv=hashf(i*13+5,7);
    let c=(hv<0.30)?vLerp(BIRD_C.amber,BIRD_C.amberD,0.15+s*0.5)
         :vLerp(BIRD_C.blue,BIRD_C.blueL,smooth(0.10,0.95,s));
    if(hv>0.86)c=vLerp(c,BIRD_C.viol,0.42);
    c=vLerp(c,BIRD_C.viol,smooth(0.72,1.0,s)*0.35);
    feaPush(out,q.base,q.dir,normalAt(0.96,Math.PI*1.5),q.len,q.len*0.46,
      c,[0.9,-0.26-s*0.16,1.0,3.0],(i%3-1)*0.26+((i%2)?0.12:-0.12));
  }
  mark("хохол");
  return new Float32Array(out);
}
/* ── пыль в воздухе ──
   Строится один раз: точки в объёме вокруг птицы, всё движение — в шейдере. */
function buildDust(n){
  const R=rnd(0x0d51),d=[];
  for(let i=0;i<n;i++){
    const a=R()*TAU,r=0.5+R()*2.4;
    d.push(Math.cos(a)*r,0.1+R()*2.3,Math.sin(a)*r-0.2,R());
  }
  return new Float32Array(d);
}
