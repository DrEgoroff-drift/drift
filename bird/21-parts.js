/* ══════════════ части: клюв, глаза, лапы, жёрдочка ══════════════
   Всё, что не перо. Собирается один раз в одну сетку и рисуется одним вызовом.

   КЛЮВ — главная примета попугая: короткий, высокий у основания и с крючком,
   который уходит НАЗАД под себя. Прямой конус — это не попугай, это воробей.
   Нижняя челюсть короче и тупее, она прячется в крючок.

   ЛАПЫ. Попугай зигодактиль: два пальца вперёд, два назад — и именно поэтому
   он держится за ветку, а не стоит на ней. Пальцы обнимают жёрдочку по её
   окружности, а не заканчиваются в воздухе. */

function buildParts(){
  const M=meshBox();
  const C=BIRD_C;
  /* ── клюв ──
     Первая сборка дала жёлтую пластину на щеке: клюв начинался ВНУТРИ головы
     и почти весь в ней и оставался, наружу торчало только широкое основание.
     Клюв попугая короткий, но ВЫСОКИЙ и загнутый: надклювье выходит из
     восковицы, идёт вперёд-вниз и уходит крючком назад под себя. Наружу от
     поверхности головы (z≈0.30) он выступает всего на полторы своих толщины —
     длинный клюв делает из попугая ворону. */
  /* Клюв крупнее прежнего на десятую: на листе он занимает треть головы по
     высоте, и мелкий клюв сразу превращает попугая в воробья. Цвет костяной,
     к крючку темнеет до рогового. */
  /* ── КЛЮВ ──
     ВЫДВИНУТ ВПЕРЁД. Прежний кончался на z≈0.32, а лицо птицы вместе с
     оперением выходит на 0.34–0.40 — клюв целиком тонул в голове, и наружу
     торчало одно скругление. Теперь крючок выходит за лицо примерно на
     полтора своих сечения и уходит вниз-назад, как на фотографии.
     Цвет: кость у основания, тёплый янтарь ближе к концу, тёмный рог на самом
     крючке; подклювье — короткий тёмный клин. */
  const beakCol=(v,u)=>{
    const along=vLerp(vLerp(C.beak,C.beakD,smooth(.20,.78,v)),C.beakTip,smooth(.72,1,v)*.85);
    const down=Math.max(0,-Math.sin(u*TAU));
    return vLerp(along,vLerp(C.beakD,C.beakTip,.55),down*.45);
  };
  tube(M,[
    {p:[0,1.792,0.150],r:[0.080,0.136]},
    {p:[0,1.782,0.250],r:[0.079,0.135]},
    {p:[0,1.758,0.348],r:[0.075,0.132]},
    {p:[0,1.716,0.432],r:[0.063,0.110]},
    {p:[0,1.658,0.482],r:[0.046,0.082]},
    {p:[0,1.598,0.480],r:[0.032,0.055]},
    {p:[0,1.556,0.442],r:[0.017,0.032]},
    {p:[0,1.536,0.386],r:[0.005,0.013]}
  ],18,{m:1,t:1,up:[1,0,0],col:(v,u)=>beakCol(v,u)});
  /* подклювье: короткий тёмный клин, виден снизу узкой полосой */
  tube(M,[
    {p:[0,1.676,0.150],r:[0.080,0.048]},
    {p:[0,1.666,0.256],r:[0.076,0.048]},
    {p:[0,1.652,0.356],r:[0.062,0.041]},
    {p:[0,1.642,0.428],r:[0.036,0.029]},
    {p:[0,1.638,0.462],r:[0.008,0.011]}
  ],14,{m:9,t:1,up:[1,0,0],col:(v)=>vLerp(vLerp(C.beakD,C.beakTip,.55),C.beakTip,smooth(.3,1,v)*.7)});
  /* НУТРО. Пока клюв закрыт, его не видно вовсе; стоит челюсти открыться — там
     обязана быть темнота с языком, а не дырка в модели. Зевок без нутра
     выглядит поломкой, и это первое, что замечают. */
  sphere(M,[0,1.664,0.170],0.104,10,{m:2,t:1,scale:[0.84,0.74,1.30],
    col:()=>C.mouth});
  tube(M,[
    {p:[0,1.640,0.150],r:[0.034,0.018],t:1},
    {p:[0,1.632,0.250],r:[0.030,0.016],t:1},
    {p:[0,1.626,0.330],r:[0.016,0.010],t:1}
  ],8,{m:9,t:1,up:[1,0,0],col:(v)=>vLerp(C.tongue,C.mouth,smooth(.2,1,v)*.6)});
  /* Восковицы НЕТ: на листе породы её нет, а ноздря — тёмное пятно прямо на
     роге (красится в 30-shade, геометрии не стоит). Уголок рта — точка там,
     где сходятся челюсти: без неё клюв выглядит приклеенным к лицу. */
  for(const sx of [-1,1])
    sphere(M,[sx*0.100,1.660,0.180],0.025,7,{m:2,t:1,scale:[0.7,1,1.5],
      col:()=>vLerp(C.mouth,C.eye,.5)});

  /* ── глаза ──
     Тёмная бусина с голым кольцом вокруг. Кольцо — примета попугая не меньше
     клюва: без него глаз тонет в оперении и голова делается кукольной. */
  for(const sx of [-1,1]){
    /* глаз стоит в СЕРЕДИНЕ головы по высоте: поднятый к темени, он делает
       лоб низким, а птицу — сердитой */
    const p=[sx*0.252,1.758,0.108];
    const n=vNorm([sx*0.94,0.10,0.33]);
    /* голое кольцо: у попугая оно есть, но это узкий ободок, а не пол-головы.
       0.092 давало оранжевое блюдце в треть черепа */
    /* два кольца: голое светлое снаружи и тёмный ободок вплотную к яблоку.
       Без тёмного глаз лежит на голубой коже как пуговица на пальто.
       КОЛЬЦО ШИРЕ СРЕЗА ОПЕРЕНИЯ. Перья срезались по радиусу 0.118, а кольцо
       кончалось на 0.098 — между ними оставалось голое ТЕЛО, а оно красится
       тёмной массой (материал 0). Отсюда синяя проплешина в пол-щеки и глаз,
       утопленный в яму. Теперь кольцо вылезает за срез, и перья ложатся на
       его край, как на листе породы. */
    /* УЗКИЙ ОБОДОК. Кольцо в 0.134 — это блин в треть щеки: гладкий, без
       единой складки, с ровной кромкой там, где обрывались перья. Именно его
       автор и обвёл. У попугая голая кожа вокруг глаза — узкий ободок, а не
       поле; всё остальное закрывает мелкое перо, идущее от глаза лучами
       (розетка в 22-feather). */
    disc(M,vAdd(p,vMul(n,-0.004)),n,0.098,26,{m:5,t:1,ry:0.90,
      col:(k)=>k?vLerp(C.cream,C.creamD,.62):vLerp(C.cream,C.creamD,.06)});
    /* тёмная подводка вплотную к яблоку — линия, а не лужа */
    disc(M,vAdd(p,vMul(n,0.004)),n,0.068,24,{m:5,t:1,ry:0.94,
      col:(k)=>k?vLerp(C.blueD,C.eye,.70):vLerp(C.eye,C.blueD,.20)});
    /* яблоко крупнее: на листе глаз занимает четверть головы, и мелкий глаз
       сразу делает птицу игрушечной. И ВЫНЕСЕНО вперёд: утопленное в череп,
       оно смотрит из ямы исподлобья */
    /* ── ГЛАЗ — ОДИН ШАР, ОСТАЛЬНОЕ РИСУЕТ СВЕТ ──
       Радужка и зрачок были геометрией: сперва плоскими дисками поверх шара
       (сфера пролезала сквозь них в середине, и от тёплого ободка с любого
       угла оставался месяц), потом зрачок стал куполом. Обоим приходилось
       подбирать высоту, и оба разъезжались.
       Теперь шар один и гладкий, а зрачок, волокна радужки и тёмный лимб
       красятся в 30-shade по местным координатам. Круг остаётся кругом с
       любой стороны, волокна стоят даром, и глаз мокрый — по нему идёт один
       чистый блик, а не блик на каждой детали. */
    sphere(M,vAdd(p,vMul(n,0.016)),0.058,18,{m:2,t:1,col:()=>C.iris});
    /* СКЛАДКИ НАД ГЛАЗОМ БОЛЬШЕ НЕТ ГЕОМЕТРИЕЙ.
       Это был почти чёрный полумесяц, поднятый над кожей на 22 мм — то есть
       тёмное лезвие, торчащее из брови. На снимке автора оно читалось дырой
       в голове прямо над глазом, и никакой складкой не было. Складка теперь
       рисуется по коже в 30-shade: там она тень, а не предмет. */
    /* ВЕКО. Собирается закрытым — куполом ровно по глазу — и в покое откинуто
       назад поворотом в вершинной программе (материал 8). Так закрытый глаз
       совпадает с открытым до сотой, чего подбором углов не добиться. */
    {
      const B=basisFrom(n),lid=meshBox();
      for(let i=0;i<=6;i++){
        const v=i/6;
        for(let j=0;j<14;j++){
          const th=j/14*TAU,r=0.062*Math.sin(v*Math.PI/2+0.10);
          const q=vAdd(vAdd(p,vMul(B[0],Math.cos(th)*r)),vMul(B[1],Math.sin(th)*r));
          const off=vMul(n,0.052*Math.cos(v*Math.PI/2));
          lid.add(vAdd(q,off),n,1,8,vLerp(C.blueD,C.creamD,0.30));
        }
      }
      for(let i=0;i<6;i++)for(let j=0;j<14;j++){
        const j1=(j+1)%14;
        lid.quad(i*14+j,i*14+j1,(i+1)*14+j1,(i+1)*14+j);
      }
      const off=M.n;
      for(let k=0;k<lid.v.length;k++)M.v.push(lid.v[k]);
      M.n+=lid.n;
      for(const ix of lid.i)M.i.push(ix+off);
    }
  }

  /* ── жёрдочка ──
     Ветка, а не палка: гнётся, к концам тоньше, с сучком. t=-1 — эта
     геометрия не едет с птицей ни при каком её движении.
     ЦЕНТР И РАДИУС — общие константы (PERCH_Y/PERCH_R): пальцы обнимают ветку
     по ним же. Пока числа стояли в двух местах, лапы держались за воздух
     внутри древесины, и на снимке от них оставались culьти. */
  /* волокно идёт ВДОЛЬ ветки, а не кольцами: кольца дают резьбу винта, и
     первая сборка именно винт и нарисовала */
  const wood=(v,u)=>vLerp(C.perch,vLerp(C.perch,[0.02,0.02,0.03],.55),
    .5+.5*Math.sin(u*TAU*7+hashf(Math.round(u*64),3)*6.0));
  const per=[];
  for(let i=0;i<=10;i++){
    const k=i/10,x=mix(-1.45,1.45,k);
    per.push({p:[x,PERCH_Y+Math.sin(k*Math.PI)*0.030-Math.abs(x)*0.045,PERCH_Z+Math.cos(k*3.1)*0.014],
      r:[PERCH_R*(0.60+Math.sin(k*Math.PI)*0.44),PERCH_R*(0.58+Math.sin(k*Math.PI)*0.42)],t:-1});
  }
  tube(M,per,14,{m:3,t:-1,up:[0,1,0],col:wood});
  sphere(M,[0.42,PERCH_Y+0.06,PERCH_Z+0.02],0.070,8,{m:3,t:-1,scale:[1.3,0.7,1.1],col:()=>vLerp(C.perch,[0.05,0.04,0.03],.4)});

  /* ── лапы ──
     Цевка короткая: сидящий попугай почти лежит на ветке брюхом. */
  for(const sx of [-1,1]){
    const hipX=sx*0.135;
    tube(M,[
      {p:[hipX,0.62,-0.08],r:[0.066,0.066],t:0.12},
      {p:[hipX,0.48,-0.05],r:[0.052,0.052],t:0.06},
      {p:[hipX*1.02,0.40,-0.02],r:[0.047,0.047],t:0},
      {p:[hipX*1.04,0.300,-0.015],r:[0.045,0.045],t:0}
    ],10,{m:4,t:0,up:[1,0,0],col:(v)=>vLerp(C.foot,C.footD,smooth(0,1,v)*.7)});
    /* Пальцы: длинные, с суставами, и обнимают ветку по её же радиусу. Толстые
       короткие пальцы читаются сосисками — на листе они тонкие и цепкие. */
    /* три пальца вперёд и один назад — не попугайская зигодактиль, а лапа
       существа: на листе породы она именно такая */
    const toes=[[0.88,1],[0.46,1],[0.06,1],[-1.10,-1]];
    for(const [a0,dir] of toes){
      const path=[],n=6;
      for(let i=0;i<n;i++){
        const k=i/(n-1);
        const a=a0*k*1.75;
        const rr=PERCH_R+0.020+0.024*(1-k);
        /* сустав: радиус пульсирует, а не тает ровно — палец с костяшками */
        const knuck=1+0.22*Math.sin(k*Math.PI*3.6);   /* сегменты видны отчётливее */
        path.push({p:[hipX*1.04+sx*0.014*k,
                      PERCH_Y+Math.cos(a)*rr,
                      PERCH_Z+Math.sin(a)*rr],
                   r:[(0.026-0.012*k)*knuck,(0.024-0.011*k)*knuck],t:0});
      }
      tube(M,path,8,{m:4,t:0,up:[1,0,0],col:(v)=>vLerp(C.foot,C.footD,.20+v*.65)});
      /* коготь: длиннее и темнее прежнего — на листе они заметно цепкие */
      const e=path[n-1].p,a=a0*1.75;
      const tip=[e[0],e[1]+Math.cos(a+0.62)*0.048,e[2]+Math.sin(a+0.62)*0.048];
      tube(M,[{p:e,r:[0.014,0.014],t:0},
              {p:vLerp(e,tip,.55),r:[0.009,0.009],t:0},
              {p:tip,r:[0.002,0.002],t:0}],
           7,{m:7,t:0,up:[1,0,0],col:(v)=>vLerp([0.045,0.038,0.048],[0.012,0.010,0.014],v)});
    }
  }
  /* ── усы хохла и хвостовые нити ──
     Нить сама по себе почти не видна: её работа — вести глаз к бусине и
     показывать, что бусина не приклеена к воздуху. Поэтому она тонкая, тёмная
     у корня и разогретая к концу. */
  for(let i=0;i<WHISK_N;i++)for(const sx of [-1,1]){
    const w=crestWhisk(i,sx);
    filament(M,w.a,w.ctrl,w.b,0.0225,0.0045,8,
      (s)=>vLerp(vLerp(C.blueD,C.blueL,0.35),C.glow,Math.pow(s,1.9)*0.70),1);
  }
  for(const sx of [-1,1]){
    const w=tailWhisk(sx);
    filament(M,w.a,w.ctrl,w.b,0.0210,0.0050,8,
      (s)=>vLerp(C.blueD,C.glow,Math.pow(s,2.4)*0.6),0.06);
  }
  /* ── ПРОБКИ ПОЛЮСОВ ──
     Лофт — труба, и его торцы закрываются веером треугольников (20-body). Но
     обход у этого веера легко разойтись с обходом колец, и тогда крышку
     срезает отсечение задних граней — на темени опять окно в череп. Здесь
     полюса просто затыкаются шариками: шар замкнут при любом обходе, стоит
     двадцать вершин и снимает вопрос совсем. */
  {
    const top=spineAt(1),bot=spineAt(0);
    /* пробка УТОПЛЕНА: шар радиусом с кольцо, сдвинутый внутрь на толщину
       кожи. Торчащий наружу шар виден на темени тёмной бусиной.
       ЦВЕТ БЕЗ МНОЖИТЕЛЯ. Материал 0 сам гасит альбедо втрое (30-shade) —
       умножая ещё раз на 0.30, пробка выходила почти чёрной, и на темени
       вместо дыры была видна такая же тёмная клякса. Дыру искали в геометрии,
       а она была в цвете. */
    sphere(M,vAdd(top.c,vMul(top.T,-0.026)),Math.max(top.rw,top.rf)*0.98,10,
      {m:0,t:1,col:()=>bodyColor(0.995,Math.PI*1.5)});
    sphere(M,vAdd(bot.c,vMul(bot.T,0.026)),Math.max(bot.rw,bot.rf)*0.98,10,
      {m:0,t:0.02,col:()=>bodyColor(0.02,Math.PI*1.5)});
  }
  return M.done();
}

/* ── бусины хохла ──
   Примета породы: у каждого пёрышка хохла на конце холодная светящаяся
   бусина. Они собираются отдельной сеткой, потому что рисуются ПОСЛЕ света и
   аддитивно — свет не должен их гасить (то же правило, что в игре). */
/* ── хохол ──
   С листа породы: хохол — это ДВА разных предмета, и путать их нельзя.
   Первое — длинные перья-плюмажи, отведённые назад широкой дугой. Второе —
   тонкие усы, каждый с холодной бусиной на конце; они длиннее перьев, гнутся
   сильнее и живут своей качкой. Прежняя сборка знала только первое, и хохол
   читался ирокезом из коротких листьев. */
/* жёрдочка: одни числа на ветку и на пальцы */
const PERCH_Y=0.150,PERCH_Z=-0.040,PERCH_R=0.132;
/* ── хохол ──
   СЕМЬ крупных перьев, а не два десятка игл. Двадцать длинных спиц читались
   ёжиком, в котором терялся глаз; узнаваем должен быть КОНТУР хохла, а его
   даёт несколько широких плоскостей разной длины. Три средних — длиннее
   остальных, они и держат силуэт. */
/* ── хохол ──
   Растёт ПРЯМО С ТЕМЕНИ и им же его закрывает: на макушке сечение лофта
   вырождается в точку, и всё, что туда не попало, оставляло дыру. Два ряда:
   пять длинных по средней линии от лба к затылку — они держат контур, — и
   восемь коротких кольцом вокруг полюса, которые и затыкают макушку. */
const CREST_N=13;
const CREST_LEN=[0.38,0.54,0.68,0.56,0.40, 0.24,0.29,0.26,0.31,0.25,0.30,0.28,0.23];
function crestQuill(i){
  if(i<5){
    const s=i/4;
    const t=0.998-s*0.085;
    const side=((i%2)?1:-1)*s*0.035;
    const base=vAdd(bodyAt(t,Math.PI*1.5),[side,0,0]);
    const dir=vNorm([side*7.0,mix(1.00,0.52,s),mix(-0.30,-0.92,s)]);
    return {base,dir,len:CREST_LEN[i],k:side/0.035,s};
  }
  const j=(i-5)/8;
  const ang=j*TAU+0.4;
  const base=bodyAt(0.986,ang);
  const dir=vNorm([Math.cos(ang)*0.55,0.86,-0.42+Math.sin(ang)*0.30]);
  return {base,dir,len:CREST_LEN[i],k:Math.cos(ang),s:0.5};
}
function tailWhisk(sx){
  const base=vAdd(bodyAt(0.08,Math.PI*1.5),[sx*0.055,0,0]);
  const ctrl=vAdd(base,[sx*0.34,-0.06,-0.70]);
  const end =vAdd(base,[sx*0.62,-0.62,-1.72]);
  return {a:base,ctrl,b:end};
}
/* ── усы ──
   Две пары. Толще у корня, к концу сходят на нет, одна пара уходит назад: это
   сенсоры существа, а не провода, приклеенные к птице. */
const WHISK_N=2;
const WHISK_MIX=[[1.00,0.34,0.28],[1.45,0.14,0.86]];
function crestWhisk(i,sx){
  const k=i/Math.max(1,WHISK_N-1),W=WHISK_MIX[i];
  const base=vAdd(bodyAt(0.965-k*0.060,Math.PI*1.5),[sx*(0.045+k*0.060),0,0]);
  const up=0.30*W[0],back=0.46*W[0],out=(0.048+0.100*W[1]);
  const ctrl=vAdd(base,[sx*out*0.35,up*1.30,-back*0.32]);
  const end =vAdd(base,[sx*out,up*(0.50-W[2]*1.10),-back*1.25]);
  return {a:base,ctrl,b:end};
}
function buildBeads(){
  const M=meshBox();
  /* бусина на конце уса. Материал 10.999 — та же качка, что у самого кончика:
     бусина обязана держаться за ус, а не висеть рядом с ним. */
  for(let i=0;i<WHISK_N;i++)for(const sx of [-1,1]){
    const w=crestWhisk(i,sx);
    sphere(M,w.b,0.016,8,{m:10.999,t:1,col:()=>BIRD_C.glow});
  }
  for(const sx of [-1,1]){
    const w=tailWhisk(sx);
    sphere(M,w.b,0.018,8,{m:10.999,t:0.06,col:()=>BIRD_C.glow});
  }
  return M.done();
}
