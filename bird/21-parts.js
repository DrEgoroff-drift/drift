/* ══════════════ части: клюв, глаза, лапы, жёрдочка ══════════════
   Всё, что не перо. Собирается один раз в одну сетку и рисуется одним вызовом.

   КЛЮВ — главная примета попугая: короткий, высокий у основания и с крючком,
   который уходит НАЗАД под себя. Прямой конус — это не попугай, это воробей.
   Нижняя челюсть короче и тупее, она прячется в крючок.

   ЛАПЫ. Попугай зигодактиль: два пальца вперёд, два назад — и именно поэтому
   он держится за ветку, а не стоит на ней. Пальцы обнимают жёрдочку по её
   окружности, а не заканчиваются в воздухе. */

function buildParts(){
  const M=meshBox();
  const C=BIRD_C;
  /* ── клюв ──
     Первая сборка дала жёлтую пластину на щеке: клюв начинался ВНУТРИ головы
     и почти весь в ней и оставался, наружу торчало только широкое основание.
     Клюв попугая короткий, но ВЫСОКИЙ и загнутый: надклювье выходит из
     восковицы, идёт вперёд-вниз и уходит крючком назад под себя. Наружу от
     поверхности головы (z≈0.30) он выступает всего на полторы своих толщины —
     длинный клюв делает из попугая ворону. */
  /* Клюв крупнее прежнего на десятую: на листе он занимает треть головы по
     высоте, и мелкий клюв сразу превращает попугая в воробья. Цвет костяной,
     к крючку темнеет до рогового. */
  const beakCol=(v,u)=>{
    /* градиент не только вдоль, но и ПОПЕРЁК: низ клюва темнее верха, иначе
       кость выходит плоским леденцом без объёма */
    const along=vLerp(vLerp(C.beak,C.beakD,smooth(.06,.72,v)),C.beakTip,smooth(.66,1,v)*.85);
    const down=Math.max(0,-Math.sin(u*TAU));
    return vLerp(along,vLerp(C.beakD,C.beakTip,.45),down*.42);
  };
  tube(M,[
    {p:[0,1.786,0.126],r:[0.099,0.118]},
    {p:[0,1.760,0.222],r:[0.097,0.114]},
    {p:[0,1.718,0.308],r:[0.085,0.101]},
    {p:[0,1.666,0.372],r:[0.064,0.084]},
    {p:[0,1.606,0.404],r:[0.045,0.060]},
    {p:[0,1.552,0.391],r:[0.027,0.040]},
    {p:[0,1.523,0.358],r:[0.008,0.020]}
  ],16,{m:1,t:1,up:[1,0,0],col:(v,u)=>beakCol(v,u)});
  /* подклювье: короче, тупее, шире — оно прячется в крючок надклювья */
  tube(M,[
    {p:[0,1.668,0.126],r:[0.085,0.042]},
    {p:[0,1.650,0.216],r:[0.081,0.042]},
    {p:[0,1.632,0.288],r:[0.063,0.037]},
    {p:[0,1.617,0.339],r:[0.035,0.027]},
    {p:[0,1.612,0.364],r:[0.008,0.011]}
  ],12,{m:9,t:1,up:[1,0,0],col:(v)=>vLerp(vLerp(C.beak,C.beakD,.55),C.beakTip,smooth(.3,1,v)*.7)});
  /* НУТРО. Пока клюв закрыт, его не видно вовсе; стоит челюсти открыться — там
     обязана быть темнота с языком, а не дырка в модели. Зевок без нутра
     выглядит поломкой, и это первое, что замечают. */
  sphere(M,[0,1.678,0.150],0.088,10,{m:2,t:1,scale:[0.86,0.72,1.25],
    col:()=>C.mouth});
  tube(M,[
    {p:[0,1.652,0.120],r:[0.030,0.016],t:1},
    {p:[0,1.646,0.196],r:[0.026,0.014],t:1},
    {p:[0,1.641,0.256],r:[0.014,0.009],t:1}
  ],8,{m:9,t:1,up:[1,0,0],col:(v)=>vLerp(C.tongue,C.mouth,smooth(.2,1,v)*.6)});
  /* восковица: валик у основания клюва, матовый и светлее рога */
  tube(M,[
    {p:[0,1.833,0.065],r:[0.090,0.064]},
    {p:[0,1.824,0.121],r:[0.096,0.072]},
    {p:[0,1.804,0.166],r:[0.085,0.061]}
  ],12,{m:5,t:1,up:[1,0,0],col:()=>vLerp(C.cream,C.creamD,.40)});
  /* ноздри: две тёмные точки на восковице — мелочь, которую замечают */
  for(const sx of [-1,1])
    sphere(M,[sx*0.044,1.824,0.152],0.013,6,{m:2,t:1,col:()=>[0.02,0.02,0.03]});

  /* ── глаза ──
     Тёмная бусина с голым кольцом вокруг. Кольцо — примета попугая не меньше
     клюва: без него глаз тонет в оперении и голова делается кукольной. */
  for(const sx of [-1,1]){
    const p=[sx*0.248,1.786,0.100];
    const n=vNorm([sx*0.94,0.14,0.31]);
    /* голое кольцо: у попугая оно есть, но это узкий ободок, а не пол-головы.
       0.092 давало оранжевое блюдце в треть черепа */
    /* два кольца: голое светлое снаружи и тёмный ободок вплотную к яблоку.
       Без тёмного глаз лежит на голубой коже как пуговица на пальто. */
    disc(M,vAdd(p,vMul(n,-0.012)),n,0.072,22,{m:5,t:1,ry:0.90,
      col:(k)=>k?vLerp(C.creamD,C.blueD,.62):vLerp(C.cream,C.creamD,.20)});
    disc(M,vAdd(p,vMul(n,0.002)),n,0.061,22,{m:5,t:1,ry:0.94,
      col:(k)=>k?vLerp(C.blueD,C.eye,.55):vLerp(C.eye,C.blueD,.35)});
    /* яблоко крупнее: на листе глаз занимает четверть головы, и мелкий глаз
       сразу делает птицу игрушечной */
    sphere(M,vAdd(p,vMul(n,0.024)),0.062,12,{m:2,t:1,col:()=>C.eye});
    /* радужка почти чёрная: на листе тёплого в ней ровно на догадку. Кольцо
       амбером во всю радужку читалось неоновой линзой */
    disc(M,vAdd(p,vMul(n,0.064)),n,0.046,18,{m:2,t:1,
      col:(k)=>k?vLerp(C.eye,C.amberD,.22):C.eye});
    /* ВЕКО. Собирается закрытым — куполом ровно по глазу — и в покое откинуто
       назад поворотом в вершинной программе (материал 8). Так закрытый глаз
       совпадает с открытым до сотой, чего подбором углов не добиться. */
    {
      const B=basisFrom(n),lid=meshBox();
      for(let i=0;i<=6;i++){
        const v=i/6;
        for(let j=0;j<14;j++){
          const th=j/14*TAU,r=0.062*Math.sin(v*Math.PI/2+0.10);
          const q=vAdd(vAdd(p,vMul(B[0],Math.cos(th)*r)),vMul(B[1],Math.sin(th)*r));
          const off=vMul(n,0.052*Math.cos(v*Math.PI/2));
          lid.add(vAdd(q,off),n,1,8,vLerp(C.blueD,C.creamD,0.30));
        }
      }
      for(let i=0;i<6;i++)for(let j=0;j<14;j++){
        const j1=(j+1)%14;
        lid.quad(i*14+j,i*14+j1,(i+1)*14+j1,(i+1)*14+j);
      }
      const off=M.n;
      for(let k=0;k<lid.v.length;k++)M.v.push(lid.v[k]);
      M.n+=lid.n;
      for(const ix of lid.i)M.i.push(ix+off);
    }
  }

  /* ── жёрдочка ──
     Ветка, а не палка: слегка гнётся, к концам тоньше, с одним сучком.
     t=-1 — эта геометрия не едет с птицей ни при каком её движении. */
  /* волокно идёт ВДОЛЬ ветки, а не кольцами: кольца дают резьбу винта, и
     первая сборка именно винт и нарисовала */
  const wood=(v,u)=>vLerp(C.perch,vLerp(C.perch,[0.02,0.02,0.03],.55),
    .5+.5*Math.sin(u*TAU*7+hashf(Math.round(u*64),3)*6.0));
  const per=[];
  for(let i=0;i<=10;i++){
    const k=i/10,x=mix(-1.45,1.45,k);
    per.push({p:[x,0.305+Math.sin(k*Math.PI)*0.035,-0.04+Math.cos(k*3.1)*0.012],
      r:[0.085+Math.sin(k*Math.PI)*0.022,0.082+Math.sin(k*Math.PI)*0.020],t:-1});
  }
  tube(M,per,14,{m:3,t:-1,up:[0,1,0],col:wood});
  sphere(M,[0.42,0.33,-0.02],0.055,8,{m:3,t:-1,scale:[1.3,0.7,1.1],col:()=>vLerp(C.perch,[0.05,0.04,0.03],.4)});

  /* ── лапы ──
     Цевка короткая: сидящий попугай почти лежит на ветке брюхом. */
  for(const sx of [-1,1]){
    const hipX=sx*0.135;
    tube(M,[
      {p:[hipX,0.64,-0.06],r:[0.062,0.062],t:0.12},
      {p:[hipX,0.53,-0.05],r:[0.050,0.050],t:0.06},
      {p:[hipX*1.02,0.42,-0.035],r:[0.044,0.044],t:0},
      {p:[hipX*1.04,0.368,-0.03],r:[0.042,0.042],t:0}
    ],10,{m:4,t:0,up:[1,0,0],col:(v)=>vLerp(C.foot,C.footD,smooth(0,1,v)*.7)});
    /* четыре пальца: два вперёд, два назад, все обнимают ветку */
    const toes=[[0.62,1],[0.30,1],[-0.55,-1],[-1.05,-1]];
    for(const [a0,dir] of toes){
      const path=[],n=5;
      for(let i=0;i<n;i++){
        const k=i/(n-1);
        /* палец идёт по окружности ветки: от верха вниз по её боку */
        const a=a0*k*1.55;
        const rr=0.098+0.030*(1-k);
        path.push({p:[hipX*1.04+sx*0.010*k+dir*0.0,
                      0.310+Math.cos(a)*rr,
                      -0.035+Math.sin(a)*rr],
                   r:[0.038-0.017*k,0.036-0.016*k],t:0});
      }
      tube(M,path,8,{m:4,t:0,up:[1,0,0],col:(v)=>vLerp(C.foot,C.footD,.25+v*.6)});
      /* коготь: маленький загнутый конус на конце пальца */
      const e=path[n-1].p,a=a0*1.55;
      const tip=[e[0],e[1]+Math.cos(a+0.5)*0.048,e[2]+Math.sin(a+0.5)*0.048];
      tube(M,[{p:e,r:[0.017,0.017],t:0},
              {p:vLerp(e,tip,.6),r:[0.011,0.011],t:0},
              {p:tip,r:[0.002,0.002],t:0}],
           6,{m:7,t:0,up:[1,0,0],col:()=>[0.035,0.030,0.038]});
    }
  }
  /* ── усы хохла и хвостовые нити ──
     Нить сама по себе почти не видна: её работа — вести глаз к бусине и
     показывать, что бусина не приклеена к воздуху. Поэтому она тонкая, тёмная
     у корня и разогретая к концу. */
  for(let i=0;i<WHISK_N;i++)for(const sx of [-1,1]){
    const w=crestWhisk(i,sx);
    filament(M,w.a,w.ctrl,w.b,0.0115,0.0040,6,
      (s)=>vLerp(vLerp(C.amberD,C.blueD,0.45),C.glow,Math.pow(s,2.2)*0.65),1);
  }
  for(const sx of [-1,1]){
    const w=tailWhisk(sx);
    filament(M,w.a,w.ctrl,w.b,0.0125,0.0045,6,
      (s)=>vLerp(C.blueD,C.glow,Math.pow(s,2.4)*0.6),0.06);
  }
  return M.done();
}

/* ── бусины хохла ──
   Примета породы: у каждого пёрышка хохла на конце холодная светящаяся
   бусина. Они собираются отдельной сеткой, потому что рисуются ПОСЛЕ света и
   аддитивно — свет не должен их гасить (то же правило, что в игре). */
/* ── хохол ──
   С листа породы: хохол — это ДВА разных предмета, и путать их нельзя.
   Первое — длинные перья-плюмажи, отведённые назад широкой дугой. Второе —
   тонкие усы, каждый с холодной бусиной на конце; они длиннее перьев, гнутся
   сильнее и живут своей качкой. Прежняя сборка знала только первое, и хохол
   читался ирокезом из коротких листьев. */
const CREST_N=11;
function crestQuill(i){
  const s=i/(CREST_N-1);
  /* шапкой ото лба к затылку, а не полосой по темени: на листе хохол
     начинается почти от восковицы */
  const t=0.999-s*0.135;
  const a=Math.PI*1.5;                            /* затылочная сторона */
  const side=Math.sin(s*Math.PI)*((i%3)-1)*0.072;
  const base=vAdd(bodyAt(t,a),[side,0,0]);
  /* перья идут веером: передние выше, задние сильнее отведены назад */
  const dir=vNorm([side*3.2,mix(0.98,0.40,s),mix(0.16,-0.94,s)]);
  const len=0.62-Math.abs(s-0.40)*0.26;
  return {base,dir,len,k:side/0.055,s};
}
/* хвостовые нити: пара, длиннее всех, уходят вниз-назад за хвостом */
function tailWhisk(sx){
  const base=vAdd(bodyAt(0.08,Math.PI*1.5),[sx*0.055,0,0]);
  const ctrl=vAdd(base,[sx*0.16,-0.10,-0.62]);
  const end =vAdd(base,[sx*0.30,-0.46,-1.62]);
  return {a:base,ctrl,b:end};
}
/* усы: четыре пары, всё длиннее и всё сильнее назад */
const WHISK_N=4;
function crestWhisk(i,sx){
  const k=i/(WHISK_N-1);
  const base=vAdd(bodyAt(0.985-k*0.055,Math.PI*1.5),[sx*(0.035+k*0.055),0,0]);
  /* Дуга подковой: ус поднимается, разворачивается и кончик ПРОВИСАЕТ. Первая
     сборка вела его вверх-назад по прямой — получалась антенна радара. Оттяжка
     стоит высоко и близко, конец — ниже неё. */
  const up=mix(0.62,0.86,k),back=mix(0.30,0.62,k),out=mix(0.14,0.42,k);
  const ctrl=vAdd(base,[sx*out*0.30,up*1.30,-back*0.20]);
  const end =vAdd(base,[sx*out,up*mix(0.55,0.16,k),-back*1.15]);
  return {a:base,ctrl,b:end};
}
function buildBeads(){
  const M=meshBox();
  /* бусина на конце уса. Материал 10.999 — та же качка, что у самого кончика:
     бусина обязана держаться за ус, а не висеть рядом с ним. */
  for(let i=0;i<WHISK_N;i++)for(const sx of [-1,1]){
    const w=crestWhisk(i,sx);
    sphere(M,w.b,0.024,8,{m:10.999,t:1,col:()=>BIRD_C.glow});
  }
  for(const sx of [-1,1]){
    const w=tailWhisk(sx);
    sphere(M,w.b,0.026,8,{m:10.999,t:0.06,col:()=>BIRD_C.glow});
  }
  return M.done();
}
