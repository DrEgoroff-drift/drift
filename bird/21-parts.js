/* ══════════════ части: клюв, глаза, лапы, жёрдочка ══════════════
   Всё, что не перо. Собирается один раз в одну сетку и рисуется одним вызовом.

   КЛЮВ — главная примета попугая: короткий, высокий у основания и с крючком,
   который уходит НАЗАД под себя. Прямой конус — это не попугай, это воробей.
   Нижняя челюсть короче и тупее, она прячется в крючок.

   ЛАПЫ. Попугай зигодактиль: два пальца вперёд, два назад — и именно поэтому
   он держится за ветку, а не стоит на ней. Пальцы обнимают жёрдочку по её
   окружности, а не заканчиваются в воздухе. */

function buildParts(){
  const M=meshBox();
  const C=BIRD_C;
  /* ── клюв ──
     Первая сборка дала жёлтую пластину на щеке: клюв начинался ВНУТРИ головы
     и почти весь в ней и оставался, наружу торчало только широкое основание.
     Клюв попугая короткий, но ВЫСОКИЙ и загнутый: надклювье выходит из
     восковицы, идёт вперёд-вниз и уходит крючком назад под себя. Наружу от
     поверхности головы (z≈0.30) он выступает всего на полторы своих толщины —
     длинный клюв делает из попугая ворону. */
  const beakCol=(v)=>vLerp(C.beak,C.beakD,smooth(.10,.95,v));
  tube(M,[
    {p:[0,1.781,0.130],r:[0.090,0.107]},
    {p:[0,1.757,0.220],r:[0.088,0.104]},
    {p:[0,1.719,0.298],r:[0.077,0.092]},
    {p:[0,1.672,0.355],r:[0.058,0.076]},
    {p:[0,1.618,0.384],r:[0.041,0.055]},
    {p:[0,1.569,0.372],r:[0.025,0.037]},
    {p:[0,1.543,0.342],r:[0.007,0.018]}
  ],16,{m:1,t:1,up:[1,0,0],col:(v)=>beakCol(v)});
  /* подклювье: короче, тупее, шире — оно прячется в крючок надклювья */
  tube(M,[
    {p:[0,1.671,0.130],r:[0.077,0.038]},
    {p:[0,1.654,0.213],r:[0.073,0.038]},
    {p:[0,1.637,0.280],r:[0.057,0.034]},
    {p:[0,1.623,0.327],r:[0.032,0.025]},
    {p:[0,1.618,0.350],r:[0.007,0.010]}
  ],12,{m:9,t:1,up:[1,0,0],col:(v)=>vLerp(vLerp(C.beak,C.beakD,.50),C.beakD,smooth(.2,1,v))});
  /* восковица: валик у основания клюва, матовый и светлее рога */
  tube(M,[
    {p:[0,1.833,0.065],r:[0.090,0.064]},
    {p:[0,1.824,0.121],r:[0.096,0.072]},
    {p:[0,1.804,0.166],r:[0.085,0.061]}
  ],12,{m:5,t:1,up:[1,0,0],col:()=>vLerp(C.cream,C.creamD,.40)});
  /* ноздри: две тёмные точки на восковице — мелочь, которую замечают */
  for(const sx of [-1,1])
    sphere(M,[sx*0.044,1.824,0.152],0.013,6,{m:2,t:1,col:()=>[0.02,0.02,0.03]});

  /* ── глаза ──
     Тёмная бусина с голым кольцом вокруг. Кольцо — примета попугая не меньше
     клюва: без него глаз тонет в оперении и голова делается кукольной. */
  for(const sx of [-1,1]){
    const p=[sx*0.248,1.786,0.100];
    const n=vNorm([sx*0.94,0.14,0.31]);
    /* голое кольцо: у попугая оно есть, но это узкий ободок, а не пол-головы.
       0.092 давало оранжевое блюдце в треть черепа */
    disc(M,vAdd(p,vMul(n,-0.012)),n,0.070,20,{m:5,t:1,ry:0.90,
      col:(k)=>k?vLerp(C.creamD,C.blueD,.62):vLerp(C.cream,C.creamD,.20)});
    sphere(M,vAdd(p,vMul(n,0.010)),0.054,10,{m:2,t:1,col:()=>C.eye});
    disc(M,vAdd(p,vMul(n,0.048)),n,0.032,16,{m:2,t:1,
      col:(k)=>k?vLerp(C.amberD,C.eye,.40):C.eye});
    /* ВЕКО. Собирается закрытым — куполом ровно по глазу — и в покое откинуто
       назад поворотом в вершинной программе (материал 8). Так закрытый глаз
       совпадает с открытым до сотой, чего подбором углов не добиться. */
    {
      const B=basisFrom(n),lid=meshBox();
      for(let i=0;i<=6;i++){
        const v=i/6;
        for(let j=0;j<14;j++){
          const th=j/14*TAU,r=0.062*Math.sin(v*Math.PI/2+0.10);
          const q=vAdd(vAdd(p,vMul(B[0],Math.cos(th)*r)),vMul(B[1],Math.sin(th)*r));
          const off=vMul(n,0.052*Math.cos(v*Math.PI/2));
          lid.add(vAdd(q,off),n,1,8,vLerp(C.blueD,C.creamD,0.30));
        }
      }
      for(let i=0;i<6;i++)for(let j=0;j<14;j++){
        const j1=(j+1)%14;
        lid.quad(i*14+j,i*14+j1,(i+1)*14+j1,(i+1)*14+j);
      }
      const off=M.n;
      for(let k=0;k<lid.v.length;k++)M.v.push(lid.v[k]);
      M.n+=lid.n;
      for(const ix of lid.i)M.i.push(ix+off);
    }
  }

  /* ── жёрдочка ──
     Ветка, а не палка: слегка гнётся, к концам тоньше, с одним сучком.
     t=-1 — эта геометрия не едет с птицей ни при каком её движении. */
  /* волокно идёт ВДОЛЬ ветки, а не кольцами: кольца дают резьбу винта, и
     первая сборка именно винт и нарисовала */
  const wood=(v,u)=>vLerp(C.perch,vLerp(C.perch,[0.02,0.02,0.03],.55),
    .5+.5*Math.sin(u*TAU*7+hashf(Math.round(u*64),3)*6.0));
  const per=[];
  for(let i=0;i<=10;i++){
    const k=i/10,x=mix(-1.45,1.45,k);
    per.push({p:[x,0.305+Math.sin(k*Math.PI)*0.035,-0.04+Math.cos(k*3.1)*0.012],
      r:[0.085+Math.sin(k*Math.PI)*0.022,0.082+Math.sin(k*Math.PI)*0.020],t:-1});
  }
  tube(M,per,14,{m:3,t:-1,up:[0,1,0],col:wood});
  sphere(M,[0.42,0.33,-0.02],0.055,8,{m:3,t:-1,scale:[1.3,0.7,1.1],col:()=>vLerp(C.perch,[0.05,0.04,0.03],.4)});

  /* ── лапы ──
     Цевка короткая: сидящий попугай почти лежит на ветке брюхом. */
  for(const sx of [-1,1]){
    const hipX=sx*0.135;
    tube(M,[
      {p:[hipX,0.64,-0.06],r:[0.062,0.062],t:0.12},
      {p:[hipX,0.53,-0.05],r:[0.050,0.050],t:0.06},
      {p:[hipX*1.02,0.42,-0.035],r:[0.044,0.044],t:0},
      {p:[hipX*1.04,0.368,-0.03],r:[0.042,0.042],t:0}
    ],10,{m:4,t:0,up:[1,0,0],col:(v)=>vLerp(C.foot,C.footD,smooth(0,1,v)*.7)});
    /* четыре пальца: два вперёд, два назад, все обнимают ветку */
    const toes=[[0.62,1],[0.30,1],[-0.55,-1],[-1.05,-1]];
    for(const [a0,dir] of toes){
      const path=[],n=5;
      for(let i=0;i<n;i++){
        const k=i/(n-1);
        /* палец идёт по окружности ветки: от верха вниз по её боку */
        const a=a0*k*1.55;
        const rr=0.098+0.030*(1-k);
        path.push({p:[hipX*1.04+sx*0.010*k+dir*0.0,
                      0.310+Math.cos(a)*rr,
                      -0.035+Math.sin(a)*rr],
                   r:[0.038-0.017*k,0.036-0.016*k],t:0});
      }
      tube(M,path,8,{m:4,t:0,up:[1,0,0],col:(v)=>vLerp(C.foot,C.footD,.25+v*.6)});
      /* коготь: маленький загнутый конус на конце пальца */
      const e=path[n-1].p,a=a0*1.55;
      const tip=[e[0],e[1]+Math.cos(a+0.5)*0.048,e[2]+Math.sin(a+0.5)*0.048];
      tube(M,[{p:e,r:[0.017,0.017],t:0},
              {p:vLerp(e,tip,.6),r:[0.011,0.011],t:0},
              {p:tip,r:[0.002,0.002],t:0}],
           6,{m:7,t:0,up:[1,0,0],col:()=>[0.035,0.030,0.038]});
    }
  }
  return M.done();
}

/* ── бусины хохла ──
   Примета породы: у каждого пёрышка хохла на конце холодная светящаяся
   бусина. Они собираются отдельной сеткой, потому что рисуются ПОСЛЕ света и
   аддитивно — свет не должен их гасить (то же правило, что в игре). */
const CREST_N=13;
function crestQuill(i){
  /* Хохол идёт по темени ОТ ЛБА К ЗАТЫЛКУ, а не поперёк: первая сборка ставила
     пёрышки на лоб (a=π/2 у макушки — это перёд), и над клювом получался
     светящийся рог. Здесь s=0 — переднее пёрышко у восковицы, s=1 — заднее на
     затылке; каждое отведено назад, и чем дальше, тем сильнее. */
  const s=i/(CREST_N-1);
  const t=0.995-s*0.10;
  const a=Math.PI*1.5;                            /* затылочная сторона */
  const side=Math.sin(s*Math.PI)*((i%3)-1)*0.052;   /* веер в три ручья, а не гребень */
  const base=vAdd(bodyAt(t,a),[side,0,0]);
  const dir=vNorm([side*3.4,mix(0.95,0.45,s),mix(0.10,-0.90,s)]);
  const len=(0.265-Math.abs(s-0.45)*0.13);
  return {base,dir,len,k:side/0.055};
}
function buildBeads(){
  const M=meshBox();
  for(let i=0;i<CREST_N;i++){
    const q=crestQuill(i);
    const p=vAdd(q.base,vMul(q.dir,q.len*0.93));
    sphere(M,p,0.0165,7,{m:6,t:1,col:()=>BIRD_C.glow});
  }
  return M.done();
}
