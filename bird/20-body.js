/* ══════════════ порода: тело ══════════════
   Та же птица, что в игре (src/12y): кобальт спины, кремовая грудь, янтарь на
   плече, хохол из отведённых назад пёрышек с холодной бусиной на конце. Здесь
   она в объёме, поэтому порода задаётся не рисунком, а СИЛУЭТОМ: одиннадцать
   станций вдоль хребта, у каждой ширина, вынос вперёд (грудь) и назад (спина).

   Ось: X вправо, Y вверх, Z вперёд — птица смотрит в +Z, лапы на нуле.

   ПРАВИЛО ТЕЛА (то же, что в двумерной сборке). Сперва одна масса силуэта, и
   только потом на неё кладутся перья. Тело здесь — не подложка «чтобы не
   просвечивало», а то, что читается на просвет между перьями и на кромке. */

const BIRD_C={
  body:sRGB("#101a2e"),
  blue:sRGB("#2f6fd6"), blueD:sRGB("#17417f"), blueL:sRGB("#7cbdf5"),
  cream:sRGB("#fdf7e9"), creamD:sRGB("#ddcbab"),
  amber:sRGB("#f2a03c"), amberD:sRGB("#bc6a1c"),
  viol:sRGB("#7a5ad2"),
  /* клюв не жёлтый, а костяной: на листе породы это слоновая кость с тёплой
     тенью, и именно поэтому он не спорит с янтарём хохла */
  beak:sRGB("#f4e6c6"), beakD:sRGB("#c99f66"), beakTip:sRGB("#8a6234"),
  mouth:sRGB("#4a2028"), tongue:sRGB("#96545c"),
  foot:sRGB("#b4763f"), footD:sRGB("#6f431f"),
  glow:sRGB("#6ff0ff"),
  eye:sRGB("#120b16"),
  perch:sRGB("#3a2e24")
};

/* станция: [t, y, z, ширина, вынос вперёд, вынос назад]
   Птица не шар: у сидящего попугая корпус вытянут, грудь выдаётся вперёд, а
   бока сжаты. Первая сборка дала колобок — числа середины ужаты, а хребет
   удлинён, чтобы между лапами и головой было тело, а не мяч. */
const BIRD_SPINE=[
  [0.00, 0.56,-0.66, 0.075,0.075,0.075],
  [0.10, 0.60,-0.52, 0.170,0.165,0.140],
  [0.22, 0.67,-0.32, 0.252,0.244,0.212],
  [0.35, 0.80,-0.15, 0.308,0.338,0.256],
  [0.48, 0.99,-0.05, 0.316,0.374,0.264],
  [0.60, 1.19,-0.02, 0.278,0.302,0.248],
  [0.70, 1.36,-0.06, 0.212,0.212,0.222],
  [0.78, 1.50,-0.06, 0.196,0.196,0.218],
  [0.86, 1.66,-0.01, 0.290,0.300,0.295],
  [0.94, 1.80, 0.04, 0.300,0.300,0.290],
  [1.00, 1.94, 0.02, 0.085,0.085,0.085]
];
const SP_PTS=BIRD_SPINE.map(s=>s.slice(1));   /* для сплайна: без параметра t */

/* точка хребта и его локальный базис.
   N — «перёд» сечения: у шеи это грудь, у хвоста — брюхо. Считается из
   касательной, поэтому силуэт правится одними числами таблицы. */
function spineAt(t){
  const s=catmull(SP_PTS,t);
  const e=1e-3,a=catmull(SP_PTS,clamp(t-e,0,1)),b=catmull(SP_PTS,clamp(t+e,0,1));
  const T=vNorm([0,b[0]-a[0],b[1]-a[1]]);
  const N=[0,-T[2],T[1]];
  return {c:[0,s[0],s[1]],T,N,rw:s[2],rf:s[3],rb:s[4]};
}
/* точка поверхности тела: a=0 — бок, a=+90° — грудь/брюхо, a=180° — другой бок */
function bodyAt(t,a){
  const S=spineAt(t),sa=Math.sin(a),ca=Math.cos(a);
  const r=S.rb+(S.rf-S.rb)*(.5+.5*sa);
  return [S.c[0]+ca*S.rw, S.c[1]+S.N[1]*r*sa, S.c[2]+S.N[2]*r*sa+ca*0];
}

/* ── окрас ──
   Не текстура, а функция от (t,a): пятна породы должны переживать любую
   пересборку сетки и одинаково красить и тело, и перья поверх него. */
function bodyColor(t,a){
  const belly=.5+.5*Math.sin(a);          /* 1 — грудь, 0 — спина */
  const side=Math.abs(Math.cos(a));
  let c=vLerp(BIRD_C.blueD,BIRD_C.blue,smooth(.0,.55,belly)*.8+.2);
  /* грудь и брюхо кремовые, с тёплой подпалиной к хвосту */
  /* Кромка между кремовой грудью и кобальтом спины не бывает ровной: у птицы
     она рвётся перьями. Порог сдвигается шумом по (t,a) — линейка исчезает,
     а цвет остаётся тем же. */
  const jit=(hashf(Math.round(t*90),Math.round(a*14))-0.5)*0.13;
  const cream=smooth(.50,.68,belly+jit)*smooth(.70,.58,t);
  c=vLerp(c,vLerp(BIRD_C.creamD,BIRD_C.cream,smooth(.2,.6,t)),cream);
  /* плечо: янтарный эполет по бокам корпуса */
  /* эполет — узкая капля на ПЛЕЧЕ, а не половина груди. Он требует настоящего
     бока (side) и середины по высоте: на листе оранжевого мало, и тем он там
     и хорош */
  const ep=smooth(.62,.44,Math.abs(t-.545)*7)*smooth(.52,.80,side)
          *smooth(.26,.40,belly)*smooth(.74,.56,belly);
  c=vLerp(c,BIRD_C.amber,clamp(ep,0,1)*.95);
  /* подхвостье уходит в фиолетовый — единственное холодное пятно внизу */
  c=vLerp(c,BIRD_C.viol,smooth(.14,.03,t)*.45);
  /* щека: тёплое пятно под глазом, чтобы голова не была одноцветной */
  /* щека: пятно с рваным краем, и мешается оно почти в упор — половинчатая
     подмесь янтаря в кобальт даёт сиреневый, а не тёплую щёку */
  const cj=(hashf(Math.round(t*120),Math.round(a*18))-0.5)*0.10;
  const ch=smooth(.060,.028,Math.abs(t-.872)+cj*0.35)*smooth(.68,.86,side)*smooth(.46,.32,belly);
  c=vLerp(c,BIRD_C.amber,clamp(ch,0,1));
  /* ── ЛИЦО ──
     Главная примета головы с листа породы: лоб, щёки и горло кремовые, кобальт
     лежит по темени и затылку. Без маски птица читается синим комком, и никакой
     клюв этого не спасает. Край маски рвётся тем же шумом, что и грудь. */
  const frontal=.5+.5*Math.sin(a);
  const headk=smooth(.79,.87,t);
  /* маска НЕ должна заходить на темя: там кобальт. Верхняя граница по t жёстче
     нижней, и фронтальность требуется настоящая, а не «чуть спереди» */
  const mask=headk*smooth(.52,.78,frontal+jit*0.6)*smooth(.965,.905,t);
  c=vLerp(c,vLerp(BIRD_C.cream,BIRD_C.creamD,.18),clamp(mask,0,1)*.92);
  /* бровь: тёмная дуга над глазом. Она делает взгляд, и на листе он есть */
  const brow=smooth(.042,.006,Math.abs(t-.952))*smooth(.42,.78,side)*smooth(.30,.62,frontal);
  c=vLerp(c,vLerp(BIRD_C.body,BIRD_C.blueD,.35),clamp(brow,0,1));
  /* янтарь у основания хохла: тёплая искра на затылке, как на листе */
  const nape=smooth(.045,.0,Math.abs(t-.955))*smooth(.45,.15,frontal);
  c=vLerp(c,BIRD_C.amber,clamp(nape,0,1)*.8);
  return c;
}

/* нормаль поверхности — одна на весь модуль.
   Тело и укладка перьев ОБЯЗАНЫ считать её одинаково: пока их было две,
   на голове они расходились в знаке, кожа выворачивалась наружу и
   закрывала собой всё оперение головы — птица выходила лысой. */
function bodyNormal(t,a){
  const e=0.01,d=0.05;
  const p=bodyAt(t,a);
  const du=vSub(bodyAt(clamp(t+e,0,1),a),bodyAt(clamp(t-e,0,1),a));
  const dv=vSub(bodyAt(t,a+d),bodyAt(t,a-d));
  let n=vNorm(vCross(dv,du));
  /* «наружу» меряется не от оси сечения, а от точки, отодвинутой назад по
     хребту: на темени нормаль смотрит вверх, а радиус сечения — вбок, и знак
     по радиусу там пляшет */
  const S=spineAt(t),ref=vSub(p,vSub(S.c,vMul(S.T,0.12)));
  if(vDot(n,ref)<0)n=vMul(n,-1);
  return n;
}

/* ── сетка тела ──
   Лофт по станциям: NT колец по NA точек. Нормали считаются разностями по
   сетке — надёжнее аналитики, которая на капах врёт.
   Атрибуты: pos(3) nrm(3) t(1) a(1) col(3) — по 11 чисел на вершину. */
function buildBody(NT,NA){
  const verts=new Float32Array(NT*NA*11),idx=[];
  const P=[],Nn=[];
  for(let i=0;i<NT;i++){
    const t=i/(NT-1);
    for(let j=0;j<NA;j++){
      const a=j/NA*TAU;
      P.push(bodyAt(t,a));
    }
  }
  const at=(i,j)=>P[i*NA+((j%NA)+NA)%NA];
  for(let i=0;i<NT;i++)for(let j=0;j<NA;j++){
    let n=bodyNormal(i/(NT-1),j/NA*TAU);
    if(i===0||i===NT-1){ /* на капах разность вырождается — берём осевое направление */
      const S=spineAt(i===0?0:1);
      n=vNorm(vAdd(vMul(S.T,i===0?-1:1),vMul(n,.35)));
    }
    Nn.push(n);
  }
  /* КОЖА ЛЕЖИТ НИЖЕ ОПЕРЕНИЯ. Тело строится по тем же станциям, что и укладка
     перьев, но утоплено на два сантиметра внутрь. Иначе перо лежит ровно на
     поверхности тела, глубина спорит сама с собой, и оперение проступает
     рваными пятнами — на голове так пропало всё. */
  const SKIN=0.022;
  for(let i=0;i<NT;i++)for(let j=0;j<NA;j++){
    const k=(i*NA+j)*11,p0=P[i*NA+j],n=Nn[i*NA+j],t=i/(NT-1),a=j/NA*TAU,c=bodyColor(t,a);
    const p=vSub(p0,vMul(n,SKIN));
    verts[k]=p[0];verts[k+1]=p[1];verts[k+2]=p[2];
    verts[k+3]=n[0];verts[k+4]=n[1];verts[k+5]=n[2];
    verts[k+6]=t;verts[k+7]=0;   /* материал 0: тёмная масса под перьями */
    verts[k+8]=c[0];verts[k+9]=c[1];verts[k+10]=c[2];
  }
  for(let i=0;i<NT-1;i++)for(let j=0;j<NA;j++){
    const j1=(j+1)%NA,A=i*NA+j,B=i*NA+j1,C=(i+1)*NA+j,D=(i+1)*NA+j1;
    idx.push(A,C,B, B,C,D);
  }
  return {verts,index:new Uint16Array(idx),stride:11,
          attrs:[["p",3,0],["n",3,3],["tm",2,6],["c",3,8]]};
}
